// ⭐ มติผู้ใช้ 2026-09-06: *"ตรงหน้าตั้งค่าผู้ใช้งาน ก็เอาทีมออกด้วย"* — หน้าผู้ใช้
// ดูแล "คนคนนี้เป็นใคร ทำอะไรได้" ส่วน "อยู่ทีมไหน" เป็นของทะเบียนทีม
//
// 🐞 เหตุที่ต้องมีด่าน: ก่อนหน้านี้แก้ทีมได้สองที่ และ **สองที่ตรวจคนละทะเบียน** —
// หน้าผู้ใช้ตรวจกับค่าคงที่ `TEAMS` ในโค้ด ส่วน /sa/teams ตรวจกับตาราง `teams` จริง
// (ปฏิเสธทีมที่ปิดแล้ว + โชว์จำนวนดีล/เป้าที่ค้างก่อนกด) ⇒ ทางที่หลวมกว่าทำให้คน
// ถูกจัดเข้าทีมที่ปิดไปแล้วได้โดยไม่มีอะไรฟ้อง
//
// ⚠️ เทสต์นี้อ่าน **ซอร์ส** เพราะทั้งสองไฟล์เป็นหน้า/route ที่ import มารันตรง ๆ ไม่ได้
// (client component + next/server) — ท่าเดียวกับ navMenuNames.test.mjs
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const usersPage = readFileSync(join(here, 'page.js'), 'utf8');
const teamRoute = readFileSync(join(here, '../api/users/[id]/team/route.js'), 'utf8');

test('⭐ หน้าผู้ใช้ต้องไม่มีช่องทีม และต้องไม่ส่งทีมขึ้น API', () => {
  // ช่องกรอก/ตัวเลือกทีมบนฟอร์ม
  assert.ok(!/ariaLabel="ทีมที่สังกัด"/.test(usersPage), 'ยังมีตัวเลือกทีมบนฟอร์มผู้ใช้');
  assert.ok(!/ariaLabel="ทีมหลัก"/.test(usersPage), 'ยังมีตัวเลือกทีมหลักบนฟอร์มผู้ใช้');
  // payload — คีย์ team/teams ห้ามถูกประกอบขึ้นที่นี่อีก
  assert.ok(!/resolveTeamAssignment/.test(usersPage), 'ยังประกอบ payload ทีมอยู่ที่หน้าผู้ใช้');
  assert.ok(!/teamPayload/.test(usersPage), 'ยังมี teamPayload อยู่ที่หน้าผู้ใช้');
});

/* ⚠️ คนไร้ทีมล็อกอินได้แต่ **ไม่เห็นข้อมูลอะไรเลย** และไม่มี error ให้เห็น —
   สองจุดนี้คือทั้งหมดที่กันไม่ให้บัญชีใหม่ตกหล่นเงียบ ๆ ถอดเมื่อไรต้องมีอย่างอื่นแทน */
test('⭐ ต้องเตือนคนที่ยังไม่ได้จัดเข้าทีม และพาไปหน้าจัดทีมต่อ', () => {
  assert.match(usersPage, /ยังไม่ได้จัดเข้าทีม/, 'ตารางผู้ใช้ไม่มีป้ายเตือนคนที่ยังไม่มีทีม');
  assert.match(usersPage, /สร้างบัญชีแล้ว — ยังไม่ได้จัดเข้าทีม/, 'สร้างบัญชีแล้วไม่ได้พาไปจัดทีมต่อ');
  assert.match(usersPage, /router\.push\("\/sa\/teams"\)/, 'ปุ่ม "ไปหน้าจัดทีม" ไม่ได้พาไปไหน');
});

/* 🐞 เส้นย้ายทีมไม่เคยถอนสิทธิ์เอกสารร่วมบน Drive เลย ส่วน PATCH /api/users/[id] ถอนอยู่
   ⇒ ตอนที่ยังจัดทีมได้สองทางก็ยังพอมีทางถอน · พอเหลือทางนี้ทางเดียว ถ้าไม่ถอนที่นี่
   สิทธิ์บน Drive จะบวมทางเดียวตลอดกาล (การ *ให้* เป็นอัตโนมัติทุกครั้งที่เปิดหน้า) */
test('⭐ ย้ายทีมแล้วต้องถอนสิทธิ์เอกสารร่วมบน Drive', () => {
  assert.match(teamRoute, /revokeGoogleDocAccess/, 'เส้นย้ายทีมไม่ได้ถอนสิทธิ์เอกสารร่วม');
});
