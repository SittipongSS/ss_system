import { withUser, conflict } from '@/lib/http';
import { requireService } from '@/lib/service/sitesRepo';

export const dynamic = 'force-dynamic';

const BIND_RETIRED_MESSAGE = 'ปิดทางผูกโซนของ TS แล้ว — ฝ่ายขายตั้งงานบริการที่หน้าใบสั่งขาย แล้วผู้จัดการฝ่ายขายตรวจ · ใบที่อนุมัติแล้วขึ้น ‘รอตั้งรอบ’ เอง';

export const POST = withUser(async ({ user }) => {
  const access = requireService({ user });
  if (access.response) return access.response;
  return conflict(BIND_RETIRED_MESSAGE);
});
