import { Hourglass } from "lucide-react";
import StatusBadge from "@/components/ui/StatusBadge";

/* ── ชิปอายุของงานบริการที่ยังไม่ถึง TS (มติเจ้าของ 08/10 · ตามงานค้าง) ─────────────────────────────────
   ⭐ ชิ้นเดียวทุกผิว: แถวทะเบียนใบสั่งขาย · คิวผู้จัดการ · แบนเนอร์และการ์ดรางของหน้าใบ · แท็บใบเดิมของ TS
   ⭐ ทุกอย่างมากับก้อนที่ server คิดด้วยวันไทย (ตัวตัดสิน serviceBackfillAging ของ lib/sales/serviceSetup.js ·
      คำและเกณฑ์อยู่ที่ lib/sales/serviceBackfillAging.js) — ที่นี่ไม่มีคำ ไม่มีสี ไม่มีการคิดวัน
        tone   โทนของป้าย (กลาง → เตือนเมื่อครบเกณฑ์แรก)
        strong ครบเกณฑ์ที่สอง = ไอคอนนาฬิกาทรายนำหน้า (สัญญาณที่ไม่พึ่งสี)
        title  คำบอกเมื่อชี้: งานอยู่ขั้นไหน นับจากวันไหน
   ⚠️ เกณฑ์ที่สองใช้ **ไอคอน ไม่ใช่จุดนำ** (ผลตรวจทาน 08/10): บนแท็บ TS ป้ายขั้นที่อยู่ข้างชิปมีจุดนำเสมอ และแถวที่รอไซต์ก็เป็นโทนเตือน —
      "● ยังไม่เริ่ม" กับ "● ค้าง 30 วัน" เป็นป้ายหน้าตาเดียวกันสองใบ ระดับ 30 วันจึงมองไม่ออก · ไอคอนเป็นช่องเดิมของ StatusBadge
      (`icon`) และนาฬิกาทรายคือไอคอน "รอ" ที่ระบบใช้อยู่แล้ว — ไม่มีสีหรือโทนใหม่ ไม่ใช้แดง
   ⚠️ ไม่มีป้าย (วันเดียวกับที่งานมาถึง · ไม่มีนาฬิกา · ผู้เรียกไม่ส่งวันนี้) = ไม่วาดอะไรเลย
   ⚠️ ขนาดเล็กเสมอ — ชิปนี้แทรกอยู่ในบรรทัดข้อความหรือเคียงป้ายอื่น ไม่เคยยืนเดี่ยว (ไอคอน 12px ให้พอดีความสูง 20px ของป้ายเล็ก) */
export default function ServiceAgingChip({ aging }) {
  if (!aging?.label) return null;
  return (
    <StatusBadge
      tone={aging.tone}
      icon={aging.strong ? Hourglass : undefined}
      iconSize={12}
      size="sm"
      label={aging.label}
      title={aging.title || undefined}
    />
  );
}
