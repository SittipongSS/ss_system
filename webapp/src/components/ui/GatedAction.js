"use client";
// ── ปุ่มที่ "ยังทำไม่ได้" — โชว์เสมอ แล้วบอกเหตุตอนกด ─────────────────────────
//
// ⭐ **มติผู้ใช้ 2026-08-22** — ก่อนหน้านี้หน้าดีลหน้าเดียวปฏิบัติกับ "เงื่อนไขยังไม่ครบ"
//    สามแบบพร้อมกัน:
//      · คำร้อง       — เอาข้อความมาแทนที่ปุ่ม
//      · ใบเสนอราคา   — ซ่อนปุ่มเงียบ ๆ
//      · สัญญา        — โชว์ปุ่มเสมอ บอกเหตุในโมดัล
//    ⇒ เลือกท่าของสัญญาเป็นมาตรฐาน ด้วยเหตุผลที่การ์ดสัญญาเขียนไว้เองแล้ว:
//    **"ซ่อนปุ่มเงียบ ๆ = คนถามว่าปุ่มอยู่ไหน"** · ปุ่มที่หายไปไม่ได้สอนอะไรใคร
//    ส่วนข้อความแทนที่ปุ่มก็ทำให้แถบเครื่องมือขยับตำแหน่งไปมาตามสถานะของแถว
//
// ⚠️ **`blocker` ต้องมาจากด่านตัวเดียวกับที่ server ใช้ปฏิเสธจริง** (เช่น
//    `quotationDealBlocker` ซึ่งอยู่ไฟล์เดียวกับ `eligibleQuotationDeals`) —
//    ห้ามคิดเงื่อนไขขึ้นเองตรงจุดที่วางปุ่ม ไม่งั้นวันหนึ่งปุ่มกับด่านจะพูดคนละเรื่อง
//    (กติกาเดียวกับที่ `ContractCreateModal` เขียนไว้เรื่อง `/contracts/options`)
//
// ⚠️ นี่ไม่ใช่ตัวแทนของ `disabled` — `disabled` ยังถูกต้องสำหรับ "กำลังบันทึกอยู่"
//    (สถานะชั่วคราวที่ไม่มีเหตุให้อธิบาย) · ตัวนี้มีไว้สำหรับเงื่อนไขของ *ข้อมูล*
//    ซึ่งผู้ใช้แก้ได้และต้องรู้ว่าต้องไปแก้ที่ไหน
import { useRouter } from "next/navigation";
import Button from "@/components/ui/Button";
import { notifyToast } from "@/lib/feedback";

export default function GatedAction({
  // เหตุที่ยังกดใช้งานไม่ได้ — ว่าง/null = ทำได้ตามปกติ
  blocker = "",
  // ปลายทางเมื่อทำได้ (เลือกอย่างใดอย่างหนึ่งกับ onClick)
  href = "",
  onClick,
  title = "",
  children,
  ...rest
}) {
  const router = useRouter();
  const act = (event) => {
    if (blocker) {
      // กันไม่ให้ลิงก์พาไปทั้งที่ยังไปไม่ได้ (ปุ่มยังเป็น <button> อยู่ แต่ผู้เรียก
      // อาจห่อด้วยอย่างอื่น) แล้วบอกเหตุแทน
      event?.preventDefault?.();
      notifyToast.error(blocker);
      return;
    }
    if (onClick) onClick(event);
    else if (href) router.push(href);
  };
  /* ⚠️ **เป็น `<button>` เสมอ ไม่สลับเป็น `<a>` ตอนกดได้** — สลับ element ตามสถานะ
     ทำให้คลาส/โฟกัส/เมนูคลิกขวาเปลี่ยนไปมา และเป็นที่มาของปุ่มที่หน้าตาไม่เท่ากัน
     ระหว่างสองแถวในตารางเดียวกัน · แลกกับการเสีย "เปิดในแท็บใหม่" ซึ่งปุ่ม *สร้าง*
     ไม่ได้ต้องการอยู่แล้ว (ลิงก์สำหรับ *เปิดของที่มีอยู่* ให้ใช้ `<Link>` ตามเดิม) */
  return (
    <Button type="button" onClick={act} title={blocker || title} {...rest}>
      {children}
    </Button>
  );
}
