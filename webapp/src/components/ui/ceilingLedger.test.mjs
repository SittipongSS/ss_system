import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";

/* ── ตารางเพดานในเอกสารต้องตรงกับของจริงในโค้ด (2026-09-05) ──────────────────
   `AGENTS.md` เตือนไว้เองว่า **"สถานะที่หัวไฟล์เคยเน่ามาแล้ว"** — เอกสารหลายฉบับ
   อัปเดตเนื้อในแต่ลืมแก้ตัวเลข จนเคยเขียนว่ายังไม่ลงมือทั้งที่ build เสร็จไปแล้ว
   ตารางเพดานใน UI_DESIGN_SYSTEM.md เป็นตารางที่**เน่าง่ายที่สุด**ในรีโป เพราะ
   ทุกครั้งที่มีคนรูดเพดานลง (ซึ่งด่านสองทางบังคับให้ทำ) เลขในเอกสารจะล้าทันที
   และไม่มีอะไรฟ้อง

   ⚠️ ไม่มีลิสต์ยกเว้น — เพดานทุกตัวใน audit-ui.mjs ต้องมีแถวของตัวเอง
   ทะเบียนที่ยกเว้นได้คือทะเบียนที่หมดอายุเงียบ ซึ่งรีโปนี้เจอมาสี่รอบแล้ว
   (PLUS_AFFORDANCE · catch ที่กลืน error · PREVIEW_EXEMPT · ยามพาธที่ตายแล้ว) */

const WEBAPP = process.cwd();
const AUDIT = fs.readFileSync(path.join(WEBAPP, "scripts", "audit-ui.mjs"), "utf8");
const DOC = fs.readFileSync(path.join(WEBAPP, "UI_DESIGN_SYSTEM.md"), "utf8");

/* เพดานของจริง = `const NAME_CAP = <เลข>;` ที่คอลัมน์ 0 (ไม่ใช่ตัวที่อยู่ในคอมเมนต์
   หรือในฟังก์ชัน) — รูปนี้เป็นรูปเดียวที่ audit ใช้ประกาศเพดานทุกตัว */
const caps = new Map(
  [...AUDIT.matchAll(/^const ([A-Z][A-Z0-9_]+) = (\d+);/gm)].map(([, name, value]) => [name, value]),
);

/* 🪤 อย่าผูกทะเบียนไว้กับ **ชื่อ** — `_CAP` เป็นแค่ธรรมเนียม ตั้งชื่อใหม่เป็น
   `RAW_X_LIMIT` ก็หลุดทะเบียนทันทีโดยด่านไม่ขยับ · ผูกกับ **สายที่ใช้จริง** แทน:
   เพดานคือค่าที่ถูกเอาไปเทียบสองทาง (`count > CAP` และ `count < CAP`) ในบล็อก
   failures ซึ่งเป็นสิ่งที่ทำให้มันเป็นเพดาน ไม่ใช่ตัวสะกดของชื่อ */
const compared = new Set(
  [...AUDIT.matchAll(/(\w+)\s*[<>]\s*([A-Z][A-Z0-9_]+)\b/g)].map(([, , name]) => name),
);

/* แถวในตารางเพดาน — `| \`NAME\` | 123 |` (รับคอมมาคั่นหลักด้วย เช่น 1,135) */
const rows = new Map(
  [...DOC.matchAll(/^\|\s*`([A-Z][A-Z0-9_]*_CAP)`\s*\|\s*([\d,]+)\s*\|/gm)]
    .map(([, name, value]) => [name, value.replace(/,/g, "")]),
);

test("เพดานทุกตัวในโค้ดต้องมีแถวของตัวเองในเอกสาร", () => {
  const missing = [...caps.keys()].filter((name) => !rows.has(name));
  assert.deepEqual(missing, [],
    "เพดานที่ไม่มีในตาราง = หนี้ที่คนอ่านเอกสารมองไม่เห็น\n"
    + "เพิ่มแถวในตารางเพดานของ UI_DESIGN_SYSTEM.md พร้อมเหตุผลว่าทำไมเลขยังลงไม่ได้");
});

test("แถวในเอกสารต้องไม่อ้างเพดานที่ถูกลบไปแล้ว", () => {
  const stale = [...rows.keys()].filter((name) => !caps.has(name));
  assert.deepEqual(stale, [],
    "เพดานถูกลบจาก audit-ui.mjs แล้ว (มักเพราะหนี้หมดจนกลายเป็น hard-zero) — ลบแถวออกด้วย");
});

test("ตัวเลขในเอกสารต้องตรงกับเพดานจริงทุกตัว", () => {
  const wrong = [];
  for (const [name, value] of caps) {
    if (rows.has(name) && rows.get(name) !== value) {
      wrong.push(`${name}: เอกสารเขียน ${rows.get(name)} · ของจริง ${value}`);
    }
  }
  assert.deepEqual(wrong, [],
    "ด่านสองทางบังคับให้รูดเพดานลงทุกครั้งที่หนี้ลด ⇒ เลขในเอกสารล้าได้ทุกคอมมิต\n"
    + "แก้เอกสารในคอมมิตเดียวกับที่แก้เพดาน (กฎของ AGENTS.md)");
});

/* ทางกลับของสองเทสต์แรก แต่นับจาก *การใช้งาน* ไม่ใช่จากชื่อ — ถ้าวันหนึ่งมีคนตั้ง
   เพดานใหม่โดยไม่ลงท้าย `_CAP` มันจะโผล่ที่นี่ทันที ทั้งที่สองเทสต์บนมองไม่เห็น */
test("ค่าที่ถูกใช้เป็นเพดานสองทางต้องอยู่ในทะเบียนครบ (ผูกกับการใช้ ไม่ใช่กับชื่อ)", () => {
  const orphan = [...compared].filter((name) => !rows.has(name));
  assert.deepEqual(orphan, [],
    "ค่านี้ถูกเอาไปเทียบเป็นเพดานในบล็อก failures แต่ไม่มีแถวในตารางเพดาน\n"
    + "ถ้าเปลี่ยนชื่อจนไม่ลงท้าย _CAP ทะเบียนที่ผูกกับชื่ออย่างเดียวจะมองไม่เห็น");
});

/* เพดานที่ประกาศไว้แต่ไม่มีใครเทียบ = กฎตาย (เลขค้างอยู่เฉย ๆ ไม่มีอะไรบังคับ)
   ซึ่งอ่านเหมือนมีด่านทั้งที่ไม่มี — ทรงเดียวกับยามพาธที่ตายแล้วซึ่งลบไปเมื่อ 2026-09-02 */
test("เพดานทุกตัวต้องถูกใช้เทียบจริง ไม่ใช่เลขที่ค้างอยู่เฉย ๆ", () => {
  const dead = [...caps.keys()].filter((name) => !compared.has(name));
  assert.deepEqual(dead, [],
    "ประกาศเพดานไว้แต่ไม่มี `count > CAP` / `count < CAP` ที่ไหนเลย = ด่านที่ไม่มีอยู่จริง");
});
