// ── ชิ้นที่ห้ามขาดกลางบรรทัดในร้อยแก้วของการ์ด "จัดการผลประเมิน" (S2b แก้หลังตรวจจอ head-r3-12) ──────────────
//
// 🐞 หัวหน้า UAT S2b รอบ 3 ข้อ 12 (+ ข้อ 23 · 29 · 47): การ์ดตัดบรรทัดกลางชื่อและกลางป้าย — `“เข้า / แล้ว”` · `ฝ่าย / ขาย` ·
//    `ห้อง / ประชุมชั้น 3` · `(SM / 3)` · `“ดึง / ผลกลับมาแก้”` · อ่านได้แต่สะดุด
// ⚠️ ไม่ใช่ ICU ตัดผิด (ไม่เหมือนคำทับศัพท์ของ `lib/thaiWrap.js`) — `ฝ่าย|ขาย` · `ห้อง|ประชุม|ชั้น` เป็นขอบคำจริงตามพจนานุกรม
//    แต่ชิ้นนั้นเป็น **ชื่อของสิ่งเดียว** ⇒ เป็นของข้อความชุดนี้ ไม่ใช่ของทั้งระบบ (แบบเดียวกับ `summaryKeep` ของทะเบียนหัวข้อ)
//    ตัววาดคือ `keepPhrases` ของ `ThaiText` (ห่อ `nowrap` ทั้งวลี · ตัวหนังสือไม่ถูกแตะ — ไม่มี WORD JOINER · `Ctrl+F` ยังเจอ)
// ⭐ ชิ้นมีสี่แบบ: ป้ายในเครื่องหมายคำพูด (`“…”`) · วงเล็บสั้น (`(SM 3)` · `(SM 1 · ST 2)` · `(หัวหน้ากรอกเอง)`) · ชื่อฝ่าย (`ฝ่ายขาย`) ·
//    ชื่อพื้นที่ที่ตัวตัดสินส่งมากับ `view` ⇒ บรรทัดตัดได้ที่ ` · ` และช่องว่าง **ระหว่าง** ชิ้นเท่านั้น
// 🔴 ชิ้นที่ยาวเกิน `SURVEY_CARD_UNIT_MAX` ไม่ห่อ — ของที่ตัดไม่ได้และยาวเกินกล่อง (ราง 330px · กล่องเหตุบนจอ 320) = ล้นแนวนอน
//    เช่นวงเล็บที่เป็นประโยค "(ระบบจะไม่ปิดนัดที่ยังไม่มีใครไปเป็น “เข้าแล้ว” ให้)" ตัดได้ตามปกติ แต่ `“เข้าแล้ว”` ข้างในยังเป็นชิ้น
// ⚠️ ไฟล์นี้เป็น **ตรรกะล้วน** (เทสต์ใต้ Node ได้) · ตัววาดอยู่ที่ `SurveyControlCard.js` (`keepUnits`)

/** ชิ้นยาวสุดที่ห่อไม่ให้ตัด (นับตัวอักษรรวมสระบน/ล่าง ⇒ กว้างจริงน้อยกว่านี้) — เกินนี้ปล่อยให้ตัดได้ */
export const SURVEY_CARD_UNIT_MAX = 30;

/** ชื่อที่ไม่ได้มาจากข้อมูล แต่การ์ดพิมพ์ถี่ ("ส่งผลให้ฝ่ายขาย…" · "ฝ่ายขายได้แจ้งเตือน…")
 *  🐞 UAT 26/10 (S04b mixed-blocked · head-r3-53): ป้ายท่อนของเหตุใบผสมขาดเป็น "หัวหน้าต้อง" / "ทำ: ห้องประชุมชั้น 3" — อ่านเหมือน "ทำ:" เริ่มข้อใหม่
 *     ⇒ ป้ายสองท่อน "รอช่าง:" · "หัวหน้าต้องทำ:" เป็นชิ้น
 *  🐞 UAT 26/10 (S04 doc-blocked · head-rc-r2-22): หัวการ์ดในราง 296px เหลือ "ได้" ตัวเดียวบนบรรทัดสอง ⇒ "เอกสารประเมินยังออกไม่ได้" เป็นชิ้น
 *  🐞 UAT 26/10 รอบสอง (S10 blocked · 375): เหตุแถว 17a เหลือ "แบบ" ตัวเดียวบนบรรทัดสาม ("…เป็นประเมินจาก" / "แบบ") ⇒ ชื่อวิธี "ประเมินจากแบบ" เป็นชิ้น */
export const SURVEY_CARD_UNIT_WORDS = ['ฝ่ายขาย', 'รอช่าง:', 'หัวหน้าต้องทำ:', 'เอกสารประเมินยังออกไม่ได้', 'ประเมินจากแบบ'];

const QUOTED = /“[^“”\n]+”/g;
const PAREN = /\([^()\n]+\)/g;

/**
 * ชื่อพื้นที่ที่ `view` ของการ์ด (`surveyControlView`) ถืออยู่แล้ว — ชื่อที่ร้อยแก้วของการ์ดเอ่ยถึงมาจากชุดนี้ ("เหลือ …" · "ติด n ข้อ ที่ …" ·
 * "ขาด …" · แถวพื้นที่ที่ติด · "ไปพื้นที่ที่ยังไม่ครบ: …") · การ์ดไม่คิดกติกาเอง แค่รวบรวมชื่อไปห่อ
 * ⚠️ ชื่อที่ไม่อยู่ในชุดนี้ (เช่นพื้นที่ที่พิมพ์ค้างแต่ผ่านทุกด่าน) = ตัดบรรทัดได้ตามปกติ ไม่ใช่พัง
 * @returns {string[]} ไม่ซ้ำ · ไม่มีค่าว่าง
 */
export function surveyCardUnitNames(view) {
  const names = [
    ...(Array.isArray(view?.progress?.leftNames) ? view.progress.leftNames : []),
    ...(Array.isArray(view?.zoneGaps?.rows) ? view.zoneGaps.rows.map((row) => row?.zoneName) : []),
    view?.nextZone?.name,
    ...(Array.isArray(view?.gates) ? view.gates.flatMap((gate) => (Array.isArray(gate?.zones) ? gate.zones : [])) : []),
  ];
  return [...new Set(names.filter((name) => typeof name === 'string' && name.trim()))];
}

/**
 * ชิ้นของ `text` ที่ต้องอยู่บรรทัดเดียวกัน — ส่งต่อให้ `keepPhrases(text, ชิ้น)` · ไม่มีชิ้น = `[]` (ตัววาดคืนข้อความเดิมผ่าน `thaiText`)
 * @param {string} text ร้อยแก้วหนึ่งบรรทัดของการ์ด
 * @param {string[]} names ชื่อพื้นที่ (`surveyCardUnitNames`)
 * @returns {string[]}
 */
export function surveyCardUnits(text, names = []) {
  if (typeof text !== 'string' || text.length < 2) return [];
  const found = [
    ...(text.match(QUOTED) || []),
    ...(text.match(PAREN) || []),
    ...SURVEY_CARD_UNIT_WORDS,
    ...(Array.isArray(names) ? names : []),
  ];
  return [...new Set(found.filter((unit) => typeof unit === 'string'
    && unit.trim() && unit.length <= SURVEY_CARD_UNIT_MAX && text.includes(unit)))];
}
