// 🔴 **ต้นเหตุคือคำทับศัพท์ที่พจนานุกรมไม่รู้จัก** — ไทยไม่เว้นวรรคระหว่างคำ ICU จึงต้อง
//   เดาขอบคำเอง · พอเจอคำที่ไม่มีในพจนานุกรม มันจะ **ขโมยตัวสะกดของคำหน้า** มาต่อ:
//     `ของ + ดีล`  ⇒  `ขอ | งดีล`      (ง หลุดไปอยู่กับ ดีล)
//     `จาก + ลีด`  ⇒  `จา | กลี | ด`   (ก หลุด แถม ลีด ยังขาดอีก)
//   แล้วจุดตัดบรรทัดก็ไปตกตรงรอยต่อปลอมนั้น ⇒ คนอ่านเห็นคำขาดกลาง
//   ⚠️ `Intl.Segmenter('th')` ของ Node ตอบเหมือน Chrome เป๊ะ (ICU ชุดเดียวกัน)
//      ⇒ เทสต์จับของจริงได้โดยไม่ต้องเปิดเบราว์เซอร์
//
// ⭐ **วิธีแก้ต้องใช้สองตัวคู่กัน** — วัดจริงบนเบราว์เซอร์ทีละแบบแล้ว
//   ① **ZWSP (U+200B) ขนาบนอกคำ** — บอก ICU ว่าขอบคำอยู่ตรงนี้
//        เดิม:  `มูลค่า | ขอ | งดีล | ที่ …`   ⇒ ตัดตรง "ขอ|งดีล" (ตัวสะกดถูกขโมย)
//        ใส่:   `มูลค่า | ของ | ดีล | ที่ …`   ⇒ รอยต่อกลับมาถูก
//   ② **`white-space: nowrap` ที่ตัวคำ** — ห้ามตัด *ข้างใน* คำ
//        🐞 ZWSP อย่างเดียวไม่พอ (จับได้ตอนวัดรอบสอง): `จาก+ลิสต์` รอยต่อถูกแล้ว
//           แต่เบราว์เซอร์ยังตัด `ากลิ|สต์` ได้อยู่ เพราะ ZWSP แค่ *เพิ่ม* จุดตัด
//           ไม่ได้ *ห้าม* จุดอื่น
//   ⚠️ **`nowrap` เดี่ยว ๆ ก็ไม่พอ** — วัดแล้วไม่ช่วยอะไรเลย (`ลุดจา|กลิสต` เหมือนเดิม)
//      เพราะ ICU ตัดคำข้ามขอบ element อยู่ดี ⇒ ต้องมี ZWSP บอกขอบคู่กันเสมอ
//
// 🔴 **ทำไมไม่ใช้ WORD JOINER (U+2060) คั่นตัวอักษรแทน `nowrap`** — มันได้ผลเหมือนกัน
//   แต่ไปทำลายสิ่งที่สำคัญกว่า: อักขระซ่อนอยู่ **ข้างในคำ** ⇒ `Ctrl+F` หาคำนั้นบนหน้าไม่เจอ
//   และ copy ไปวางที่อื่นได้ขยะติดไปด้วย · `nowrap` ให้ผลเท่ากันโดยตัวคำยังสะอาดเป๊ะ
//   (ทดสอบแล้วทั้งสองแบบ — เลือกแบบที่ไม่แตะตัวหนังสือ ตามกติกา "ตาเห็น = ต้องค้นเจอ")
//
// ⚠️ ไฟล์นี้เป็น **ตรรกะล้วน** (เทสต์ใน node ได้) · ตัววาดจริงอยู่ที่
//   `components/ui/ThaiText.js` ซึ่งเป็นตัวที่ใส่ `nowrap` ให้
//
// ⚠️ **ห้ามเอา ZWSP ไปฝังในสตริงต้นทาง** — มันมองไม่เห็นใน editor, ทำให้ `includes()`
//   และช่องค้นหาพัง, และหลุดลงไฟล์ export · ตัวนี้จึงเป็น **ตัวแปลงตอนแสดงผลเท่านั้น**
//   ข้อมูลกับสตริงในโค้ดยังสะอาดเหมือนเดิม
//
// ⚠️ รายการคำข้างล่างมาจาก **การวัด ไม่ใช่การเดา** — `npm run check:thaiwrap` ไล่คำ
//   ทับศัพท์ที่แอปใช้จริงผ่าน ICU แล้วบอกว่าคำไหนทำให้เกิดรอยต่อปลอม · เพิ่มคำทับศัพท์
//   ใหม่เข้าแอปเมื่อไร ด่านนั้นจะฟ้องให้มาเติมที่นี่

/** อักษรไทย (ทั้งบล็อก U+0E00–U+0E7F) — ใช้ตัดสินว่า "ติดกับคำไทยอื่นไหม" */
const THAI = /[฀-๿]/;

/** ตัวบอกขอบคำที่กว้างศูนย์ — มองไม่เห็น ไม่กินที่ ไม่เปลี่ยนความหมาย */
const ZWSP = '​';



/**
 * คำทับศัพท์ที่ ICU ตัด **คร่อมขอบคำ** เมื่ออยู่ติดคำไทยอื่น
 * (เรียงยาว→สั้น เพื่อให้คำยาวชนะตอนไล่จับ เช่น "ลิสต์" ต้องชนะก่อน "ลิ")
 * 🔴 อย่าเติมคำที่ ICU ตัดถูกอยู่แล้ว — ZWSP ที่ไม่จำเป็นคือขยะที่ติดไปกับ copy/paste
 *    (วัดแล้วว่าปลอดภัย: โน้ต · ฟอร์ม · เมนู · ไฟล์ · บิล · สเปก · ล็อก · แคช ·
 *     ดาวน์โหลด · อีเมล · เซ็น · สแกน · โควตา · แดชบอร์ด · โฟลเดอร์ · เทมเพลต)
 */
export const THAI_LOANWORDS = [
  'ออเดอร์',
  'บรีฟ',
  'ลิสต์',
  'ก๊อป',
  'เควส',
  'แท็บ',
  'ล็อต',
  'ดีล',
  'ลีด',
  'ชีต',
  // เติม 2026-09-17 พร้อมใบสเปคสินค้า FM-SA-04 — ICU ตัด `สเปกของ` เป็น `สเป|กของ`
  'สเปค',
  'สเปก',
  // เติม 2026-09-25 พร้อมจอหน้างานแบบ A (§10.5 S8) — ICU ตัด `จากม็อก` เป็น `จา|กม็|อก` และ `ม็อกทะเบียน` เป็น `ม็|อก…`
  'ม็อก',
].sort((a, b) => b.length - a.length);

/**
 * วลีไทยแท้ที่ ICU ตัด **ข้างในวลี** ผิดที่ ทั้งที่ขอบนอกของวลีถูกอยู่แล้ว — ห่อทั้งวลีด้วย `nowrap` อย่างเดียว **ไม่เติม ZWSP**
 *
 * 🐞 UAT เอกสารประเมินพื้นที่ (2026-10-08): "ดึงผลกลับมาแก้" ขึ้นบรรทัดใหม่เป็น `…ดึงผลก` / `ลับมาแก้` ทั้งในรายการ Rev และกล่องยืนยัน
 *    เพราะ ICU อ่าน `ผล + กลับ` เป็น `ผลก | ลับ` ("ผลก" กับ "ลับ" เป็นคำในพจนานุกรมทั้งคู่) — วัดด้วย `Intl.Segmenter` ได้ผลเดียวกัน
 * ⭐ ต่างจากคำทับศัพท์ข้างบน: รอยต่อปลอมอยู่ **ใน** วลี ไม่ได้คร่อมขอบ ⇒ `nowrap` รอบวลีปิดจุดตัดนั้นได้เอง และตัวหนังสือไม่ถูกแตะสักตัว
 *    (`Ctrl+F` หา "ดึงผลกลับมาแก้" ทั้งคำยังเจอ — ชื่อปุ่มของระบบ) · เทสต์ล็อกว่าขอบนอกของวลีเป็นขอบคำของ ICU จริง
 * 🔴 เติมเฉพาะวลีที่วัดแล้วว่าเพี้ยน — วลีที่ห่อ `nowrap` ตัดบรรทัดกลางวลีไม่ได้ ยิ่งยาวยิ่งเสี่ยงล้นกล่องแคบ
 */
export const THAI_KEEP_TOGETHER = ['ผลกลับ'];

/**
 * เลขที่เอกสาร/รหัสของระบบ (`SU-26100003-1` · `RQ-AS-26090186` · `SV-26090013` · `FM-TS-01`) — ห่อด้วย `nowrap` ไม่ให้ขาดที่ขีด
 * 🐞 UAT เอกสารประเมินพื้นที่ (2026-10-08): toast "… · เอกสาร SU-" / "26100003-1 ใช้ไม่ได้แล้ว" — เบราว์เซอร์ตัดบรรทัดหลังขีดได้ทุกขีด
 * ⚠️ รูปที่จับ: อักษรใหญ่ 2–4 ตัว ตามด้วย `-ท่อน` อย่างน้อยหนึ่งท่อน (ท่อน = อักษรใหญ่/ตัวเลข) · ยาวไม่เกิน `CODE_MAX`
 *    (ยาวกว่านั้นปล่อยให้ตัดได้ — ของที่ตัดไม่ได้และยาวเกินกล่อง = ล้นแนวนอน) · id แบบ `DR-fe9add35-…` (ตัวเล็ก) ไม่เข้ารูป
 */
const CODE = /[A-Z]{2,4}(?:-[A-Z0-9]+)+/y;
const CODE_MAX = 24;
const CODE_CHAR = /[A-Za-z0-9]/;

/** ชิ้นที่ต้องอยู่บรรทัดเดียวกัน ณ ตำแหน่ง `i` (วลีใน `THAI_KEEP_TOGETHER` · เลขที่เอกสาร) — ไม่มี = `null` */
function keepTogetherAt(text, i) {
  const phrase = THAI_KEEP_TOGETHER.find((w) => text.startsWith(w, i));
  if (phrase) return phrase;
  const ch = text.charCodeAt(i);
  if (ch < 65 || ch > 90) return null;
  // กลางคำหรือกลางรหัสอีกตัว = ไม่ใช่ต้นรหัส
  const before = text[i - 1] || '';
  if (before === '-' || CODE_CHAR.test(before)) return null;
  CODE.lastIndex = i;
  const code = CODE.exec(text)?.[0];
  if (!code || code.length > CODE_MAX) return null;
  // ตามด้วยตัวอักษร/ตัวเลขต่อทันที = จับได้ไม่ทั้งตัว (เช่นตัวเล็กต่อท้าย) — ไม่ห่อครึ่งรหัส
  return CODE_CHAR.test(text[i + code.length] || '') ? null : code;
}

/**
 * ซอยข้อความเป็นชิ้น ๆ — ชิ้นที่เป็นคำทับศัพท์จะถูกทำเครื่องหมาย `word: true`
 * (รวมชิ้นที่ต้องอยู่บรรทัดเดียวกันโดยไม่เติมขอบคำ: วลีใน `THAI_KEEP_TOGETHER` · เลขที่เอกสาร)
 *
 * ⚠️ ใส่ ZWSP **เฉพาะด้านที่ติดกับอักษรไทย** — คำที่มีช่องว่าง/วงเล็บ/ตัวเลขขนาบอยู่แล้ว
 *   ICU ก็เห็นขอบอยู่แล้ว ไม่ต้องเติมอะไรให้เปลืองเปล่า
 * @returns {{parts: Array<{text: string, word?: boolean}>, touched: boolean}}
 */
export function splitThai(text) {
  const parts = [];
  let plain = '';
  let i = 0;
  let touched = false;
  const flush = () => { if (plain) { parts.push({ text: plain }); plain = ''; } };
  while (i < text.length) {
    const hit = THAI_LOANWORDS.find((w) => text.startsWith(w, i));
    if (!hit) {
      const keep = keepTogetherAt(text, i);
      if (keep) {
        touched = true;
        flush();
        parts.push({ text: keep, word: true });
        i += keep.length;
        continue;
      }
      plain += text[i];
      i += 1;
      continue;
    }
    const lead = THAI.test(text[i - 1] || '') ? ZWSP : '';
    const tail = THAI.test(text[i + hit.length] || '') ? ZWSP : '';
    if (lead || tail) {
      touched = true;
      plain += lead;
      flush();
      parts.push({ text: hit, word: true });
      plain += tail;
    } else {
      plain += hit;
    }
    i += hit.length;
  }
  flush();
  return { parts, touched };
}

/**
 * ข้อความเวอร์ชัน "ใส่ขอบคำแล้ว" แบบสตริงล้วน — สำหรับด่านตรวจ/เทสต์ที่ต้องยิงเข้า
 * `Intl.Segmenter` เท่านั้น
 * 🔴 **อย่าเอาไปวาดบนจอ** — มันไม่มี `nowrap` จึงยังตัดกลางคำได้ ใช้ `thaiWrap` แทน
 */
export function thaiWrapText(text) {
  if (typeof text !== 'string' || text.length < 2) return text;
  const { parts, touched } = splitThai(text);
  return touched ? parts.map((p) => p.text).join('') : text;
}
