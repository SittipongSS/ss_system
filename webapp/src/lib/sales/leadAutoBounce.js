/* ⭐ **เกินกี่วันทำการถึงตีกลับ** (มติผู้ใช้: 5 วัน) — นับเป็น *วันทำการ* ไม่ใช่วันปฏิทิน
   ทั้งโมดูลนี้ใช้ `businessDayKey`/`countBusinessDays` อยู่แล้ว · ใช้วันปฏิทินเมื่อไร
   ลีดที่มอบวันศุกร์เย็นจะถูกลงโทษเพราะเสาร์อาทิตย์
   ⚠️ "เกิน N" ไม่ใช่ "ตั้งแต่ N" — ตรงเกณฑ์พอดียังไม่ตีกลับ (กติกาเดียวกับ
   `OVERDUE_AFTER_BY_STATUS` ของการทวง) · การทวงเกิดที่ 1–2 วัน ตัวนี้ที่ 5
   ⇒ AE ได้รับคำเตือนอย่างน้อยสามเช้าก่อนถูกดึงลีดออกจากมือ */
export const AUTO_BOUNCE_AFTER_BUSINESS_DAYS = 5;

/* หลังตีกลับอัตโนมัติครบเท่านี้รอบ **หยุดตีกลับ** แล้วส่งให้คนตัดสินใจแทน
   🪤 ไม่มีตัวนับ = วนไม่รู้จบ: cron ตีกลับ → Supervisor คัดเข้าทีมเดิม (ข้อมูลลีดยัง
   บอกอย่างเดิม) → Senior มอบให้ AE คนเดิม (คนที่ลาอยู่) → 5 วัน → ตีกลับอีก
   และทุกรอบล้าง timestamp ทิ้ง ⇒ ลีดใบนั้นจะไม่มีวันมีประวัติ SLA ที่อ่านออก */
export const AUTO_BOUNCE_MAX_ROUNDS = 2;

/* จุดเริ่มนาฬิกาของแต่ละสถานะ — ต้องตรงกับ `SINCE_OF` ของการทวง (leadNotify.js)
   ไม่งั้นระบบจะเตือนด้วยนาฬิกาหนึ่งแล้วลงโทษด้วยอีกนาฬิกาหนึ่ง
   ⚠️ **`meeting` ไม่อยู่ในลิสต์โดยเจตนา** — ใบที่ถึงขั้นนัดแล้วนับเป็นสำเร็จใน
   อัตราแปลงไปแล้ว · ตีกลับล้าง `meetingAt` ทิ้ง ⇒ ตัวเลขที่ระบบเพิ่งบันทึกว่า
   "ทำได้" จะถูกกลไกของระบบเองลบ · ใบพวกนั้นยกระดับให้ Senior ดูแทน ไม่ใช่ตีกลับ
   ⚠️ `new`/`screened` ก็ไม่อยู่ — ตีกลับใบที่อยู่คิวคัดกรองอยู่แล้วคือ no-op
   และไม่มีใครให้ดึงลีดออกจากมือ (ยังไม่ได้มอบหมาย) */
const SINCE_OF = {
  assigned: (lead) => lead?.assignedAt || lead?.createdAt || null,
  contacted: (lead) => lead?.followUpAt || null,
};

export const AUTO_BOUNCE_STATUSES = Object.keys(SINCE_OF);

/** เหตุผลที่จะถูกบันทึกในประวัติ — อ่านแล้วต้องรู้ว่าทำไมใบนี้กลับมาอยู่ตรงนี้ */
export function autoBounceReason(lead, days) {
  const what = lead?.status === 'contacted'
    ? `เลยวันติดตามที่นัดไว้ ${days} วันทำการ`
    : `ไม่มีการติดต่อลูกค้าเลย ${days} วันทำการหลังได้รับมอบหมาย`;
  return `ระบบส่งกลับคิวคัดกรองอัตโนมัติ — ${what}`;
}

/**
 * ใบไหนควรถูกตีกลับ / ใบไหนต้องให้คนตัดสิน
 *
 * @param leads   แถวจาก `sales_leads` ที่สถานะอยู่ใน `AUTO_BOUNCE_STATUSES`
 * @param ageOf   (lead) → จำนวนวันทำการนับจากจุดเริ่มของสถานะนั้น
 *                (ผู้เรียกส่งมาเพื่อไม่ต้องผูกกับตาราง holidays — ท่าเดียวกับ
 *                `overdueLeadNotices`)
 * @param roundOf (leadId) → เคยถูกตีกลับอัตโนมัติมาแล้วกี่รอบ
 * @returns {{ bounce: Array, escalate: Array }}
 *   `bounce`   = ตีกลับได้เลย
 *   `escalate` = ครบโควตารอบแล้ว **ห้ามตีกลับซ้ำ** ส่งให้ผู้ดูแลตัดสินใจแทน
 */
export function planAutoBounce(leads = [], { ageOf, roundOf = () => 0 } = {}) {
  const bounce = [];
  const escalate = [];
  for (const lead of leads || []) {
    const since = SINCE_OF[lead?.status]?.(lead);
    /* ⚠️ ไม่มีจุดเริ่มนาฬิกา = **ไม่แตะ** — ใบ `contacted` ที่ยังไม่มี `followUpAt`
       คือใบเก่าก่อน mig 0288 ซึ่งไม่มีใครเคยรับปากวันไหนไว้กับลูกค้า
       ตีกลับด้วยกำหนดที่เดาเอาเองไม่ได้ · ใบพวกนี้จะเข้าเกณฑ์เองเมื่อ AE กดบันทึก
       การติดต่อครั้งถัดไป (ซึ่งบังคับกรอกวันติดตามอยู่แล้ว) */
    if (!since) continue;
    const days = ageOf(lead);
    if (!(days > AUTO_BOUNCE_AFTER_BUSINESS_DAYS)) continue;
    const rounds = roundOf(lead.id) || 0;
    (rounds >= AUTO_BOUNCE_MAX_ROUNDS ? escalate : bounce).push({ lead, days, rounds });
  }
  /* เรียงค้างนานสุดขึ้นก่อน — ถ้ารอบนั้นทำไม่ครบ (timeout/ลิมิต) ใบที่แย่ที่สุด
     ต้องได้ถูกจัดการก่อน ไม่ใช่ใบที่บังเอิญมาก่อนใน query */
  const worstFirst = (a, b) => b.days - a.days;
  return { bounce: bounce.sort(worstFirst), escalate: escalate.sort(worstFirst) };
}

/** เหลืออีกกี่วันทำการก่อนระบบจะส่งกลับ — สำหรับบอกบนหน้าใบ ไม่ใช่สำหรับตัดสินใจตีกลับ
 *
 *  ⚠️ ตัวตัดสินจริงคือ `planAutoBounce` (`days > AUTO_BOUNCE_AFTER_BUSINESS_DAYS`)
 *  ที่นี่ต้องกลับสมการตัวเดียวกันเป๊ะ ไม่งั้นหน้าจอนับถอยหลังคนละวันกับที่ระบบลงมือ:
 *  ตีกลับเมื่อ days ≥ N+1 ⇒ เหลือ = (N+1) − days · ถึง 0 เมื่อไรคือเข้าเกณฑ์แล้ว
 *  (ยังไม่ตีกลับจนกว่า cron รอบถัดไปจะทำงาน — ข้อความบนจอต้องไม่สัญญาว่า "ตีกลับแล้ว")
 *
 *  @param days จำนวนวันทำการนับจากวันที่นัดติดตามไว้ · `null` = ไม่มีนาฬิกา
 */
export function autoBounceCountdown(days) {
  if (days == null) return null;
  return Math.max(0, AUTO_BOUNCE_AFTER_BUSINESS_DAYS + 1 - days);
}

/** ข้อความแจ้งเตือนของใบที่ครบโควตารอบแล้ว — ต้องบอกว่าให้ทำอะไรต่อ ไม่ใช่แค่รายงาน */
export function escalationNotice(entries = []) {
  if (!entries.length) return null;
  const names = entries.slice(0, 3).map((e) => e.lead?.contactName).filter(Boolean);
  const rest = entries.length - names.length;
  return {
    title: `ลีดวนอยู่ในคิว ${entries.length} ใบ — ต้องตัดสินใจ`,
    body: `${names.join(' · ')}${rest > 0 ? ` และอีก ${rest}` : ''}`
      + ` — ถูกส่งกลับอัตโนมัติครบ ${AUTO_BOUNCE_MAX_ROUNDS} รอบแล้ว`
      + ' ระบบจะไม่ส่งกลับซ้ำอีก · ย้ายทีม มอบคนใหม่ หรือปิดลีด',
  };
}
