// ── ตั้งลูกค้าให้ "ดีลที่ยังไม่มีลูกค้า" จากจุดที่ติด ────────────────────────
//
// ⭐ **มติผู้ใช้ 2026-08-24** — การเปิดดีลไม่บังคับลูกค้า (`deals` POST เขียน
//    `customerId: body.customerId || null`) แต่ใบเสนอราคาบังคับ ⇒ prod มีดีล 82 ใบ
//    ที่ยังเปิดอยู่และไม่มีลูกค้า ในนั้น 17 ใบไปถึงขั้นเสนอราคาแล้ว · เดิมทางแก้มีทางเดียว
//    คือออกจากฟอร์ม ไปหน้าดีล เติมลูกค้า แล้วกลับมาเริ่มใหม่ — อาการเดียวกับด่านโครงการ
//    ที่เพิ่งถอดไป ต่างกันตรงที่ **ด่านลูกค้าถอดไม่ได้** เพราะใบใช้ค่านั้นจริง (ชื่อ/ที่อยู่/
//    เลขผู้เสียภาษีบนเอกสาร · ราคาเฉพาะลูกค้า) ⇒ แก้ด้วยการ "เติมให้ได้จากตรงนั้น" แทน
//
// ⚠️ **เติมได้เฉพาะช่องที่ว่าง — ห้ามเปลี่ยนลูกค้าที่มีอยู่แล้ว** ลูกค้าของดีลคือรากของ
//    ทั้งสาย (ใบเสนอราคา · ใบสั่งขาย · คำร้อง · โครงการ อ่านต่อกันมา) การสลับตัวจึงเป็น
//    คนละเรื่องกับการเติมช่องว่าง และต้องทำที่หน้าดีลซึ่งเห็นของที่ค้างอยู่ทั้งหมด
//
// ⚠️ กติกา "ลูกค้าใช้ออกเอกสารได้ไหม" ต้องตรงกับตัวกรองของ `GET /api/customers`
//    (อนุมัติแล้ว + ไม่ถูกพักใช้) — ที่นั่นกรองให้ตัวเลือกบนจอ ที่นี่กันคนยิงตรงเข้า API

import { customerNameIn } from '@/lib/master/customerName';

/** ลูกค้ารายนี้ใช้ออกเอกสารได้ไหม — legacy NULL ถือว่าอนุมัติ/ใช้งานอยู่ (ก่อน mig 0027/0030) */
export function isQuotableCustomer(customer) {
  if (!customer?.id) return false;
  const approval = customer.approvalStatus;
  if (approval && approval !== 'approved') return false;
  return customer.isActive !== false;
}

/** ดีลใบนี้ยังรอเติมลูกค้าอยู่ไหม */
export function dealAwaitsCustomer(deal) {
  return Boolean(deal) && !deal.customerId;
}

/**
 * เหตุที่ตั้งลูกค้ารายนี้ให้ดีลไม่ได้ — คืน `null` เมื่อตั้งได้
 * ใช้ทั้งฝั่งจอ (กันเสนอตัวเลือกที่กดแล้วโดนตีกลับ) และฝั่ง server (ด่านจริง)
 */
export function dealCustomerAdoptError(deal, customer) {
  if (!deal) return 'ไม่พบดีล';
  if (!dealAwaitsCustomer(deal)) {
    return 'ดีลนี้มีลูกค้าอยู่แล้ว — เปลี่ยนลูกค้าต้องทำที่หน้าดีล';
  }
  if (!customer?.id) return 'ไม่พบลูกค้าที่เลือก';
  if (!isQuotableCustomer(customer)) {
    return 'ลูกค้ารายนี้ยังใช้ออกเอกสารไม่ได้ (รออนุมัติ หรือถูกพักใช้)';
  }
  return null;
}

/** ข้อความบอกผลลัพธ์ล่วงหน้า — ฟอร์มขึ้นก่อนกดบันทึก, audit ใช้ตอนบันทึกแล้ว */
export function dealCustomerAdoptNote(deal, customer) {
  if (!dealAwaitsCustomer(deal) || !customer?.id) return '';
  // จุดวาด ⇒ ลูกค้าที่มีแต่ชื่ออังกฤษต้องได้ชื่อ ไม่ใช่ UUID กลางประโยค
  const who = customerNameIn(customer) || customer.id;
  return `ดีลนี้ยังไม่มีลูกค้า — บันทึกใบนี้จะตั้งลูกค้าเป็น ${who} ให้ดีลด้วย`;
}

/* ── เปลี่ยน/ล้างลูกค้าของดีล (ฟอร์มแก้ไขดีล) ───────────────────────────────
   ⭐ **มติผู้ใช้ 2026-08-24 (รอบสอง)** — ตรวจโค้ดแล้วพบว่า `PATCH deals/[id]` รับ
   `customerId` ดิบ ๆ เข้าคอลัมน์เลย ไม่ตรวจอะไรสักอย่าง ⇒ เดินอ้อมด่านของ
   `link-project` ได้ทั้งชุด · prod หลุดจริงแล้ว 1 ใบ (DL-26080193: ดีลเป็นของ
   "หจก. สยามสวิสส" แต่ผูกโครงการของ "บจก. สยามสวิสส สีลม" และมีใบเสนอราคาแล้ว 2 ใบ)

   ⚠️ **เติมช่องว่าง ≠ เปลี่ยนตัว** — เติมคือให้ข้อมูลที่ยังไม่เคยมี (ปลอดภัย)
   ส่วนเปลี่ยนคือย้ายรากของทั้งสายไปอยู่ใต้ลูกค้าคนใหม่ ขณะที่เอกสารที่ออกไปแล้ว
   **ตรึงลูกค้าเดิมไว้โดยเจตนา** (หลักฐานการค้า) ⇒ ดีลกับเอกสารของมันจะเถียงกันถาวร
   จึงยอมให้เปลี่ยนเฉพาะตอนที่ยังไม่มีอะไรงอกจากดีลใบนั้น

   ⚠️ **ล้างเป็นค่าว่างได้แม้ผูกโครงการอยู่** — ตรงกับ `hasCompatibleProjectCustomer`
   ที่ยอมให้ดีลไร้ลูกค้าอยู่ในโครงการได้ · เส้นทางออกจากทางตันคือ ล้างลูกค้า →
   ย้ายโครงการ → ตั้งลูกค้าใหม่ ปิดกั้นตรงนี้เมื่อไรคือทำให้ดีลที่ผูกผิดแก้ไม่ได้เลย */

/** สรุปของที่งอกจากดีลแล้ว — ตัวเลขไว้บอกผู้ใช้ว่าติดอะไรอยู่กี่ใบ */
export function dealAttachmentSummary(counts = {}) {
  const parts = [
    ['ใบเสนอราคา', counts.quotations],
    ['ใบสั่งขาย', counts.salesOrders],
    ['คำร้อง', counts.requests],
  ].filter(([, n]) => Number(n) > 0).map(([label, n]) => `${label} ${n}`);
  return parts.join(' · ');
}

/**
 * ด่านเดียวของ "ลูกค้าของดีลเปลี่ยนได้ไหม" — ใช้ที่ `PATCH deals/[id]`
 * `customer` = แถวลูกค้าปลายทาง (null = ล้างค่า) · `project` = โครงการที่ดีลผูกอยู่
 * `counts` = จำนวนเอกสารที่ผูกดีล · `isWon` = ดีลปิด Won แล้ว
 */
export function dealCustomerPatchError({
  deal, customer = null, requestedId = null, project = null, counts = {}, isWon = false,
} = {}) {
  if (!deal) return 'ไม่พบดีล';
  const current = String(deal.customerId || '');
  const wanted = String(requestedId ?? customer?.id ?? '');
  /* 🐞 **ขอ id ที่ไม่มีในทะเบียน ≠ ขอล้างค่า** — ผู้เรียกโหลดแถวลูกค้ามาให้ ถ้าหาไม่เจอ
     จะได้ `customer = null` ซึ่งหน้าตาเหมือน "ล้างค่า" เป๊ะ ⇒ ยิง id มั่ว ๆ มาแล้ว
     ลูกค้าของดีลหายเงียบ · จึงต้องรับ `requestedId` มาแยกสองเคสนี้ออกจากกัน */
  if (wanted && !customer?.id) return 'ไม่พบลูกค้าที่เลือก';
  const next = String(customer?.id || '');
  if (current === next) return null;               // ไม่ได้เปลี่ยนอะไร

  // ดีลที่ปิดแล้วคือหลักฐาน ไม่ใช่ร่าง — ยอดจริงถูกผูกกับลูกค้ารายนี้ไปแล้ว
  if (isWon) return 'ดีลปิด Won แล้ว — เปลี่ยนลูกค้าไม่ได้ (ยอดจริงและเอกสารผูกกับลูกค้ารายเดิมไปแล้ว)';

  if (next) {
    if (!isQuotableCustomer(customer)) return 'ลูกค้ารายนี้ยังใช้ออกเอกสารไม่ได้ (รออนุมัติ หรือถูกพักใช้)';
    // ⚠️ กติกาเดียวกับ hasCompatibleProjectCustomer ของ link-project — ห้ามให้ดีลกับ
    // โครงการเป็นคนละลูกค้า ไม่ว่าจะเข้ามาทางไหน
    if (project?.customerId && String(project.customerId) !== next) {
      const who = project.customerName || project.customerId;
      const code = project.code || project.id;
      return `โครงการ ${code} เป็นของ ${who} — ย้ายดีลไปโครงการของลูกค้าใหม่ก่อน หรือเลือกลูกค้าให้ตรงกับโครงการ`;
    }
  }

  // เปลี่ยน/ล้าง "ลูกค้าที่มีอยู่แล้ว" = ต้องยังไม่มีอะไรงอกจากดีลใบนี้
  const attached = current ? dealAttachmentSummary(counts) : '';
  if (attached) {
    return `ดีลนี้มีเอกสารผูกอยู่แล้ว (${attached}) — เปลี่ยนลูกค้าไม่ได้ ถ้าผูกผิดรายให้ลบเอกสารพวกนั้นก่อน หรือเปิดดีลใหม่ให้ลูกค้าที่ถูกต้อง`;
  }
  return null;
}
