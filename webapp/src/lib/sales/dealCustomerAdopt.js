// ⭐ **มติผู้ใช้ 2026-08-24** — การเปิดดีลไม่บังคับลูกค้า (`deals` POST เขียน
//    `customerId: body.customerId || null`) แต่ใบเสนอราคาบังคับ ⇒ prod มีดีล 82 ใบ
//    ที่ยังเปิดอยู่และไม่มีลูกค้า ในนั้น 17 ใบไปถึงขั้นเสนอราคาแล้ว · เดิมทางแก้มีทางเดียว
//    คือออกจากฟอร์ม ไปหน้าดีล เติมลูกค้า แล้วกลับมาเริ่มใหม่ — อาการเดียวกับด่านโครงการ
//    ที่เพิ่งถอดไป ต่างกันตรงที่ **ด่านลูกค้าถอดไม่ได้** เพราะใบใช้ค่านั้นจริง (ชื่อ/ที่อยู่/
//    เลขผู้เสียภาษีบนเอกสาร · ราคาเฉพาะลูกค้า) ⇒ แก้ด้วยการ "เติมให้ได้จากตรงนั้น" แทน
//
// ⚠️ **เติมได้เฉพาะช่องที่ว่าง — ห้ามเปลี่ยนลูกค้าที่มีอยู่แล้ว** ลูกค้าของดีลคือรากของ
//    ทั้งสาย (ใบเสนอราคา · ใบสั่งขาย · คำร้อง · โครงการ อ่านต่อกันมา) การสลับตัวจึงเป็น
//    คนละเรื่องกับการเติมช่องว่าง และต้องทำที่หน้าดีลซึ่งเห็นของที่ค้างอยู่ทั้งหมด
//
// ⚠️ กติกา "ลูกค้าใช้ออกเอกสารได้ไหม" ต้องตรงกับตัวกรองของ `GET /api/customers`
//    (อนุมัติแล้ว + ไม่ถูกพักใช้) — ที่นั่นกรองให้ตัวเลือกบนจอ ที่นี่กันคนยิงตรงเข้า API

/** ลูกค้ารายนี้ใช้ออกเอกสารได้ไหม — legacy NULL ถือว่าอนุมัติ/ใช้งานอยู่ (ก่อน mig 0027/0030) */
export function isQuotableCustomer(customer) {
  if (!customer?.id) return false;
  const approval = customer.approvalStatus;
  if (approval && approval !== 'approved') return false;
  return customer.isActive !== false;
}

/** ดีลใบนี้ยังรอเติมลูกค้าอยู่ไหม */
export function dealAwaitsCustomer(deal) {
  return Boolean(deal) && !deal.customerId;
}

/**
 * เหตุที่ตั้งลูกค้ารายนี้ให้ดีลไม่ได้ — คืน `null` เมื่อตั้งได้
 * ใช้ทั้งฝั่งจอ (กันเสนอตัวเลือกที่กดแล้วโดนตีกลับ) และฝั่ง server (ด่านจริง)
 */
export function dealCustomerAdoptError(deal, customer) {
  if (!deal) return 'ไม่พบดีล';
  if (!dealAwaitsCustomer(deal)) {
    return 'ดีลนี้มีลูกค้าอยู่แล้ว — เปลี่ยนลูกค้าต้องทำที่หน้าดีล';
  }
  if (!customer?.id) return 'ไม่พบลูกค้าที่เลือก';
  if (!isQuotableCustomer(customer)) {
    return 'ลูกค้ารายนี้ยังใช้ออกเอกสารไม่ได้ (รออนุมัติ หรือถูกพักใช้)';
  }
  return null;
}

/** ข้อความบอกผลลัพธ์ล่วงหน้า — ฟอร์มขึ้นก่อนกดบันทึก, audit ใช้ตอนบันทึกแล้ว */
export function dealCustomerAdoptNote(deal, customer) {
  if (!dealAwaitsCustomer(deal) || !customer?.id) return '';
  const who = customer.name || customer.id;
  return `ดีลนี้ยังไม่มีลูกค้า — บันทึกใบนี้จะตั้งลูกค้าเป็น ${who} ให้ดีลด้วย`;
}
