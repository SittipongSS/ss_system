// = ~160 ครั้ง แทน ~640

/** ถี่สุด — ใช้ตอนเพิ่งมีความเคลื่อนไหว (เท่าค่าเดิมก่อนมีการถอยจังหวะ) */
export const THREAD_POLL_FAST_MS = 45_000;

/**
 * รอบถัดไปควรห่างเท่าไร เมื่อดึงติดกันมาแล้ว `quietRounds` รอบโดยไม่เจอของใหม่
 *
 * ฟังก์ชันล้วน — เทสต์พฤติกรรมได้ตรง ๆ (โปรเจกต์นี้ไม่มี test runner ฝั่ง React)
 *
 * ⚠️ ขั้นแรกต้องกินเวลา "พอให้บทสนทนาที่กำลังเดินอยู่ไม่สะดุด" — 4 รอบแรก = 3 นาที
 * ของการเงียบสนิท ซึ่งนานกว่าจังหวะพิมพ์ตอบกันปกติ
 */
export function threadPollDelay(quietRounds) {
  if (quietRounds < 4) return THREAD_POLL_FAST_MS;   // ≤3 นาทีแรกที่เงียบ — ยังถือว่ากำลังคุยกันอยู่
  if (quietRounds < 8) return 90_000;                // เงียบต่ออีก ~6 นาที
  return 180_000;                                    // เพดาน — เปิดค้างทั้งวันก็ 20 ครั้ง/ชม.
}

/**
 * ลายเซ็นของเธรด ณ ตอนนี้ — เปลี่ยนเมื่อมีข้อความเข้า/ออก
 *
 * ⚠️ ต้องนับ **จำนวน** ด้วย ไม่ใช่ดูแค่ id ตัวท้าย — ลบข้อความกลางเธรดทิ้งแล้ว
 * id ตัวท้ายยังเท่าเดิม ถ้าดูแค่นั้นจะนับว่า "เงียบ" ทั้งที่เธรดเปลี่ยนไปแล้ว
 */
export function threadSignature(items) {
  const rows = Array.isArray(items) ? items : [];
  return `${rows.length}:${rows[rows.length - 1]?.id || '-'}`;
}
