"use client";
// ── "คำตอบที่มาถึงยังเป็นของตัวกรองปัจจุบันอยู่ไหม" — คำตอบเดียวที่ทุกหน้าใช้ ──
//
// 🐞 **บั๊กจริง (ตรวจระบบ 2026-08-25):** หน้ารายการที่มีตัวกรองยิงโหลดใหม่ทุกครั้งที่
// ตัวกรองขยับ แต่ไม่มีหน้าไหนกันคำตอบที่มาผิดลำดับเลยสักหน้า — ไม่มี `AbortController`
// ไม่มีเลขลำดับ · `fetch` ไม่ได้การันตีว่าคำขอที่ยิงก่อนจะตอบก่อน
//
// อาการที่เกิด: เลื่อนช่วงวันที่ในคิวลีดสามที (ยิง 3 รอบซ้อน) รอบแรกตอบช้าสุด
// **มันจึงเป็นตัวที่เขียนทับสุดท้าย** ⇒ ตัวเลขบนจอเป็นของช่วงที่ผู้ใช้เลื่อนผ่านไปแล้ว
// ไม่มี error ไม่มีอะไรบอก · หน้าดีลเปลี่ยนเดือนรัว ๆ ได้ดีลผิดเดือนแบบเดียวกัน
//
// ⚠️ **แย่กว่า "ข้อมูลเก่า" หนึ่งขั้น** — ข้อมูลเก่ายังพอเดาได้ว่าเก่า แต่อันนี้หน้าตา
// เหมือนของจริงทุกประการ และคิวคำร้องถึงขั้นมีป้ายขอบเขตมายืนยันความผิดให้ด้วย
// (`setActiveScope` อ่านจากเฮดเดอร์ของคำตอบ ⇒ ป้ายกับแถวหลุดจากกันได้)
//
// ⚠️ **ทำไมไม่ใช้ `AbortController`** — abort ทำให้ `fetch` โยน `AbortError` ซึ่งจะไป
// โผล่ใน `catch` ของทุกหน้าเป็น "โหลดข้อมูลไม่สำเร็จ" ทั้งที่ไม่มีอะไรพัง ต้องไล่เขียน
// ตัวกรอง error เพิ่มทุกหน้า · เลขลำดับทิ้งคำตอบเงียบ ๆ ตรงจุดที่จะ setState พอดี
// (คำขอที่บินอยู่ก็ปล่อยให้จบไป — มันตอบมาแล้วเราแค่ไม่ใช้)

/** สร้างตัวนับรอบหนึ่งชุด — หนึ่งชุดต่อหนึ่ง "รายการ" ที่โหลดซ้ำได้ */
export function createLatestRun() {
  let seq = 0;
  /** เริ่มรอบใหม่ → คืนฟังก์ชันถามว่า "รอบของฉันยังเป็นรอบล่าสุดอยู่ไหม" */
  return function startRun() {
    const mine = ++seq;
    return () => mine === seq;
  };
}
