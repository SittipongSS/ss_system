// การประกอบ/แยกค่า datetime ของ DateTimeInput — แยกออกมาเป็นฟังก์ชันบริสุทธิ์เพราะ
// repo ยังไม่มีตัวเรนเดอร์ React ในเทสต์ ตรรกะที่ทำข้อมูลหายได้ต้องเทสต์ได้โดยไม่ต้อง mount
//
// รูปค่าที่เก็บ: "" หรือ "YYYY-MM-DDTHH:mm" (วินาทีถ้ามีมาจากหลังบ้านจะไม่ถูกตัด)

/** แยกค่าที่เก็บออกเป็นส่วนวันที่และเวลา — ไม่ตัดวินาที เพื่อไม่ทำข้อมูลเดิมเพี้ยน */
export function splitDateTime(value) {
  const [date = "", time = ""] = String(value || "").split("T");
  return { date, time };
}

/**
 * ผู้ใช้แก้ส่วนใดส่วนหนึ่ง → คืนค่าที่เก็บได้ พร้อม "เวลาที่ต้องจำไว้"
 *
 * ⚠️ ไม่มีวันที่ = ประกอบ ISO ไม่ได้ แต่ห้ามทิ้งเวลาที่ผู้ใช้พิมพ์ ต้องคืนไปให้ component
 * เก็บไว้ใน state แล้วเอามาใช้ตอนได้วันที่ ไม่งั้นเกิดสองอาการ (ของจริงก่อนแก้):
 *   1. ช่องเวลายังโชว์ 10:15 ที่พิมพ์ไว้ ขณะที่ฟอร์มเก็บค่าว่าง = เห็นค่าหนึ่งบันทึกอีกค่า
 *   2. พอเลือกวันที่ทีหลัง ได้ T00:00 — เวลาที่พิมพ์หายไปเงียบ ๆ
 */
export function resolveDateTimeEdit(nextDate, nextTime) {
  if (!nextDate) return { value: "", pendingTime: nextTime || "" };
  return { value: `${nextDate}T${nextTime || "00:00"}`, pendingTime: "" };
}
