/* กลับขึ้นหัวของส่วนที่เพิ่งเปลี่ยนเนื้อหา — ใช้ตอนกดเปลี่ยนหน้าในตาราง (`Pager`)
   และตอนสลับแท็บ (`Tabs`)
 *
 * ทำไมต้องมี: ปุ่มเปลี่ยนหน้าอยู่ **ท้ายตาราง** พอกดแล้วแถวชุดใหม่ขึ้นมาแทนที่
 * แถวแรกจะอยู่เหนือขอบบนของจอ คนอ่านต้องไถขึ้นเองทุกครั้งถึงจะเห็นว่าหน้าใหม่มีอะไร
 * แท็บก็เหมือนกัน — สลับแท็บตอนไถอยู่กลางหน้าแล้วเนื้อหาใหม่เริ่มเหนือจอ
 *
 * ⚠️ เลื่อน **ขึ้นอย่างเดียว** — ถ้าหัวส่วนยังอยู่ในจอ (เช่นกดเปลี่ยนแท็บตอนอยู่บนสุด)
 * ห้ามเลื่อน ไม่งั้นการกดปุ่มจะดันจอลงมาเองโดยไม่มีใครขอ
 * ⚠️ ระยะเผื่อแถบเมนูสองชั้นที่ตรึงบนสุดมาจาก `scroll-margin-top` ของตัว element
 * (ตั้งไว้ใน globals.css) ไม่ใช่เลขในไฟล์นี้ — `scrollIntoView` เคารพค่านั้นให้เอง
 * และเราอ่านค่าเดียวกันกลับมาใช้เทียบว่า "ยังอยู่ในจอไหม"
 */
export function scrollToTopOf(element) {
  if (!element || typeof window === "undefined") return;

  /* 🪤 ต้องรอให้ React วาดเนื้อหาชุดใหม่ก่อนค่อยเลื่อน (rAF สองชั้น = หลัง commit +
     หลัง layout รอบถัดไป) ไม่งั้นวัดตำแหน่งจากผังหน้าเก่าที่กำลังจะหายไป
     🪤 และต้องเป็น `behavior: "auto"` ไม่ใช่ smooth — เนื้อหาชุดใหม่มักสั้นกว่าเดิม
     พอหน้าสั้นลงระหว่างแอนิเมชัน เบราว์เซอร์จะบีบ scroll ลงมาที่ก้นหน้าแล้วทิ้ง
     แอนิเมชันค้างกลางทาง (วัดจริง 2026-08-13: สลับแท็บแล้วไปค้างที่ 329px แทนที่จะ
     เป็น 138px ที่ถูกต้อง) การกระโดดทันทีไม่มีช่วงกลางให้ค้าง */
  /* ⚠️ ใช้ setTimeout ไม่ใช่ requestAnimationFrame — rAF **ไม่ทำงานเลย** เมื่อแท็บของ
     เบราว์เซอร์ถูกซ่อน (วัดจริง 2026-08-13 บนพรีวิว: `document.visibilityState`
     เป็น "hidden" แล้ว rAF ไม่ยิงสักครั้ง) การเลื่อนจะเงียบหายไปทั้งกรณี
     React commit ของ event แบบคลิกเป็น synchronous อยู่แล้ว งานใน timeout จึงได้เห็น
     ผังหน้าใหม่แน่นอน */
  setTimeout(() => {
    const margin = Number.parseFloat(window.getComputedStyle(element).scrollMarginTop) || 0;
    if (element.getBoundingClientRect().top >= margin) return;
    element.scrollIntoView({ block: "start", behavior: "auto" });
  }, 0);
}

/* หา "ส่วน" ที่ควรเลื่อนไปหา: กล่องที่ผู้เรียกทำเครื่องหมายไว้ก่อน แล้วค่อยถอยมาที่
   การ์ดส่วนกลาง (`.ui-section`) — ถ้าไม่เจอเลยคืน null แล้วไม่ต้องเลื่อน ดีกว่าเดา
   ไปกระโดดที่ <body> ซึ่งพาไปสุดหน้าแทนที่จะเป็นหัวตาราง */
export function closestScrollSection(element) {
  return element?.closest("[data-scroll-top], .ui-section") || null;
}
