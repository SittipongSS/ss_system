"use client";
// ── "ควรดึงของใหม่ตอนกลับมามองแท็บไหม" — คำตอบเดียวที่ทั้งระบบใช้ ──────────
//
// 🐞 **อาการที่ผู้ใช้รายงาน (2026-08-25):** *"ต้อง F5 ถึงจะดึงข้อมูล"*
// ผลตรวจ: ทั้งระบบไม่มีสัญญาณดึงข้อมูลใหม่เลยนอกจาก **ตอน mount** กับ **ตอนบันทึกสำเร็จ**
// (`grep visibilitychange` ทั้ง src/ = 0 แมตช์) ⇒ แท็บที่เปิดค้างไว้ = ข้อมูลแช่แข็ง
// ถาวร · เปลี่ยนหน้าผ่านเมนูดึงใหม่อยู่แล้ว (client component remount) ปัญหาจึงอยู่ที่
// "แท็บค้าง" ล้วน ๆ ไม่ใช่ "เดินเมนู"
//
// ⚠️ **เลือกจังหวะ "กลับมามอง" ไม่ใช่ interval ทุกหน้า** โดยเจตนา:
//   · interval ทุกหน้า = ทุกแท็บที่เปิดทิ้งไว้เผา invocation ทั้งวันแม้จอมืด ซึ่งขัดกับ
//     จุดยืนต้นทุนที่เขียนไว้เองใน `NotificationBell.js`
//   · Supabase Realtime ทำไม่ได้ในสภาพปัจจุบัน — DB ไม่มี RLS policy สิทธิ์อยู่ในโค้ด
//     ล้วน และเบราว์เซอร์ถือ anon key ⇒ subscribe แล้วได้อย่างเดียวคือไม่เห็นอะไรเลย
//     หรือเห็นทุกแถวของทุกทีม
//   ⇒ ต้นทุนตอนแท็บซ่อน = 0 request · จ่ายเฉพาะตอนมีคนกำลังดูจริง

/** ห่างจากรอบก่อนน้อยกว่านี้ = ยังสดพอ ไม่ต้องยิงใหม่ (คนสลับแท็บถี่ ๆ ต้องไม่ยิงรัว) */
export const DEFAULT_MIN_GAP_MS = 30_000;

/**
 * ตัดสินว่ารอบนี้ควรยิงไหม — แยกออกมาเป็นฟังก์ชันล้วนเพื่อให้เทสต์พฤติกรรมได้จริง
 * (โปรเจกต์นี้ไม่มี test runner ฝั่ง React)
 *
 * @param visibility ค่า `document.visibilityState` ณ ตอนนั้น
 * @param lastAt     เวลาที่ดึงล่าสุด (ms)
 * @param now        เวลาปัจจุบัน (ms)
 * @param minGapMs   ระยะห่างขั้นต่ำ
 */
export function shouldRevalidate(visibility, lastAt, now, minGapMs = DEFAULT_MIN_GAP_MS) {
  // แท็บซ่อนอยู่ = ไม่มีใครดู ⇒ ไม่ยิง (นี่คือทั้งหมดของการประหยัด)
  if (visibility !== "visible") return false;
  // ⚠️ `visibilitychange` กับ `focus` เด้งพร้อมกันตอนสลับแท็บกลับมา — คอกกั้นนี้คือสิ่ง
  // เดียวที่กันไม่ให้กลายเป็นยิงสองรอบทุกครั้ง
  return now - lastAt >= minGapMs;
}
