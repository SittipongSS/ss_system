export function kindsForDept(dept) {
  if (!REQUEST_DEPTS.includes(dept)) return [];
  const list = REQUEST_KIND_LIST.filter((k) => {
    if (REQUEST_KINDS[k].legacy) return false;
    const fixed = REQUEST_KINDS[k].dept;
    return !fixed || fixed === dept;
  });
  // 🐞 **เรียงให้ตระกูลติดกันก่อนคืน** — `Select` ขึ้นหัวกลุ่มเมื่อกลุ่มของแถวต่างจาก
  // แถวก่อนหน้า ⇒ ลิสต์ที่ตระกูลไม่ติดกันทำให้ **หัวกลุ่มเดิมโผล่ซ้ำ** · ของจริงบนจอ
  // ตอน PR #1003: ฝ่าย RD ได้ "ทั่วไป(สอบถามข้อมูล) → งานพัฒนา → ขอราคา →
  // ทั่วไป(ขอเอกสาร)" · เรียงที่นี่ไม่ใช่ที่ฟอร์ม เพราะลิสต์นี้เป็นของ API ด้วย
  // และสองที่ต้องเห็นลำดับเดียวกัน
  //
  // ⚠️ ลำดับ *ของตระกูล* — ตัวที่ประกาศไว้ใน `FAMILY_ORDER` มาก่อนตามลำดับนั้น
  // ที่เหลือตามลำดับที่เจอครั้งแรกในทะเบียน ⇒ ฝ่ายที่เพิ่มหัวข้อใหม่ยังไม่ต้องมา
  // ลงทะเบียนตระกูลของตัวเองที่นี่ แต่ตระกูลที่ผู้ใช้สั่งลำดับไว้แล้วจะไม่สลับเอง
  const seen = [];
  for (const k of list) {
    const family = requestKindFamily(k);
    if (!seen.includes(family)) seen.push(family);
  }
  const order = [
    ...FAMILY_ORDER.filter((f) => seen.includes(f)),
    ...seen.filter((f) => !FAMILY_ORDER.includes(f)),
  ];
  return list.slice().sort(
    (a, b) => order.indexOf(requestKindFamily(a)) - order.indexOf(requestKindFamily(b)),
  );
}

// เปิดใบใหม่ด้วยหัวข้อนี้ได้ไหม — ด่านฝั่ง server (ฟอร์มกรองแล้ว แต่ยิงตรงยังได้)
export function legacyKindError(kind) {
  if (!REQUEST_KINDS[kind]?.legacy) return null;
  return `"${requestKindLabel(kind)}" เลิกใช้แล้ว — เปิดใบใหม่ด้วยหัวข้อปัจจุบันแทน`;
}

// ฝ่ายที่ส่งมาต้องเข้ากับชนิด — คืนข้อความไทย หรือ null ถ้าผ่าน
//
// ⚠️ ชนิดที่ล็อกฝ่ายไว้ **ไม่ override เงียบ ๆ** อีกแล้ว: ก่อนหน้านี้ `deptForRequest`
// ทิ้งค่าที่ client ส่งมาโดยไม่บอกใคร ซึ่งเคยพอสำหรับตอนที่ฟอร์มไม่ให้เลือกฝ่าย —
// แต่ตอนนี้ผู้ใช้ *เห็นและเลือกฝ่ายเอง* ถ้าเลือกแล้วระบบเงียบ ๆ ส่งไปฝ่ายอื่น
// คนขอจะรอคำตอบจากฝ่ายที่ไม่เคยได้รับเรื่อง
export function requestDeptError(kind, dept) {
  if (!isRequestKind(kind)) return 'ชนิดคำร้องไม่ถูกต้อง';
  if (!REQUEST_DEPTS.includes(dept)) return 'ต้องระบุฝ่ายที่ต้องการให้ตอบ';
  const fixed = REQUEST_KINDS[kind].dept;
  if (fixed && fixed !== dept) {
    return `"${requestKindLabel(kind)}" เป็นงานของฝ่าย ${fixed} ส่งถึงฝ่าย ${dept} ไม่ได้`;
  }
  return null;
}

/* scope เลขที่ของแต่ละหัวข้อ — **อ่านจากทะเบียนอย่างเดียว ไม่มีค่าเดา**
   RQ- (สอบถามข้อมูล + ติดตามของเข้า) · SB- (พัฒนากลิ่น) · FD- (พัฒนาสูตร) ·
   DC- (ขอเอกสาร RD) · DF- (ขอเอกสารการเงิน FN)

   ⭐ **RQ- เหลือของสอบถาม** (มติผู้ใช้ 2026-08-18) — เดิมสี่หัวข้อใช้ร่วมกันจนเปิดคิว
   มาแล้วแยกไม่ออกว่าใบไหนเป็นงานแบบไหน · ติดตามของเข้า (PC) ยังเป็น RQ- ผู้ใช้ยังไม่สั่งแยก

   🐞 **เดิมมีค่าเดา `dept === 'PC' ? 'PM' : 'RM'`** (ซากจากยุคคำร้องขอราคาวัสดุ —
   RM = เนื้อสาร · PM = บรรจุภัณฑ์) · หัวข้อที่ใช้ค่านั้นถูกถอดไปแล้ว และทุกหัวข้อที่
   เหลือประกาศ `scope` ครบ ⇒ กิ่งนั้นไม่มีทางถูกเรียก แต่ยัง **กลืนความผิดพลาด**:
   หัวข้อใหม่ที่ลืมประกาศ scope จะได้ `RM-` เงียบ ๆ แล้วเลขที่ออกไปแก้ไม่ได้อีก
   (`docNo` ล็อกด้วย trigger) ⇒ ถอดค่าเดาทิ้ง แล้วบังคับ `scope` ที่ `kinds/registry.js`
   ตั้งแต่ตอนโหลดทะเบียนแทน (มติผู้ใช้ 2026-08-18)
   ⚠️ `dept` ยังรับไว้ในลายเซ็นเพราะผู้เรียกส่งมาอยู่แล้ว และ scope รายฝ่ายอาจกลับมา
   ตอนมีโมดูลจัดซื้อ — แต่ห้ามเอาค่าเดากลับมา */
export function requestDocScope(kind) {
  return REQUEST_KINDS[kind]?.scope || null;
}

// ── ด่านตรวจตอนสร้าง — คืนข้อความไทย หรือ null ถ้าผ่าน ──────────────────
// ⚠️ กฎขึ้นกับ "ชนิด" ทั้งหมด จึงตรวจที่นี่ที่เดียว ไม่ใช่กระจายใน handler
export function requestShapeError(kind, body = {}) {
  if (!isRequestKind(kind)) return 'ชนิดคำร้องไม่ถูกต้อง';
  const meta = REQUEST_KINDS[kind];

  // ── ของที่หัวข้อนี้ต้องอ้างถึง (มติผู้ใช้ 2026-08-03 รอบสอง) ────────────
  // ถามก่อนทุกข้อเพราะอยู่ต้นฟอร์ม — ตีกลับเรื่องท้าย ๆ ก่อนทั้งที่ข้อแรกยังไม่ครบ
  // ทำให้ผู้ใช้ไล่แก้ผิดที่ · ลำดับตามที่ประกาศใน needs = ลำดับที่ฟอร์มถาม
  //
  // ⚠️ `projectId` ของหัวข้อที่ต้องมีดีล **ไม่ต้องรับจาก client ก็ได้** — POST ดึงจาก
  // แถวดีลเสมอ · ที่ตรวจตรงนี้คือ "ผู้ใช้เลือกครบหรือยัง" ฝั่งจอ ส่วนความถูกต้องของ
  // ความสัมพันธ์ (ดีลนี้อยู่โครงการนั้นจริงไหม / SO ใบนี้ของดีลไหน) เป็นด่านของ
  // handler ที่มองเห็นแถวจริง
  for (const ref of meta.needs || []) {
    const spec = REQUEST_NEEDS[ref];
    if (!spec) continue;
    if (body[spec.field]) continue;
    // ของที่ server เติมจากแถวอื่น — ถามหา **ต้นทาง** แทน · ต้นทางมาแล้วถือว่าผ่าน
    // ที่นี่ แล้วไปตกที่ handler ถ้าแถวต้นทางไม่มีค่านั้นจริง (ข้อความละเอียดกว่า:
    // "ดีลนี้ยังไม่ผูกโครงการ" ไม่ใช่ "ต้องเลือกโครงการ" ซึ่งไม่มีช่องให้เลือก)
    if (spec.derivedFrom) {
      if (body[spec.derivedFrom]) continue;
      // 🐞 ต้นทางก็ยังว่าง — เดิมตกมาคืน error ของ **ปลายทาง** ⇒ ฟอร์มเปล่าของ
      // พัฒนาสูตร/ขอเอกสาร/สอบถามข้อมูล ขึ้น "ต้องเลือกโครงการ" ทั้งที่ช่อง
      // โครงการเป็นช่องอ่านอย่างเดียว ("เติมจากดีลที่เลือก") — สั่งให้ทำสิ่งที่
      // หน้าจอไม่มีให้ทำ ซึ่งเป็นอาการเดียวกับที่คอมเมนต์ข้างบนบอกว่าปิดไปแล้ว
      // แต่ปิดแค่ครึ่งเดียว (ครึ่งที่ "เลือกดีลแล้วแต่ดีลไม่มีโครงการ")
      // ⇒ ต้องบอกสิ่งที่ผู้ใช้กดได้จริง: เลือกดีลก่อน
      // ⚠️ `derivedFrom` เก็บชื่อ **ฟิลด์ใน body** (`dealId`) ไม่ใช่ชื่อ ref (`deal`)
      // — ค้นจาก field ตรง ๆ อย่าใช้ REQUEST_NEEDS[spec.derivedFrom]
      const source = Object.values(REQUEST_NEEDS).find((n) => n.field === spec.derivedFrom);
      return source?.error || spec.error;
    }
    return spec.error;
  }

  // ⭐ **ยอดที่ขอวางบิล** (B-2 · ม-ค) — อยู่ตรงนี้เพราะเป็นช่องของแท็บ "งาน"
  // เหมือนของที่ต้องอ้างข้างบน · ถามชื่อเรื่องก่อนแล้วค่อยถามยอด = ส่งผู้ใช้ไปแก้ผิดแท็บ
  // ⚠️ ตรวจแค่ "มีหรือยัง" — ความสัมพันธ์กับยอดของใบ (เกินไหม · % เท่าไร) ตรวจที่
  // handler ด้วย `resolveBillAmount` ซึ่งเห็นยอดจริงของแถว ไม่ใช่ค่าที่ client แนบมา
  if (meta.needs?.includes('quotation') && !(Number(body.billAmount) > 0)) {
    return 'ต้องระบุยอดที่ขอวางบิล';
  }

  /* ⭐ ใบประเมินต้องบอกว่า **จะให้วัดตรงไหน** — ไซต์เปล่า ๆ ไม่ใช่งานที่ TS รับไปทำได้
     ⚠️ อยู่คู่กับ needs 'site' ไม่ใช่ `kind === 'site_survey'` — รูปเดียวกับยอดวางบิล
        ข้างบน · รายละเอียดของแต่ละแถว (ชื่อซ้ำ · เกินเพดาน) อยู่ที่
        `lib/service/surveyRequest.js` ซึ่งทั้งจอและ handler เรียกตัวเดียวกัน */
  if (meta.needs?.includes('site') && !(Array.isArray(body.zones) && body.zones.length)) {
    return 'ต้องมีพื้นที่ที่ต้องประเมินอย่างน้อย 1 รายการ';
  }

  // ชื่อเรื่องบังคับ**ทุกหัวข้อ** — เดิมหัวข้อขอราคายกเว้นไว้เพราะสื่อความด้วยบรรทัด
  // วัสดุ แต่บนคิวรวมและในเธรดดีล บรรทัดวัสดุมองไม่เห็น เหลือแต่ช่องว่าง
  if (!String(body.title ?? '').trim()) return 'ต้องระบุชื่อเรื่อง';

  if (meta.hasItems && (!Array.isArray(body.items) || body.items.length === 0)) {
    return 'ต้องมีรายการอย่างน้อย 1 รายการ';
  }

  if (String(body.title ?? '').length > 200) return 'ชื่อเรื่องยาวเกิน 200 ตัวอักษร';
  // ⭐ **ด่วนแล้วต้องบอกว่าทำไม** (mig 0222) — ฟอร์มกระดาษ FM-RD-01 เขียนไว้บนหัวว่า
  // "หากเป็นงานด่วน กรุณาระบุคำว่าด่วน และวันที่ต้องการ **พร้อมแจ้งเหตุผล**"
  // ⚠️ ติ๊กด่วนได้ฟรีเมื่อไร ทุกใบก็ด่วนภายในสองเดือน แล้วธงนั้นเลิกมีความหมาย
  if (body.urgent) {
    const reason = String(body.urgentReason ?? '').trim();
    if (!reason) return 'งานด่วนต้องระบุเหตุผลว่าทำไมถึงด่วน';
    if (reason.length > 500) return 'เหตุผลงานด่วนยาวเกิน 500 ตัวอักษร';
  }
  if (String(body.body ?? '').length > 4000) return 'รายละเอียดยาวเกิน 4000 ตัวอักษร';

  /* ⭐ **วันที่ต้องการรับงานบังคับทุกหัวข้อ** (มติผู้ใช้ 2026-08-08: "วันที่คาดหวังกับ
     วันที่กำหนดส่ง อยากให้บังคับใส่เสมอ ทุกคำร้อง") — คู่กับวันกำหนดส่งที่ฝ่ายปลายทาง
     แจ้งเป็นก้าวของตัวเอง · ใบที่ไม่มีวันนี้ ฝ่ายปลายทางไม่มีข้อมูลเลยว่างานนี้รีบแค่ไหน
     ตอนตัดสินใจรับปากวัน
     ⚠️ **คำที่ล็อกไว้คือ "วันที่ต้องการรับงาน"** (มติผู้ใช้ 2026-08-19) — ของเดิมเขียนว่า
     "ต้องการคำตอบ" ซึ่งจริงเฉพาะหัวข้อสอบถาม · หัวข้อที่ฝ่ายต้องส่ง *ของ* (กลิ่น ·
     สูตร · เอกสาร) ไม่ได้รอคำตอบ แต่รองาน ⇒ ป้ายเดิมอ่านผิดความหมายเกินครึ่งระบบ */
  const due = String(body.requestedDueDate ?? '').trim();
  if (!due) return 'ต้องระบุวันที่ต้องการรับงาน';
  if (!/^\d{4}-\d{2}-\d{2}$/.test(due)) return 'วันที่ต้องการรับงานไม่ถูกต้อง';
  return null;
}
