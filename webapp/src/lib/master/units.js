// ไม่รู้หมวด = ถือว่ามี เพื่อไม่ให้ช่องหายไปเงียบ ๆ กับแถวที่อ่านหมวดไม่ออก
export const PACKAGING_MAIN_CATEGORIES = Object.freeze(['01', '02']);

/**
 * สินค้าตัวนี้มีช่องปริมาตร/หน่วยบรรจุ/จำนวนต่อลัง ไหม
 * รับได้ทั้ง record ({ categoryCode, fgCode }) และรหัสหมวดตรง ๆ
 */
export function hasPackagingFields(recordOrCode) {
  const raw = typeof recordOrCode === 'string'
    ? recordOrCode
    : (recordOrCode?.categoryCode || categoryOf(recordOrCode?.fgCode));
  const mainCode = String(raw || '').slice(0, 2);
  if (!mainCode) return true;
  return PACKAGING_MAIN_CATEGORIES.includes(mainCode);
}

// ── ลิสต์รวม: ช่องที่นับได้ทั้ง "จำนวนชิ้น" และ "ปริมาณ" ────────────────────
// ใช้กับช่องหน่วยที่ **ไม่ใช่หน่วยขายบนเอกสาร** และไม่ใช่ขนาดต่อหน่วยขายด้วย — คือช่องที่
// ถามว่า "เอาเท่าไร" ล้วน ๆ เช่นบรรทัดคำร้องพัฒนาสินค้า ("ขอตัวอย่าง 3 ชิ้น" หรือ "100 ml")
// ของจริงในฐานใช้ทั้งสองแบบอยู่แล้ว ⇒ บังคับให้เลือกได้ลิสต์เดียวจะตัดเคสที่ใช้งานจริงทิ้ง
//
// เรียงหน่วยขายก่อนเพราะเป็นคำที่คนเลือกบ่อยกว่า · dedupe ด้วย Set (ไม่มีคำซ้ำกันตอนนี้
// แต่ถ้าวันหลังมีคำเดียวกันโผล่ทั้งสองลิสต์ ตัวเลือกต้องไม่ขึ้นสองครั้ง)
export const ALL_UNITS = Object.freeze([...new Set([...SALE_UNITS, ...VOLUME_UNITS])]);

export const DEFAULT_SALE_UNIT = 'ชิ้น';
export const DEFAULT_VOLUME_UNIT = 'ml';

// เพดานความยาว — หน่วยไปโผล่ในคอลัมน์แคบบนเอกสาร A4 ค่ายาวผิดปกติจาก client
// จะดันตารางเสียรูป (คอลัมน์ใน DB เป็น text ไม่มีเพดานของตัวเอง)
export const SALE_UNIT_MAX = 20;

export function saleUnitOf(value, fallback = DEFAULT_SALE_UNIT) {
  const text = String(value ?? '').trim();
  if (!text) return fallback;
  return text.length > SALE_UNIT_MAX ? text.slice(0, SALE_UNIT_MAX) : text;
}

// ตัวเลือกสำหรับ dropdown = ลิสต์มาตรฐาน + "ค่าปัจจุบัน" ถ้ามันไม่อยู่ในลิสต์แล้ว
// (เช่นสินค้าที่เคยตั้ง 'แพ็ค'/'โหล'/'oz' ไว้ก่อนลิสต์ถูกตัด) — ถ้าไม่พ่วงไว้ ช่องจะเด้ง
// กลับเป็นค่าแรกของลิสต์ แล้วหน่วยเปลี่ยนเงียบ ๆ ตอนผู้ใช้กดบันทึกเรื่องอื่น
export function unitOptions(list, current) {
  const value = String(current ?? '').trim();
  if (!value || list.includes(value)) return list.map((unit) => ({ value: unit, label: unit }));
  return [
    ...list.map((unit) => ({ value: unit, label: unit })),
    { value, label: `${value} (ค่าเดิม)` },
  ];
}

// ── ประโยคสรุปบรรจุภัณฑ์ '1 ขวด = 50 ml · 1 ลัง = 12 ขวด' ────────────────
// สองช่องนี้ชื่อคล้ายกันจนสลับกันได้ง่าย: "หน่วยขาย" คือหน่วยที่ **นับขาย** บน
// ใบเสนอราคา/ใบสั่งขาย (ไปเป็น quotation_lines.unit) ส่วน "หน่วยปริมาตร" คือ
// **ขนาดของหนึ่งหน่วยขาย** · คำอธิบายใต้ช่องช่วยได้ระดับหนึ่ง แต่ประโยคที่ประกอบ
// จากค่าที่กรอกจริงบอกได้ตรงกว่า — กรอกสลับช่องเมื่อไหร่ ประโยคจะอ่านแล้วผิดทันที
// ('1 ml = 50 ขวด') โดยไม่ต้องรอให้ไปโผล่ผิดบนเอกสารของลูกค้า
export function packagingSummary({ volume, volumeUnit, saleUnit, piecesPerCase } = {}) {
  const unit = String(saleUnit ?? '').trim() || DEFAULT_SALE_UNIT;
  const parts = [];
  const size = String(volume ?? '').trim();
  if (size) parts.push(`1 ${unit} = ${size} ${String(volumeUnit ?? '').trim() || DEFAULT_VOLUME_UNIT}`);
  const perCase = String(piecesPerCase ?? '').trim();
  if (perCase) parts.push(`1 ลัง = ${perCase} ${unit}`);
  return parts.join(' · ');
}

// ── ช่องบรรจุภัณฑ์ที่ต้องล้างเมื่อสินค้าอยู่กลุ่มที่ไม่มีของ ────────────────
// ใช้ทั้งตอนสร้างและตอนแก้ (ฝั่ง server) — ซ่อนช่องบนจออย่างเดียวไม่พอ เพราะ PATCH
// ยิงตรงได้ และสินค้าที่ย้ายหมวดข้ามกลุ่มจะพาค่าเก่าติดมาด้วย
export const PACKAGING_FIELDS = Object.freeze(['volume', 'volumeUnit', 'piecesPerCase']);

/** คืน patch ที่ล้างช่องบรรจุภัณฑ์ (ว่างเปล่าเมื่อกลุ่มนั้นมีช่องอยู่แล้ว) */
export function clearedPackagingFields(recordOrCode) {
  if (hasPackagingFields(recordOrCode)) return {};
  return Object.fromEntries(PACKAGING_FIELDS.map((key) => [key, null]));
}

// '30 ml' — รวมการเติมหน่วยตั้งต้นที่เดิมเขียน `|| 'ml'` ซ้ำอยู่หลายหน้า
// `language` ส่ง 'en' เมื่อพิมพ์ลงเอกสารอังกฤษ (ไทย/ไม่ระบุ = คืนคำที่เก็บไว้ตรง ๆ)
export function formatVolume(product, language = 'th') {
  const volume = product?.volume;
  if (volume === null || volume === undefined || volume === '') return '-';
  const unit = String(product?.volumeUnit || '').trim() || DEFAULT_VOLUME_UNIT;
  return `${volume} ${volumeUnitLabel(unit, language)}`;
}
