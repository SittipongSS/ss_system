// รหัสจังหวัดในทะเบียนเป็นสตริงที่มีศูนย์นำ ('10') แต่คีย์ของอ็อบเจกต์ข้างบนเป็นเลข
// ⇒ ทำให้เป็นตัวเลขก่อนเทียบเสมอ ('10' และ 10 ต้องได้คำตอบเดียวกัน)
const keyOf = (provinceCode) => {
  const digits = String(provinceCode ?? '').trim();
  if (!/^\d{1,2}$/.test(digits)) return null;
  return Number(digits);
};

/** ตัวย่อสามตัวของจังหวัด — `null` ถ้าไม่ใช่รหัสจังหวัดที่รู้จัก */
export function provinceAbbr(provinceCode) {
  const key = keyOf(provinceCode);
  return key === null ? null : (PROVINCES[key]?.[0] || null);
}

/** ภาคของจังหวัด (เลขสองหลัก) — `null` ถ้าไม่ใช่รหัสจังหวัดที่รู้จัก */
export function provinceRegion(provinceCode) {
  const key = keyOf(provinceCode);
  return key === null ? null : (PROVINCES[key]?.[1] || null);
}

/** ชื่อภาคไทย — ไว้แสดงบนจอคู่กับตัวเลข (ผู้ใช้ไม่ได้ท่องว่า 04 คือภาคไหน) */
export function regionLabel(regionCode) {
  return REGIONS[String(regionCode ?? '').trim()] || null;
}

