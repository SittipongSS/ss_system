// ── ชื่อกิจการลูกค้าสองภาษา (mig 0283) ──────────────────────────────────
//
// ⭐ ที่มา: เอกสาร IFRA / MSDS ที่ RD ออกให้ลูกค้าเป็นภาษาอังกฤษทั้งใบ — ชื่อกิจการ
// ต้องเป็นอังกฤษด้วย ไม่ใช่แค่ที่อยู่ · ฝั่งบริษัทเรามีอยู่แล้ว (COMPANY_LEGAL_NAME_EN)
// ฝั่งลูกค้าเพิ่งมีช่องนี้
//
// ── กติกา (มติผู้ใช้ 2026-08-22) ──
// 1. **ต้องมีอย่างน้อยหนึ่งภาษา** ไม่บังคับว่าภาษาไหน — ลูกค้าต่างชาติที่ไม่มีชื่อไทย
//    ต้องสร้างได้ และลูกค้าไทยที่ไม่เคยมีชื่ออังกฤษก็ต้องอยู่ได้เหมือนเดิม
// 2. **โชว์ภาษาหลักของบริบทก่อน ไม่มีค่อยตกไปอีกภาษา** — ⚠️ ไม่แปลให้เอง
//    (กติกาเดียวกับชื่อสินค้าบนใบเสนอราคา: ใบภาษาไหนใช้ชื่อภาษานั้นก่อน)
//
// ⚠️ หน้าจอระบบยังเป็นไทยล้วน — ช่องนี้ **ไม่ใช่ชื่อสำหรับแสดงคู่กัน** แบบหมวดสินค้า
// (`EN · TH`) · ตาราง/ดรอปดาวน์เลือกลูกค้ายังโชว์ชื่อเดียวตามกติกาข้อ 2

const text = (value) => String(value ?? '').trim();

/** ชื่อที่ต้องวาดในบริบทภาษาหนึ่ง — ไม่มีภาษานั้นก็ตกไปอีกภาษา */
export function customerNameIn(customer, language = 'th') {
  const th = text(customer?.name);
  const en = text(customer?.nameEn);
  return language === 'en' ? (en || th) : (th || en);
}

/** มีชื่ออย่างน้อยหนึ่งภาษาหรือยัง — ใช้ทั้งด่านฝั่งฟอร์มและฝั่ง API (ตัวเดียวกัน) */
export function hasCustomerName(customer) {
  return !!(text(customer?.name) || text(customer?.nameEn));
}

/** ข้อความด่านตรวจ — null = ผ่าน (รูปเดียวกับ arCodeError/taxIdDuplicateError) */
export function customerNameError(customer) {
  return hasCustomerName(customer) ? null : 'ต้องมีชื่อกิจการอย่างน้อยหนึ่งภาษา (ไทยหรืออังกฤษ)';
}

// ── ฝั่งเขียน: ชื่อที่ประทับลงตารางอื่น ────────────────────────────────────
//
// 🐞 ที่มา (2026-09-03): ลูกค้าที่มีแต่ชื่ออังกฤษ (ไทยว่าง) โชว์ขีดทุกจอ ทั้งที่กรอก
// ชื่อไว้แล้ว — ไม่ใช่เพราะจอไม่ยอมวาด แต่เพราะ **จุดเขียนสำเนาอ่านแค่ `name`**
// แล้วประทับ null ลงคอลัมน์ `customerName` ของดีล/โครงการ/สินค้าตั้งแต่วันสร้าง
// จอปลายทางจึงมีแต่ null ให้วาด · วัดจริงตอนพบ: AR-630 มีดีล/โครงการ/สินค้า
// อย่างละใบที่ customerName = null
//
// ⚠️ **ทุกจุดที่ก๊อป customers.name ลงตารางอื่นต้องเรียกตัวนี้ ห้ามอ่าน `.name` ตรง ๆ**
// และ select ต้องหยิบ `nameEn` มาด้วย ไม่งั้น fallback ไม่มีข้อมูลให้ตก

/* คอลัมน์ขั้นต่ำที่ต้อง select ทุกครั้งที่จะเอาชื่อลูกค้าไปประทับหรือไปวาด
   quote ตามคอนเวนชันของรีโป — ไม่ใช่เพราะ PostgREST บังคับ (ลิสต์ที่ไม่ quote เช่น
   CUSTOMER_PICKER_COLUMNS ใช้งานบน production อยู่) แต่เพื่อให้คอลัมน์ camelCase
   ของ `customers` เขียนเหมือนกันทุกที่ */
export const CUSTOMER_NAME_SELECT = 'id, name, "nameEn"';

/* ชื่อที่ประทับลงคอลัมน์สำเนา — ไทยก่อน ไม่มีค่อยตกไปอังกฤษ (กติกาข้อ 2)
   ไม่มีสักภาษา = null (ปลายทางวาดขีดตามกติกาค่าว่างทั้งระบบ) */
export function customerSnapshotName(customer) {
  return customerNameIn(customer, 'th') || null;
}

/* ข้อความค้นหาของลูกค้าหนึ่งราย — ต้องเจอ **ทั้งสองภาษา** ไม่ใช่แค่ภาษาที่โชว์
   (กติกา search haystack + ลูกค้าต่างชาติที่คนพิมพ์หาด้วยชื่ออังกฤษเสมอ) */
export function customerNameSearchText(customer) {
  return [text(customer?.name), text(customer?.nameEn)].filter(Boolean).join(' ');
}

// ── คำเตือน: "สำนักงานใหญ่ / สาขา" ไม่ควรอยู่ในชื่อกิจการ ────────────────
//
// ⭐ ที่มา (2026-08-27): ตอนคืนแถว "สาขา" กลับมาบนใบเสนอราคา (หายไปตั้งแต่ 5 ส.ค.)
// ใบของลูกค้าที่พิมพ์คำนี้ติดไว้ในชื่อ กลายเป็นขัดกันเองบนกระดาษแผ่นเดียว:
//
//   ผู้ซื้อ   บริษัท ซารางแฮร์ ดูล จำกัด (สำนักงานใหญ่)   ← ชื่อบอกสำนักงานใหญ่
//   สาขา     สาขาที่ 00001                                ← ช่องสาขาบอกสาขา 1
//
// ที่ถูกคือเลขสาขาเป็นคุณสมบัติของ **ที่อยู่** (สถานประกอบการ) ไม่ใช่ของชื่อนิติบุคคล —
// เหตุผลเต็มอยู่ที่หัวไฟล์ lib/master/addresses.js · ของจริงในทะเบียนมี 15 ราย จาก 191
//
// ⚠️ **เตือน ไม่บล็อก** — แถวเดิม 15 รายต้องบันทึกต่อได้โดยไม่ต้องแก้ชื่อก่อน และชื่อ
// จดทะเบียนบางรายอาจมีคำเหล่านี้อยู่จริง เราไม่มีทางรู้แทนคนกรอก
const BRANCH_WORDS_TH = /สำนักงานใหญ่|สนง\.?ใหญ่|สนญ\.?|สาขา/;
const BRANCH_WORDS_EN = /\b(head\s*office|branch)\b/i;

export function customerNameBranchWarning(customer) {
  const hits = [];
  if (BRANCH_WORDS_TH.test(text(customer?.name))) hits.push('ชื่อภาษาไทย');
  if (BRANCH_WORDS_EN.test(text(customer?.nameEn))) hits.push('ชื่อภาษาอังกฤษ');
  if (!hits.length) return null;
  return `${hits.join(' และ ')}มีคำว่า “สำนักงานใหญ่/สาขา” — เลขสาขาควรอยู่ที่ช่อง “เลขสาขา” ของที่อยู่ ไม่ใช่ในชื่อกิจการ ไม่งั้นเอกสารจะบอกสาขาสองที่ไม่ตรงกัน (บันทึกต่อได้)`;
}

// ── คำนำหน้าชื่อลูกค้าบุคคลธรรมดา (mig 0296) ────────────────────────────
//
// ⭐ ที่มา (มติผู้ใช้ 2026-08-27): ทะเบียนเขียนคำนำหน้ากันคนละแบบทั้งกอง และ
// ตัวที่ใช้เยอะสุดคือ 'คุณ' (42 ราย) ซึ่ง **ไม่ใช่คำนำหน้าตามกฎหมาย** ใช้บนใบกำกับ
// ภาษีเต็มรูปไม่ได้ ⇒ ตัวเลือกมีสามตัวตามบัตรประชาชนเท่านั้น
//
// ⚠️ 'คุณ' **ไม่อยู่ในตัวเลือก** โดยตั้งใจ — ของเดิม 42 รายต้องไล่แก้เป็น
// นาย/นาง/นางสาว ทีละราย (เดาแทนคนไม่ได้: ชื่อไทยหลายชื่อใช้ได้ทั้งสองเพศ)
//
// ⚠️ ช่อง "อื่น ๆ" พิมพ์เองได้ เพราะคำนำหน้าที่ใช้จริงมีนอกสามตัวนี้
// (ทะเบียนมี 'ดร.' อยู่แล้ว 1 ราย · ยศทหาร/ตำรวจก็เป็นคำนำหน้าบนเอกสารจริง)
export const CUSTOMER_NAME_TITLES = Object.freeze(['นาย', 'นาง', 'นางสาว']);

/* ประกอบชื่อเต็มจากคำนำหน้า + ชื่อ — ใช้ทั้งฝั่งฟอร์ม (พรีวิว) และฝั่ง API (ค่าที่เขียนจริง)
   ⚠️ **ถอยไปใช้ `name` เดิมเมื่อยังไม่มี namePerson** — แถวยุคก่อน mig 0296 กับลูกค้า
   นิติบุคคลไม่มีสองช่องนี้ ต้องไม่ถูกล้างเป็นค่าว่างตอนบันทึกผ่านสายที่ไม่ได้ส่งมา */
export function composeCustomerName({ nameTitle, namePerson, name } = {}) {
  const person = text(namePerson);
  if (!person) return text(name);
  const title = text(nameTitle);
  return title ? `${title} ${person}` : person;
}

/* แยกชื่อเต็มที่มีคำนำหน้าติดมา → { nameTitle, namePerson }
   ใช้ตอน backfill และตอนเปิดฟอร์มแก้แถวที่ยังไม่มีสองช่องนี้ (ไม่ได้เขียนลงฐาน
   จนกว่าคนจะกดบันทึก) · จับไม่ได้ = คำนำหน้าว่าง ชื่อเต็มไปอยู่ที่ namePerson
   ⚠️ 'คุณ' จับด้วย แต่คืนออกมาตามที่เจอ — **ไม่แปลงให้เป็น นาย/นางสาว เอง**
   เพราะเดาเพศจากชื่อไทยไม่ได้ · จอเป็นคนบอกว่าค่านี้ไม่อยู่ในตัวเลือก */
const TITLE_PATTERN = /^(นางสาว|นาง|นาย|น\.ส\.?|ด\.ช\.|ด\.ญ\.|คุณ|ดร\.)\s*/;
export function splitCustomerName(fullName) {
  const full = text(fullName);
  const match = TITLE_PATTERN.exec(full);
  if (!match) return { nameTitle: '', namePerson: full };
  // 'น.ส.' เป็นตัวย่อของ 'นางสาว' — เก็บรูปเต็มรูปเดียวทั้งระบบ ไม่งั้นเรียง/กรอง
  // ได้สองกอง · ตัวย่ออื่น (ด.ช./ด.ญ.) ไม่มีรูปเต็มที่ใช้บนเอกสาร จึงคงตามที่เจอ
  const raw = match[1];
  const nameTitle = /^น\.ส\.?$/.test(raw) ? 'นางสาว' : raw;
  return { nameTitle, namePerson: full.slice(match[0].length).trim() };
}

/* เขียนกระจก `name` จากสองช่องย่อย — เรียกก่อนบันทึกทุกครั้ง (POST/PATCH)
   คืน patch ที่พร้อม merge · ไม่มีช่องย่อยส่งมาเลย = ไม่แตะอะไรทั้งนั้น
   🪤 **นิติบุคคลต้องล้างสองช่องนี้ทิ้ง** ไม่ใช่ปล่อยผ่าน — ฟอร์มถือ state ชุดเดียว
      ทั้งสองประเภท คนสลับ "บุคคลธรรมดา → นิติบุคคล" แล้วบันทึก ถ้าไม่ล้าง แถวนั้น
      จะค้าง namePerson ของยุคที่ยังเป็นบุคคล แล้ว `name` โดนประกอบทับด้วยชื่อเก่า
      ทุกครั้งที่แก้ครั้งถัดไป */
export function customerNamePatch(body = {}) {
  if (body.namePerson === undefined && body.nameTitle === undefined) return {};
  if (body.customerType !== 'individual') return { nameTitle: null, namePerson: null };
  const nameTitle = text(body.nameTitle) || null;
  const namePerson = text(body.namePerson) || null;
  return { nameTitle, namePerson, name: composeCustomerName({ nameTitle, namePerson, name: body.name }) || null };
}
