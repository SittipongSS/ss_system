//
// ⭐ ที่มา: เอกสาร IFRA / MSDS ที่ RD ออกให้ลูกค้าเป็นภาษาอังกฤษทั้งใบ — ชื่อกิจการ
// ต้องเป็นอังกฤษด้วย ไม่ใช่แค่ที่อยู่ · ฝั่งบริษัทเรามีอยู่แล้ว (COMPANY_LEGAL_NAME_EN)
// ฝั่งลูกค้าเพิ่งมีช่องนี้
//
// ── กติกา (มติผู้ใช้ 2026-08-22) ──
// 1. **ต้องมีอย่างน้อยหนึ่งภาษา** ไม่บังคับว่าภาษาไหน — ลูกค้าต่างชาติที่ไม่มีชื่อไทย
//    ต้องสร้างได้ และลูกค้าไทยที่ไม่เคยมีชื่ออังกฤษก็ต้องอยู่ได้เหมือนเดิม
// 2. **โชว์ภาษาหลักของบริบทก่อน ไม่มีค่อยตกไปอีกภาษา** — ⚠️ ไม่แปลให้เอง
//    (กติกาเดียวกับชื่อสินค้าบนใบเสนอราคา: ใบภาษาไหนใช้ชื่อภาษานั้นก่อน)
//
// ⚠️ หน้าจอระบบยังเป็นไทยล้วน — ช่องนี้ **ไม่ใช่ชื่อสำหรับแสดงคู่กัน** แบบหมวดสินค้า
// (`EN · TH`) · ตาราง/ดรอปดาวน์เลือกลูกค้ายังโชว์ชื่อเดียวตามกติกาข้อ 2

const text = (value) => String(value ?? '').trim();

/** ชื่อที่ต้องวาดในบริบทภาษาหนึ่ง — ไม่มีภาษานั้นก็ตกไปอีกภาษา */
export function customerNameIn(customer, language = 'th') {
  const th = text(customer?.name);
  const en = text(customer?.nameEn);
  return language === 'en' ? (en || th) : (th || en);
}

/** มีชื่ออย่างน้อยหนึ่งภาษาหรือยัง — ใช้ทั้งด่านฝั่งฟอร์มและฝั่ง API (ตัวเดียวกัน) */
export function hasCustomerName(customer) {
  return !!(text(customer?.name) || text(customer?.nameEn));
}

/** ข้อความด่านตรวจ — null = ผ่าน (รูปเดียวกับ arCodeError/taxIdDuplicateError) */
export function customerNameError(customer) {
  return hasCustomerName(customer) ? null : 'ต้องมีชื่อกิจการอย่างน้อยหนึ่งภาษา (ไทยหรืออังกฤษ)';
}

// ── คำเตือน: "สำนักงานใหญ่ / สาขา" ไม่ควรอยู่ในชื่อกิจการ ────────────────
//
// ⭐ ที่มา (2026-08-27): ตอนคืนแถว "สาขา" กลับมาบนใบเสนอราคา (หายไปตั้งแต่ 5 ส.ค.)
// ใบของลูกค้าที่พิมพ์คำนี้ติดไว้ในชื่อ กลายเป็นขัดกันเองบนกระดาษแผ่นเดียว:
//
//   ผู้ซื้อ   บริษัท ซารางแฮร์ ดูล จำกัด (สำนักงานใหญ่)   ← ชื่อบอกสำนักงานใหญ่
//   สาขา     สาขาที่ 00001                                ← ช่องสาขาบอกสาขา 1
//
// ที่ถูกคือเลขสาขาเป็นคุณสมบัติของ **ที่อยู่** (สถานประกอบการ) ไม่ใช่ของชื่อนิติบุคคล —
// เหตุผลเต็มอยู่ที่หัวไฟล์ lib/master/addresses.js · ของจริงในทะเบียนมี 15 ราย จาก 191
//
// ⚠️ **เตือน ไม่บล็อก** — แถวเดิม 15 รายต้องบันทึกต่อได้โดยไม่ต้องแก้ชื่อก่อน และชื่อ
// จดทะเบียนบางรายอาจมีคำเหล่านี้อยู่จริง เราไม่มีทางรู้แทนคนกรอก
const BRANCH_WORDS_TH = /สำนักงานใหญ่|สนง\.?ใหญ่|สนญ\.?|สาขา/;
const BRANCH_WORDS_EN = /\b(head\s*office|branch)\b/i;

export function customerNameBranchWarning(customer) {
  const hits = [];
  if (BRANCH_WORDS_TH.test(text(customer?.name))) hits.push('ชื่อภาษาไทย');
  if (BRANCH_WORDS_EN.test(text(customer?.nameEn))) hits.push('ชื่อภาษาอังกฤษ');
  if (!hits.length) return null;
  return `${hits.join(' และ ')}มีคำว่า “สำนักงานใหญ่/สาขา” — เลขสาขาควรอยู่ที่ช่อง “เลขสาขา” ของที่อยู่ ไม่ใช่ในชื่อกิจการ ไม่งั้นเอกสารจะบอกสาขาสองที่ไม่ตรงกัน (บันทึกต่อได้)`;
}
