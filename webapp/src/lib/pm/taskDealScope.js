import { hasTeam, isSuperuser, userTeams } from '@/lib/permissions';

// ── ทุกงานต้องผูกดีล (มติผู้ใช้ 2026-08-06) ─────────────────────────────────
// เดิมบังคับเฉพาะฝ่ายขาย (SA) เพราะฝ่ายอื่นไม่มี team → taskDealScope = 'none' →
// ไม่มีดีลให้เลือกเลย บังคับไปก็แค่ทำให้เขาสร้างงานไม่ได้. ตอนนี้แก้ที่ต้นเหตุ:
// **ฝ่ายที่ไม่มีทีมเห็นดีลทั้งหมด** (เขาทำงานให้ทุกทีมขายอยู่แล้ว) แล้วจึงบังคับได้จริง
//
// ทำไมต้องบังคับ — งานที่ไม่ผูกดีลคืองานที่หน้าดีล/หน้าโครงการมองไม่เห็น: ดีลไม่รู้ว่า
// มีงานเปิดค้างอยู่ และ KPI รายดีลนับไม่ครบ ทั้งที่คนทำงานก็ทำให้ดีลใบใดใบหนึ่งอยู่ดี
//
// ⚠️ **ไม่มีข้อยกเว้นตาม role** (มติผู้ใช้ 2026-08-06 รอบสอง) — รอบแรกยกเว้น
// admin/เลขาไว้ด้วยเหตุผลว่า "งานดูแลระบบไม่ได้เกิดจากดีล" แต่ผลจริงคือบัญชีที่ใช้
// งานจริงที่สุด (แอดมิน) กดบันทึกงานโดยไม่เลือกดีลได้ = กติกาที่บังคับไม่ถึงคนที่
// สร้างงานมากที่สุด · ทุกคนที่ล็อกอินต้องผูกดีล ไม่มีใครได้รับการยกเว้น
//
// ⭐ **ผ่อนเป็น "ค่าตั้งต้น" แล้ว (มติผู้ใช้ 2026-08-08)** — ฟอร์มมีสวิตช์ "ไม่ผูกดีล"
// ที่ **ปิดไว้เสมอ** กดเองได้เมื่องานนั้นไม่ได้เกิดจากดีลจริง ๆ (งานดูแลระบบ/งานภายใน)
// แล้วส่งธง `noDealLink` มาให้ route ปล่อยผ่าน · เหตุผลของกติกาเดิมยังจริงทุกข้อ
// จึงยังเป็นค่าตั้งต้นและมีคำเตือนที่สวิตช์ — เปลี่ยนจาก "ห้ามเลย" เป็น "ต้องตั้งใจ"
// ⚠️ ฟังก์ชันนี้ยังคืน true เสมอ — ธง noDealLink เป็นเรื่องของ *คำขอรายครั้ง*
// ไม่ใช่ของ role จึงเช็คที่ route ไม่ใช่ที่นี่ (อย่าย้ายมาปนกัน)
//
// ข้อยกเว้นเดียวที่เหลือคือ **งานที่สร้างจากคำร้อง** (เช็คที่ route ไม่ใช่ที่นี่):
// ดีลมาจากคำร้องต้นทาง ซึ่งบางหัวข้อไม่ผูกดีลโดยเจตนา (เช่น ขอราคา F/FB) คนสร้าง
// งานเลือกดีลเองไม่ได้เลย บังคับแล้วจะกลายเป็น "เปิดงานจากคำร้องพวกนั้นไม่ได้"
export function requiresDealLink(user) {
  return !!user;
}

export function canLinkTaskToDeal(user, deal) {
  if (!user || !deal) return false;
  if (isSuperuser(user.role)) return true;
  // ฝ่ายที่ไม่มีทีม (RD/PC/PD/WH/QC/TS/FN) รับงานจากทุกทีมขาย — ขอบเขต "ทีมเดียวกัน"
  // ใช้กับคนที่มีทีมเท่านั้น ไม่งั้นกติกาจะกลายเป็น "ผูกดีลไม่ได้เลย"
  if (!userTeams(user).length) return true;
  return hasTeam(user, deal.team);
}

// `teams` = ทุกทีมที่ผู้ใช้สังกัด (คนเดียวอยู่ได้หลายทีม) — ผู้เรียกกรองด้วย .in()
export function taskDealScope(user) {
  if (!user) return { kind: 'none', teams: [] };
  if (isSuperuser(user.role)) return { kind: 'all', teams: [] };
  const teams = userTeams(user);
  return teams.length ? { kind: 'team', teams } : { kind: 'all', teams: [] };
}
