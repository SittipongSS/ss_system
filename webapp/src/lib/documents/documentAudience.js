//    กระดาษที่ **ใช้ภายใน** = steel #1e6091 — สีของใบสั่งขาย
//   ⇒ คนที่หยิบกระดาษขึ้นมารู้จากสีชื่อเอกสารว่าใบนี้ส่งลูกค้าได้หรือเป็นของภายใน โดยไม่ต้องอ่านหัวกระดาษ
//
// 🔑 ไฟล์นี้ถามเรื่องเดียว: "ผู้อ่านคนนี้ = คีย์สีไหน" — **ไม่รู้จักชนิดเอกสาร** (ไม่มีชื่อเอกสารไหนอยู่ที่นี่)
//   ชนิดเอกสารเป็นคนบอกเองว่ากระดาษของตัวเองให้ใครอ่าน แล้วมาถามสีที่นี่ · ค่าที่คืนเป็นคีย์ของ `DOCUMENT_ACCENT_THEMES`
//   (lib/documents/documentShell.js) ส่งต่อเป็น `accentKey` ของเปลือกเอกสารได้ตรง ๆ
//
// 🔴 **คีย์ตายตัว — ไม่ได้อ่านมาตรฐานที่เผยแพร่ของใบเสนอราคา / ใบสั่งขาย**
//   สองคีย์ข้างล่างเท่ากับ **สีตั้งต้น** ของสองชนิดนั้นใน `lib/documentStandards.js` (`documentAudience.test.mjs` ล็อกทั้งคีย์และค่าสีจริง
//   — ขยับฝั่งเดียวเมื่อไรเทสต์ล้ม) แต่สองชนิดนั้น **ยังเลือกสีจากหน้ามาตรฐานเอกสารได้** ⇒ วันที่ใครเผยแพร่ใบเสนอราคาเป็นสีอื่น
//   กระดาษที่ถามสีจากที่นี่ **ไม่ตาม** · "เหมือนใบเสนอราคา / เหมือนใบสั่งขาย" จึงเป็นที่มาของค่า ไม่ใช่สิ่งที่โครงสร้างรับประกัน
//   ⇒ ข้อความบนจอให้เอ่ยชื่อสี ไม่เอ่ยชื่อเอกสารสองชนิดนั้น · จะให้จริงโดยโครงสร้างต้องล็อกสีของสองชนิดนั้นด้วย (รอมติเจ้าของ)
// ⚠️ **ไม่มี import** โดยเจตนา — ทั้งตัวเรนเดอร์ฝั่ง server · จอฝั่ง client · และสคริปต์นอกแอป เรียกไฟล์นี้ได้โดยไม่ลากอะไรตามมา

/** ผู้อ่านของกระดาษ — `external` = ออกนอกบริษัท (ลูกค้า) · `internal` = ใช้ภายใน */
export const DOCUMENT_AUDIENCES = Object.freeze(['external', 'internal']);

const ACCENT_BY_AUDIENCE = Object.freeze({
  external: 'terracotta',
  internal: 'steel',
});

/**
 * คีย์สีของกระดาษสำหรับผู้อ่านกลุ่มหนึ่ง
 * @param audience `'external' | 'internal'`
 * @returns คีย์ของ `DOCUMENT_ACCENT_THEMES` — ค่าที่ไม่รู้จักได้สีของกระดาษที่ออกนอกบริษัท (สีตั้งต้นเดียวกับเปลือกเอกสาร)
 */
export function documentAudienceAccentKey(audience) {
  return Object.hasOwn(ACCENT_BY_AUDIENCE, audience) ? ACCENT_BY_AUDIENCE[audience] : ACCENT_BY_AUDIENCE.external;
}
