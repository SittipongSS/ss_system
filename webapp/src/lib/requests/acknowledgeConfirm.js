// ⭐ มติเจ้าของ 23/09: การ์ดคำร้องบนหน้าจัดคิว (/service/schedule) กดรับเรื่องได้ด้วย ⇒ ปุ่มเดียวกัน
//    สองหน้า ต้องบอกผลลัพธ์ชุดเดียวกัน (กติกา "ทุกการอนุมัติต้องมีโมดัลบอกผล" · #1223)
