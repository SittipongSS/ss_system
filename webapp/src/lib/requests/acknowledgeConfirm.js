// ⭐ ยิ่งจำเป็นหลังแยกก้าว: คนกดต้องรู้ว่ากดแล้วใบ **ยังไม่มีวันกำหนดส่ง** และต้องกลับมากด
//    ก้าวถัดไปอีกที ไม่งั้นจะเข้าใจว่าจบแล้ว
import {
  requestNeedsRef, requestPdrRowsPickScent, requestUsesDeliveredRows, requestUsesPdr,
} from '@/lib/master/requestTypes';
import { issuesPdrRefNoOnAcknowledge } from '@/lib/requests/pdrRefNo';
import { planNpdWorkRows } from '@/lib/requests/npdWorkRows';
import { commitDueLabels, commitDueMode } from '@/lib/requests/commitDue';

/**
 * ⭐ ใบประเมินที่ **ประเมินจากแบบทั้งใบ** (งานโต๊ะ · งวด S2b) — ก้าวถัดจากรับเรื่องไม่ใช่การลงคิว:
 *   ใบออกจาก "คำร้องรอลงคิว" ของหน้าจัดคิว แล้วหัวหน้าฝ่ายบริการกด "รับปากวันส่งผล" ที่หน้าคำร้อง / ใบประเมิน
 * คืนประโยคของก้าวถัดไป หรือ `null` เมื่อไม่ใช่งานโต๊ะ (ทุกใบเดิมของระบบ) — กล่องยืนยันและ toast หลังรับเรื่องใช้ตัวเดียวกัน
 * ⚠️ ชื่อปุ่มมาจาก `commitDueLabels` (ไม่พิมพ์ซ้ำ) · งานโต๊ะถามผ่าน `commitDueMode` (ธง `surveyNeedsVisit === false` ตรงตัว)
 * ⚠️ ชื่อปุ่มในประโยคใช้อัญประกาศโค้ง “…” เหมือนข้อความเด้งของใบลงหน้างานบนหน้าเดียวกัน
 *    (เดิมอัญประกาศตรง "…" — S2b แก้หลังตรวจจอ S2b-str-ack)
 */
export function acknowledgeDeskNext(request) {
  if (commitDueMode(request) !== 'desk') return null;
  return `ใบนี้ประเมินจากแบบ ไม่ต้องลงคิวเข้าพื้นที่ · หัวหน้าฝ่ายบริการกด “${commitDueLabels(request).action}” เมื่อรู้วันส่งผล`;
}

/* ข้อความเด้งหลังรับเรื่องงานโต๊ะ **ค้างนานกว่าค่าตั้งต้นของ Toast (3.6 วินาที)** — การ์ดหายจากรายการทันทีหลังกด
   ข้อความนี้จึงเป็นร่องรอยเดียวที่บอกผู้วางคิวว่าก้าวต่อไปเป็นของหัวหน้า · ยาวราว 120 ตัวอักษร (สี่บรรทัดบนมือถือ)
   อ่านไม่จบใน 3.6 วินาที (S2b แก้หลังตรวจจอ planner-q8) */
export const ACKNOWLEDGE_DESK_TOAST = Object.freeze({ duration: 8000 });

/**
 * ข้อความเด้งหลังรับเรื่องสำเร็จบนหน้าจัดคิว เมื่อใบเป็นงานโต๊ะ — `{ kind, msg, duration }` หรือ `null` (ไม่ใช่งานโต๊ะ
 *   ⇒ หน้าใช้ข้อความ "การ์ดเปลี่ยนเป็น …" ของเดิม) · ประโยคก้าวถัดไปตัวเดียวกับกล่องยืนยัน (`acknowledgeDeskNext`)
 * @param docNo เลขที่ใบที่การ์ดโชว์
 */
export function acknowledgeDeskToast(request, docNo) {
  const deskNext = acknowledgeDeskNext(request);
  if (!deskNext) return null;
  return { kind: 'success', msg: `รับเรื่อง ${docNo} แล้ว — ${deskNext}`, duration: ACKNOWLEDGE_DESK_TOAST.duration };
}

/**
 * `{ title, description, detail, confirmLabel }` ของกล่องยืนยันรับเรื่อง
 * @param now เวลาที่ใช้ตัดสินว่าเดือนนี้ออกเลข PDR ให้เองหรือยัง (เทสต์ตรึงได้)
 */
export function acknowledgeConfirmCopy(request, { now = new Date() } = {}) {
  const req = request || {};
  const scheduling = requestNeedsRef(req.kind, 'site');
  const deskNext = acknowledgeDeskNext(req);
  /* งานโต๊ะ (ประเมินจากแบบทั้งใบ): ไม่มีปุ่ม "ลงคิวเข้าพื้นที่" บนจอ ⇒ บอกก้าวจริงของใบนี้แทน
     และ **ไม่ขึ้นต้นด้วย "ใบนี้จะเข้าคิวของ … ทันที"** — ประโยคเดียวกันจะบอกทั้ง "เข้าคิว" และ "ไม่ต้องลงคิว"
     ซึ่งขัดกันเอง แล้วหลังกดการ์ดก็หายจากคิวด้วย (S2b แก้หลังตรวจจอ S2b-str-ack) · ใบอื่นทุกใบได้ประโยคเดิมทุกตัวอักษร */
  const detail = (deskNext
    ? `นับเป็นงานที่ ${req.dept} รับไว้ทันที · ยังไม่ต้องระบุวันตอนนี้ — ${deskNext}`
    : `ใบนี้จะเข้าคิวของ ${req.dept} ทันที และนับเป็นงานที่ ${req.dept} รับไว้แล้ว`
      /* ⚠️ ชื่อปุ่มขั้นถัดไป **ต่างตามหัวข้อ** — ใบประเมินไม่มีปุ่มชื่อ "แจ้งกำหนดส่ง"
         บนจอเลย (ปุ่มจริงคือ "ลงคิวเข้าพื้นที่") ⇒ สั่งให้ไปกดปุ่มที่ไม่มีอยู่ */
      + (scheduling
        ? ' · ยังไม่ต้องระบุวันตอนนี้ — ใบจะไปอยู่สถานะ "รอกำหนดส่ง"'
          + ' แล้วกด "ลงคิวเข้าพื้นที่" เมื่อรู้วัน เวลา และเจ้าหน้าที่ที่จะไป'
        : ' · ยังไม่ต้องระบุวันกำหนดส่งตอนนี้ — ใบจะไปอยู่สถานะ "รอกำหนดส่ง"'
          + ' แล้วกด "แจ้งกำหนดส่ง" เมื่อรู้วันจริง'))
    /* ⭐ บอกด้วยว่ากดแล้ว **ได้เลขที่เอกสารหรือยัง** — สองโหมดคนละเรื่องกันเลย
       (mig 0271 · 0272) · เลขอัตโนมัติใช้วันที่ของวินาทีที่กดและแก้ทีหลังไม่ได้
       ส่วนช่วงกรอกเองต้องบอกให้ชัดว่ายังต้องไปกดอีกปุ่ม ไม่งั้นคนกดจะเข้าใจว่า
       จบแล้ว แล้วเอกสารออกไปโดยไม่มีเลข */
    + (!requestUsesPdr(req) ? ''
      : issuesPdrRefNoOnAcknowledge(req, now)
        ? ' · ระบบจะออกเลขที่เอกสารของ PDR (วันที่วันนี้) ให้ในจังหวะเดียวกัน'
        : ' · เดือนนี้ยังไม่ออกเลขให้เอง — รับเรื่องแล้วกด "กรอกเลขที่เอกสาร" ใส่เลขจากกระดาษ')
    /* ⭐ พัฒนาสูตร NPD (ม-144) — บอกล่วงหน้าว่ากดแล้ว **ได้รายการส่งสูตรกี่รายการ** (ตัววางแผนตัวเดียว
       กับที่ server ใช้) · สเปรย์กลิ่นเดียวกันหลายขนาดรวมเป็นสูตรเดียว ต้องไม่ทำให้คนกดงงว่าหายไปไหน */
    + (requestUsesDeliveredRows(req) && requestPdrRowsPickScent(req)
      ? (() => {
        const n = planNpdWorkRows({ targets: req.targets, items: req.items }).insert.length;
        return n ? ` · ระบบจะแตกสินค้าในแบบฟอร์ม PDR เป็นรายการส่งสูตร ${n} รายการ (หนึ่งรายการต่อคู่หมวด × กลิ่น)` : '';
      })()
      : '');
  return {
    title: 'รับเรื่อง',
    description: req.docNo || '',
    detail,
    confirmLabel: 'รับเรื่อง',
  };
}
