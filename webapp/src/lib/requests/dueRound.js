// 🐞 **ช่องว่างที่ผู้ใช้ทักมา**: ลูกค้าขอให้แก้ ⇒ ระบบเปิดแถวรอบใหม่ให้เอง แต่ไม่มี
// อะไรถามวันส่งของรอบนั้น · ใบยังถือ `committedDueDate` ของรอบก่อน ซึ่งโดยนิยาม
// คือวันที่ผ่านไปแล้ว ⇒ คิว "เลยกำหนด" นับใบนั้นค้างตลอดกาล และรางขึ้นขั้น
// "แจ้งวันส่ง" เป็น **เขียวผ่านแล้ว** พร้อมวันที่ไม่เกี่ยวกับงานที่กำลังทำอยู่
// (วัด 2026-08-25: ใบที่เดินอยู่ 53 ใบ — 22 ใบเลยวันที่แจ้งไว้แล้ว)
//
// ⭐ **ใครแจ้งวัน ≠ ใครบันทึก feedback** (มติผู้ใช้ 2026-08-25) — ข้อนี้เป็นเหตุผลที่
// ไฟล์นี้มีอยู่ แทนที่จะไปเพิ่มช่องวันในโมดัลบันทึกคำตอบ:
//   · `HOP_OWNER.outcome = 'requester'` ⇒ **SA** เป็นคนบันทึกว่าลูกค้าว่าอย่างไร
//   · `commit-due` / `reschedule` กันด้วย `canAnswerRequest` ⇒ **RD/ฝ่ายปลายทาง**
//     เท่านั้นที่แจ้งวันได้
// ⇒ ยัดช่องวันลงโมดัลของ SA = ฟอร์มที่กรอกแล้วยิงไม่ผ่านด่าน 403
// ⇒ ทางที่ถูกคือ **ให้ขั้น "แจ้งวันส่ง" กลับมาเป็นขั้นปัจจุบันของใบ** แล้ว RD กด
//   ปุ่มเดิมที่มีอยู่แล้ว — ไม่ต้องเพิ่มฟอร์มใหม่ให้ใคร
//
// ⚠️ **ไม่นับ "รอบที่เท่าไร"** — เลขรอบต้องมีคนคอยนับให้ตรงกับสายพันธุ์ของแถว
// (`derivedFromItemId`) ซึ่งเป็นตัวนับที่สองที่ drift ได้ · ที่นี่ถามคำถามที่ตอบได้
// จากของที่มีอยู่แล้ว: **แถวรอบแก้ที่ยังเดินอยู่ เกิดหลังการแจ้งวันครั้งล่าสุดไหม**
import { isRowSettled } from '@/lib/requests/rowStage';

/**
 * แถวที่เป็น "รอบแก้ที่ยังเดินอยู่" — เกิดจากที่ลูกค้าขอให้แก้ และยังไม่จบ
 *
 * ⚠️ `derivedFromItemId` เป็นตัวชี้ว่าแถวนี้เป็นรอบต่อของแถวไหน (ตั้งโดย
 * `followUpRowFrom`) — แถวรอบแรกไม่มีค่านี้เสมอ
 */
export function openReworkRows(items = []) {
  return (items || []).filter((row) => row?.derivedFromItemId && !isRowSettled(row));
}

/**
 * วันส่งที่ใบถืออยู่ **ค้างจากรอบก่อน** หรือไม่ — คืน `true` เมื่อยังไม่มีใครแจ้งวัน
 * ของรอบที่กำลังทำอยู่
 *
 * ⚠️ `dueCommittedAt` เป็น NULL = ใบเก่าที่มีมาก่อน mig 0288 ⇒ **ถือว่าไม่ค้าง**
 * ไม่ใช่ค้าง · ตีความอีกทางแล้วใบเก่าทุกใบที่มีรอบแก้จะเด้งกลับไปขั้น "แจ้งวันส่ง"
 * พร้อมกันในวันที่ deploy โดยที่ไม่มีใครสั่ง
 *
 * ⚠️ เทียบ **timestamp กับ timestamp** — `createdAt` ของแถวกับ `dueCommittedAt`
 * เป็น timestamptz ทั้งคู่ · `outcomeAt` เป็น date จึงใช้ไม่ได้ (ลูกค้าขอแก้กับ RD
 * แจ้งวันในวันเดียวกันแยกไม่ออกว่าอะไรเกิดก่อน)
 */
export function dueIsStale(request, items = []) {
  if (!request) return false;
  if (!String(request.committedDueDate ?? '').trim()) return false;
  const committedAt = request.dueCommittedAt ? Date.parse(request.dueCommittedAt) : null;
  if (!Number.isFinite(committedAt)) return false;
  return openReworkRows(items).some((row) => {
    const born = row.createdAt ? Date.parse(row.createdAt) : null;
    return Number.isFinite(born) && born > committedAt;
  });
}
