// ทุกคีย์ในชุดสำเร็จรูปมีตัววาดจริงในพาเนล ไม่ใช่พิมพ์ชื่อคอลัมน์ผิดแล้วได้ช่องว่าง

/** ป้ายหัวคอลัมน์ + การจัดวาง — `num` = ชิดขวา + ตัวเลขความกว้างเท่ากัน (กฎ 3) */
export const REQUEST_COLUMNS = {
  // ⭐ คอลัมน์แรกของคิวคือคำตอบของคำถามแรก "ฉันต้องทำอะไร" (ม-60)
  next: { label: 'ต้องทำอะไร' },
  // เลขที่ + ชนิด + เรื่อง/ลูกค้า + ถึงฝ่าย = "ใบนี้คือใบอะไร" ก้อนเดียว
  doc: { label: 'คำร้อง' },
  kind: { label: 'ชนิด' },
  dept: { label: 'ถึงฝ่าย' },
  owner: { label: 'ผู้รับเรื่อง' },
  due: { label: 'กำหนดส่ง', num: true },
  progress: { label: 'คืบหน้า', num: true },
  status: { label: 'สถานะ' },
};

export const REQUEST_COLUMN_KEYS = Object.keys(REQUEST_COLUMNS);

/**
 * ชุดคอลัมน์สำเร็จรูปต่อบริบท
 *
 * `queue`  — หน้าคิวเต็ม (`/requests` · `/rd/requests`) · 4 คอลัมน์ตามมติ 2026-08-08
 * `linked` — การ์ด "คำร้องที่ผูกกับรายการนี้" บนหน้าดีล/โครงการ
 *
 * ⚠️ `linked` **ขึ้นต้นด้วย `next` เหมือนกัน** ทั้งที่ของเดิมไม่มี — คนที่เปิดหน้าดีล
 * ถามคำถามเดียวกับคนที่เปิดคิว ("ค้างที่ใคร") · ของเดิมตอบได้แค่ "สถานะ" ซึ่งบอก
 * ไม่ได้ว่าใบที่ยังเป็นร่างนั้น *ยังไม่ส่ง* หรือ *ถูกตีกลับมาให้แก้*
 * ⚠️ ไม่มี `progress` — บนหน้าดีลพื้นที่แคบกว่า และความคืบหน้ารายบรรทัดเป็นเรื่อง
 * ของคนทำงานในคิว ไม่ใช่ของคนที่มาดูภาพรวมดีล
 * ⚠️ ไม่มี `kind` เป็นคอลัมน์แยก — เซลล์ `doc` เติมชนิดเข้าบรรทัดรองให้เองเมื่อไม่มี
 * คอลัมน์ของมัน ⇒ ได้ข้อมูลเท่าเดิมโดยไม่กินความกว้างอีกช่อง (การ์ดอยู่ในคอลัมน์แคบ)
 */
export const REQUEST_COLUMN_PRESETS = {
  queue: ['next', 'doc', 'due', 'progress'],
  linked: ['next', 'doc', 'dept', 'owner', 'due', 'status'],
};

/** คืนรายชื่อคอลัมน์ที่ใช้จริง — ตัดคีย์ที่ไม่มีในทะเบียนทิ้ง (พิมพ์ผิด = ไม่วาด) */
export function requestColumns(columns) {
  const list = Array.isArray(columns) ? columns : REQUEST_COLUMN_PRESETS[columns] || REQUEST_COLUMN_PRESETS.queue;
  return list.filter((key) => REQUEST_COLUMNS[key]);
}
