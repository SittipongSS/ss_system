/** คืนรายชื่อคอลัมน์ที่ใช้จริง — ตัดคีย์ที่ไม่มีในทะเบียนทิ้ง (พิมพ์ผิด = ไม่วาด) */
export function requestColumns(columns) {
  const list = Array.isArray(columns) ? columns : REQUEST_COLUMN_PRESETS[columns] || REQUEST_COLUMN_PRESETS.queue;
  return list.filter((key) => REQUEST_COLUMNS[key]);
}
