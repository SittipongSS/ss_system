// ⭐ **ลิสต์เดียวคุมทั้งสองฝั่ง** — `/requests` ตัดคิวของฝ่ายที่มีโมดูลออกจากแท็บ
// "รอฉันตอบ" · `/rd/requests` รับเฉพาะฝ่ายตัวเอง ⇒ วันที่ PC ได้โมดูล เพิ่มชื่อ
// ฝ่ายที่นี่ที่เดียวแล้วทั้งสองจอตามเอง ไม่ต้องไล่แก้เงื่อนไขในหน้าจอ
//
// ⚠️ **ห้ามใช้ลิสต์นี้ตัดสินสิทธิ์** — มันตอบแค่ "งานของฝ่ายนี้แสดงที่จอไหน"
// ด่านจริงคือ `canAnswerRequestsFor` (lib/permissions.js) และตัวกรองที่ API
// ⇒ ฝ่ายที่หลุดจากลิสต์นี้ไม่ได้เสียสิทธิ์อะไร แค่เห็นงานตัวเองในคิวรวมแทน
export const DEPTS_WITH_OWN_MODULE = ['RD'];

export function deptHasOwnModule(dept) {
  return DEPTS_WITH_OWN_MODULE.includes(dept);
}

// ฝ่ายที่คิวของมันยังอยู่ในคิวรวม `/requests` — ผู้เรียกส่งฝ่ายที่ตัวเองตอบได้เข้ามา
//
// ⚠️ AE Supervisor ยังยืนยันใบที่ `/requests` ได้เหมือนเดิม (มติ ม-32) เพราะเขาไม่ได้
// อยู่ฝ่ายผู้ตอบ — ใบที่รอเขาเข้าแท็บ "รอฉันตอบ" ผ่านสาขา `owner === 'requester'`
// ซึ่งไม่เกี่ยวกับลิสต์นี้เลย
export function deptsInSharedQueue(depts = []) {
  return depts.filter((dept) => !deptHasOwnModule(dept));
}
