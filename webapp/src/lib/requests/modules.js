// วิจัยและพัฒนาเลย"* (มติ ม-29) ⇒ ฝ่ายที่มีบ้านของตัวเองแล้วต้องดูงานของฝ่าย
// **ที่เดียว** ไม่ใช่โผล่ทั้งในบ้านตัวเองและในคิวรวมของฝ่ายขาย
