// ── ตาใครตอบ — สำหรับหัวข้อที่ "ทั้งใบคือเธรด" (มติผู้ใช้ 2026-08-20) ─────
//
// ⭐ **โจทย์**: *"จะทำไงให้รู้ว่าฝ่ายไหนต้องตอบกลับ ขอเจาะที่หัวข้อสอบถาม"*
//
// หัวข้อที่ไม่มีบรรทัด (สอบถามข้อมูล) ไม่มีขั้นของแถวให้อ่าน ⇒ ระบบเดิมไม่มีทางรู้ว่า
// ลูกปิงปองอยู่ฝั่งไหน · คิวขึ้น "รอฝ่ายเริ่ม" ค้างตั้งแต่วันรับเรื่องจนถึงวันที่มีคนกด
// "ตอบแล้ว" แม้ฝ่ายจะตอบในเธรดไปแล้วและกำลังรอผู้ขอตอบกลับ
//
// ⭐ **ตัดสินจากคนโพสต์ล่าสุด ไม่ใช่ปุ่มที่ต้องมีคนกด** — เธรดพลิกฝั่งเองทุกข้อความ
// ไม่มีอะไรให้ใครจำ (`lastReplySide` · mig 0270 stamp ตอนโพสต์)
// ⚠️ จุดอ่อนที่รู้ตัว: ฝ่ายโพสต์โน้ตกลางทาง ("ขอเวลา 2 วัน") ป้ายจะพลิกไปฝั่งผู้ขอ
// ทั้งที่งานยังอยู่ที่ฝ่าย — มันแก้ตัวเองในข้อความถัดไป · อย่าเพิ่งเติมปุ่มกดทับจนกว่า
// จะเจอของจริงบ่อยพอ (ปุ่มที่ไม่มีใครกด = หนี้ UI)
import { requestDeliversRows, requestHasItems } from '@/lib/master/requestTypes';

/**
 * หัวข้อที่ **ทั้งใบคือเธรด** — ไม่มีบรรทัดตั้งแต่เปิดใบ และฝ่ายไม่ได้สร้างแถวตอนส่งงาน
 *
 * ⚠️ เงื่อนไขชุดเดียวกับปุ่ม "ตอบแล้ว" (`canMarkAnswered` ในหน้ารายละเอียด) โดยตั้งใจ —
 * หัวข้อที่มีแถวมีขั้นของแถวเล่าอยู่แล้วว่าใครค้าง ("รอ RD ทำต่อ" / "รอ SA ทำต่อ")
 * ซึ่งละเอียดกว่าเธรด ⇒ ทับด้วยการพลิกตามข้อความล่าสุดเมื่อไรคือทำให้ข้อมูลหยาบลง
 */
export function requestIsThreadOnly(kind) {
  return !requestHasItems(kind) && !requestDeliversRows(kind);
}

/**
 * ชื่อที่ใช้เรียกแต่ละฝั่งบนป้าย — **ชื่อฝ่ายจริง ไม่ใช่คำว่า "ฝ่าย" ลอย ๆ**
 * (มติผู้ใช้ 2026-08-20: *"รอฝ่ายตอบ… ฝ่ายคืออะไร ไม่สวยเลย"*)
 *
 * ⚠️ ฝั่งผู้ขอถอยไปใช้คำว่า "ผู้ขอ" เมื่อใบนั้นไม่มี `requesterDept` — ใบที่เปิดก่อน
 * mig 0270 และ backfill ไม่ถึง (ไม่มีเหตุการณ์ "ส่งเคส" ในเธรด) ยังต้องอ่านออก
 */
export function requestSideLabel(request, side) {
  return side === 'dept'
    ? (request?.dept || 'ฝ่ายผู้รับ')
    : (request?.requesterDept || 'ผู้ขอ');
}

/**
 * ประโยค "รอ <ฝั่ง> <ทำอะไร>" — **เว้นวรรครอบรหัสฝ่ายเท่านั้น**
 *
 * ⚠️ ไทยไม่เว้นวรรคกลางประโยค แต่รหัสฝ่ายเป็นอักษรละติน (RD · SA · FN) ที่ติดกับ
 * ตัวไทยแล้วอ่านยาก ⇒ "รอ RD ตอบ" ต้องมีช่องไฟ ส่วนคำถอย ("ผู้ขอ") ต้องไม่มี
 * ("รอผู้ขอปิดเรื่อง" ไม่ใช่ "รอ ผู้ขอ ปิดเรื่อง")
 */
const isDeptCode = (who) => /^[A-Za-z0-9][A-Za-z0-9&./-]*$/.test(who);

export function requestWaitLabel(request, side, verb) {
  const who = requestSideLabel(request, side);
  return isDeptCode(who) ? `รอ ${who} ${verb}` : `รอ${who}${verb}`;
}

/**
 * ประโยค "<ฝั่ง> <ทำอะไร>" — กติกาช่องไฟเดียวกับ `requestWaitLabel` แต่ไม่มีคำว่า "รอ"
 * ("RD ตอบ 17/08/2026" · "ผู้ขอยังไม่ปิด")
 *
 * 🐞 เคยเขียนต่อสตริงเองที่หน้าจอ ⇒ คำถอยที่เป็นภาษาไทยได้ช่องไฟติดมาด้วย
 * ("ผู้ขอ ยังไม่ปิด") · กติกาต้องอยู่ที่เดียวกับตัวที่มีคำว่า "รอ"
 */
export function requestSideText(request, side, verb) {
  const who = requestSideLabel(request, side);
  return isDeptCode(who) ? `${who} ${verb}` : `${who}${verb}`;
}

/**
 * ตาใครตอบ — คืน `{ side, label }` หรือ `null` เมื่อคำถามนี้ไม่มีความหมายกับใบนั้น
 *
 * ⚠️ เฉพาะใบที่ **รับเรื่องแล้วและยังเดินอยู่** — ใบที่ยังไม่มีใครรับมีป้ายของตัวเอง
 * ("รอรับเรื่อง") · ใบที่ตอบแล้ว/ปิดแล้วไม่มีใครต้องตอบอีก
 * ⚠️ ยังไม่มีข้อความของคนเลย = นับเป็นตาของฝ่าย — ผู้ขอเขียนคำถามไว้ในใบตั้งแต่ตอน
 * เปิดแล้ว การเงียบของฝ่ายคือสิ่งที่ต้องทวง ไม่ใช่ให้ใบไปค้างที่ฝั่งคนถาม
 */
export function requestReplyTurn(request) {
  if (!request || request.status !== 'acknowledged') return null;
  if (!requestIsThreadOnly(request.kind)) return null;
  /* ⚠️ **ถามว่าใบนี้มีแถวอยู่จริงไหม ไม่ใช่เชื่อทะเบียนชนิดอย่างเดียว** — บทเรียน
     เดียวกับด่านปิดเรื่อง (`closeRequestError`): ใบที่มีแถวจริงมีขั้นของแถวเล่าอยู่แล้ว
     ว่าใครค้าง ซึ่งละเอียดกว่าเธรด ⇒ ทับด้วยการพลิกตามข้อความล่าสุดคือทำให้หยาบลง
     🐞 และใบที่ `kind` ว่าง/ไม่รู้จัก จะถูกนับเป็น "เธรดล้วน" ทั้งที่มีแถวเดินอยู่ */
  if ((request.items || []).length) return null;
  const side = request.lastReplySide === 'dept' ? 'requester' : 'dept';
  return { side, label: requestWaitLabel(request, side, 'ตอบ') };
}
