import { hasTeam, primaryTeam } from '@/lib/permissions';

// ── ทีมเจ้าของคำร้อง (คิวทีมที่ใบนี้เข้า) ─────────────────────────────────────
//
// ตัวตัดสินเดียวของทั้ง server (POST /api/sa/requests) และชิป "ทีมเจ้าของคำร้อง" บนฟอร์ม
// ⇒ ทีมที่จอโชว์ตอนผู้ใช้ยังไม่ได้กดเลือก = ทีมที่ถูกบันทึกจริง
//
// ลำดับ:
//   1. ทีมที่เลือกมา — ถ้าคนเปิดอยู่ทีมนั้นจริง (ค่าที่ไม่ใช่ทีมตัวเองไม่มีผล กันยิง API ตรงโยนใบเข้าคิวคนอื่น)
//   2. ทีมของดีลต้นทาง — ถ้าคนเปิดอยู่ทีมนั้น
//      🐞 ตรวจบัญชีสองทีม 26/11/2026: เดิมข้ามข้อนี้ ⇒ AE ที่อยู่ ODM+SV เปิดคำร้องคาดีล SV
//         แล้วใบเข้าคิว ODM (ทีมหลัก) ทั้งที่งานเป็นของ SV
//   3. ทีมหลักของคนเปิด
//   4. ทีมของดีลต้นทาง — คนเปิดไม่มีทีมเลย (admin/หัวหน้าฝ่ายขาย/RD/PC) · กติกาเดิมของ route:
//      ขอบเขตเดินตามงาน ไม่ใช่ตามคนกด (mig 0253 / lib/pm/projectOwner.js)
//   5. null — ไม่ผูกดีลและคนเปิดไม่มีทีม (งานระหว่างคนเปิดกับฝ่ายที่ตอบ)
export function requestTeamFor(user, { requested = null, dealTeam = null } = {}) {
  const own = [requested, dealTeam].find((team) => team && hasTeam(user, team));
  return own || primaryTeam(user) || dealTeam || null;
}
