// ⚠️ อ่านผ่าน `liveDueDate` เหมือนทุกจอ — ใบที่มีรอบแก้ค้างจะไม่โชว์วันของรอบก่อน
// เป็นคำสัญญาที่ยังอยู่ (ดู lib/requests/dueRound.js)
import { dueIsStale, liveDueDate } from '@/lib/requests/dueRound';
import { fmtDate } from '@/lib/format';

/**
 * เนื้อของเซลล์ "กำหนดส่ง" — คิดครั้งเดียวต่อใบ แล้วส่งให้ตารางใช้ทุกแถว
 *
 * ⚠️ **คิดที่ใบ ไม่ใช่ที่แถว** — ค่าเท่ากันทั้งตาราง · ให้แต่ละแถวเรียกเองแปลว่า
 * เรียก `dueIsStale` (ซึ่งไล่ทุกแถวในใบ) หนึ่งครั้งต่อแถว = O(n²) ในใบ 25 แถว
 *
 * @returns {{text:string, note:string|null, tone:'late'|'wait'|null}}
 */
export function requestDueCell(request, todayIso = null) {
  const due = liveDueDate(request);
  if (!due) {
    /* ⭐ **สองสถานะที่ไม่มีวันเหมือนกัน แต่คนละเรื่อง** (กติกาเดียวกับ `requestDueTone`)
       — ยังไม่เคยแจ้งเลย vs เคยแจ้งแล้วแต่วันนั้นเป็นของรอบที่ส่งไปแล้ว · อย่างหลัง
       คือของค้างที่ต้องทวง จึงเป็นเหลือง ไม่ใช่เทา */
    return dueIsStale(request, request?.items)
      ? { text: 'รอแจ้งวันรอบแก้', note: null, tone: 'wait' }
      : { text: 'ยังไม่แจ้ง', note: null, tone: null };
  }
  if (!todayIso) return { text: fmtDate(due), note: null, tone: null };
  // ⚠️ ต่างกันเป็น "วัน" ทั้งคู่เป็น YYYY-MM-DD ของวันไทย (กติกาเดียวกับ requestDueText)
  const ms = Date.parse(`${due}T00:00:00Z`) - Date.parse(`${todayIso}T00:00:00Z`);
  if (!Number.isFinite(ms)) return { text: fmtDate(due), note: null, tone: null };
  const days = Math.round(ms / 86400000);
  if (days < 0) return { text: fmtDate(due), note: `เลย ${-days} วัน`, tone: 'late' };
  if (days === 0) return { text: fmtDate(due), note: 'วันนี้', tone: 'wait' };
  return { text: fmtDate(due), note: null, tone: null };
}

/**
 * ตัวคุมกติกาข้อ 2 — สร้างครั้งเดียวต่อตาราง แล้วถามทีละแถวตามลำดับที่วาดจริง
 *
 * ⚠️ **มีสถานะข้างใน (จำว่าพิมพ์ไปหรือยัง) จึงต้องสร้างใหม่ทุกครั้งที่เรนเดอร์ตาราง**
 * — เอาไปแคชข้ามเรนเดอร์เมื่อไร ตารางรอบที่สองจะไม่พิมพ์วันเลยสักแถว
 * ⚠️ อยู่ที่นี่ที่เดียว ไม่ให้สามตารางเขียนกติกาเอง — สามชุดที่ต้องคอยดูให้ตรงกัน
 * คือโรคเดิมที่ทั้งงานนี้พยายามปิด
 */
export function dueCellTracker(due = null) {
  let printed = false;
  return (row) => {
    if (!due || row?.settled) return false;
    // สถานะที่ต้องระวังพิมพ์ทุกแถว — ไม่นับเข้าโควตา "แถวแรก"
    if (due.tone) return true;
    if (printed) return false;
    printed = true;
    return true;
  };
}
