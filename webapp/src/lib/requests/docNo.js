// ── เลขที่คำร้อง — ของกลาง ────────────────────────────────────────────────
// ออกตอนกดส่งเท่านั้น (ร่างที่ถูกทิ้งจะได้ไม่กินเลขจนขาดช่วง — บทเรียนใบขอราคาผลิต)
//
// scope มาจากทะเบียนหัวข้อที่เดียว (`requestDocScope`) — ไม่มีค่าเดาจากฝ่ายแล้ว
// (ถอด `RM-`/`PM-` ออก 2026-08-18 · ทะเบียนบังคับให้ทุกหัวข้อประกาศ scope เอง)
import { businessMonthKey } from '@/lib/businessDate';
import { requestDocScope } from '@/lib/master/requestTypes';

export const REQUEST_RUNNING_WIDTH = 4;

/* ── คีย์ของตัวนับ (มติผู้ใช้ 2026-08-31 รอบสอง) ────────────────────────────
   *"RQ ก็ XXXX เปลี่ยนเป็นเลขรันรวมตัดทุกปีแทน"*

   ⭐ **เลขรันเป็นก้อนเดียวทุกหัวข้อ และตัดรอบทุกปี** — ของเดิมแยกตัวนับรายหัวข้อ
   และตัดรอบทุกเดือน ⇒ `RQ-SB-26080001` กับ `RQ-DC-26080001` เป็นคนละใบที่ลงท้าย
   เลขเดียวกัน · ของใหม่เลขไม่ซ้ำกันทั้งปีไม่ว่าหัวข้อไหน

   🔴 **จุดที่พลาดง่ายที่สุดของเลขชุดนี้ — `YYMM` ในเลข ≠ ตัวตัดรอบของเลขรัน**
   · `YYMM` ที่เห็นในเลข มาจาก **prefix** ซึ่งคิดจากเดือนที่กดส่ง
   · ตัวตัดรอบคือ **คีย์ `month` ของ `entity_number_counters`** ซึ่งตั้งเป็น **ปี** (`YY`)
   ⇒ เลขเดินต่อข้ามเดือนภายในปีเดียวกัน:
     `RQ-SB-26080001` → (เดือนถัดไป คนละหัวข้อ) `RQ-DC-26090002` → (ปีใหม่) `RQ-IQ-27010001`

   ⚠️ **ตัวย่อหัวข้อไม่ใช่คีย์ตัวนับอีกแล้ว** — มันเหลือหน้าที่เดียวคือ *อยู่ในเลขให้คนอ่าน*
   (ทะเบียนหัวข้อยังเก็บไว้ในช่องชื่อ `scope` ตามเดิม เพราะเปลี่ยนชื่อฟิลด์กระทบหลายไฟล์
   — แต่ในไฟล์นี้เรียกมันว่า `code` เพื่อไม่ให้สับสนกับ scope ของตัวนับ)
   🪤 กิ่ง seed ของ RPC ใช้ `LIKE p_prefix || '%'` ซึ่งผูกกับหัวข้อ+เดือน ⇒ ถ้าแถวตัวนับ
     ของปีนั้นหายไป มันจะ seed จากเลขของหัวข้อเดียวเท่านั้นแล้วนับซ้ำ · กิ่งนั้นทำงาน
     เฉพาะตอนแถวหาย ซึ่ง trigger ของ mig 0241 กันไว้ไม่ให้ลบอยู่แล้ว */
export const REQUEST_NUMBER_SCOPE = 'RQ';

/** ปีของรอบเลข (2 หลัก ตามนาฬิกาไทย) — คีย์ `month` ของตัวนับ ไม่ใช่เดือนในเลข */
export const requestCounterYear = (now = new Date()) => businessMonthKey(now).slice(0, 2);

// ชิ้นส่วนของเลขที่สำหรับส่งให้ฟังก์ชัน SQL — ที่นี่ยังเป็นที่เดียวที่รู้รูปแบบเลข
export function requestDocNoParts(kind, dept, now = new Date()) {
  const code = requestDocScope(kind);
  // ⚠️ ไม่มีตัวย่อ = ทะเบียนหัวข้อผิด (registry.js กันไว้ตั้งแต่ตอนโหลด) · ตายที่นี่
  // ดีกว่าปล่อยไปให้ SQL โยน `request_scope_invalid` ตอนผู้ใช้กดส่ง
  if (!code) throw new Error(`หัวข้อ "${kind}" ไม่มี scope ของเลขที่`);
  const month = businessMonthKey(now);
  /* ⭐ **มติผู้ใช้ 2026-08-31: `RQ-AA-YYMMXXXX`** — ทุกใบขึ้นต้น `RQ` เหมือนกันหมด
     แล้วตัวย่อหัวข้อ (`AA`) อยู่กลาง · ของเดิมตัวย่อหัวข้อ *แทนที่* `RQ` ⇒ เลขคำร้อง
     ขึ้นต้นไม่เหมือนกันสักใบ (SB- FD- DC- DF- AS- RQ-) มองผ่าน ๆ ไม่รู้ว่าเป็นคำร้อง

     ⚠️ **`scope` กับ `prefix` เป็นคนละเรื่องโดยตั้งใจ** — `scope` เป็นคีย์ของตัวนับ
     (`entity_number_counters`) ส่วน `prefix` เป็นแค่สตริงที่เอาไปต่อหน้าเลขรัน
     ⇒ เติม `RQ-` ที่ prefix อย่างเดียว **ตัวนับเดินต่อไม่สะดุด และไม่ต้องมี migration**
     (RPC 0243 รับ p_scope กับ p_prefix แยกกัน ต่างจาก RPC ของสัญญาที่ฮาร์ดโค้ด scope)
     🪤 ห้ามเผลอเอา `RQ-` ไปใส่ใน `scope` — ตัวนับจะกลายเป็นคีย์ใหม่แล้วเริ่มนับ 1
     ใหม่ทุกหัวข้อ และ SQL จะเตะทิ้งเพราะ `^[A-Z]{2,4}$` ไม่ยอมให้มีขีด */
  return {
    // คีย์ตัวนับ: ก้อนเดียวทุกหัวข้อ ตัดรอบทุกปี
    scope: REQUEST_NUMBER_SCOPE,
    month: requestCounterYear(now),
    // สิ่งที่โผล่ในเลขจริง: ตัวย่อหัวข้อ + เดือนที่กดส่ง
    prefix: `RQ-${code}-${month}`,
    width: REQUEST_RUNNING_WIDTH,
  };
}

/**
 * กดส่ง: ออกเลข (ถ้าใบยังไม่มี) + บันทึก patch ในทรานแซกชันเดียว (mig 0243)
 *
 * 🐞 บั๊กจริงที่ผู้ใช้แจ้ง (IS-26080010 · 2026-08-11): ฝ่าย RD ตีกลับคำร้อง ⇒ ใบกลับ
 * เป็น `draft` โดย `docNo` ยังคาอยู่ (ตั้งใจตามมติ mig 0209 — ตีกลับคือใบเดิม ไม่ใช่
 * ใบใหม่) · แต่เส้นทางกดส่งออกเลขใหม่ทุกครั้ง ⇒ UPDATE ชน trigger
 * `guard_dept_request` (`dept_request_doc_no_immutable`) ⇒ **ใบที่ถูกตีกลับส่งซ้ำ
 * ไม่ได้เลย** ทั้งที่ทั้งฟีเจอร์ตีกลับมีไว้ให้แก้แล้วส่งใหม่
 *
 * ⚠️ ตอนนั้นแก้ด้วยการเช็ค `docNo` เดิมฝั่ง JS ก่อนออกเลข ซึ่งพอสำหรับอาการนั้น แต่
 * โครงยังเป็น "จองเลขก่อน แล้วค่อยเขียนแถว" — เลขถูก commit ตั้งแต่คำสั่งแรก ⇒ ทุกครั้ง
 * ที่ UPDATE ไม่ผ่าน (ด่านอื่น/ชน guard/คอนเนกชันหลุด) เลขนั้นหายถาวร ของจริงที่วัดได้:
 * ตัวนับ RQ เดือน 2608 วิ่งไปถึง 37 ทั้งที่เลขที่ออกจริงสูงสุดคือ RQ-26080029
 *
 * ⇒ ตอนนี้ทั้งการออกเลขและการเขียนแถวอยู่ในฟังก์ชัน SQL ตัวเดียว ล้มตรงไหนก็คืนเลข
 * และการเช็ค "ใบนี้มีเลขแล้วหรือยัง" ย้ายไปอยู่ใต้ `SELECT … FOR UPDATE` ⇒ สองคนกดส่ง
 * พร้อมกันก็ไม่ได้คนละเลขบนใบเดียวกัน
 *
 * ⚠️ นี่ไม่ใช่ด่าน "ส่งได้ไหม" — ด่านนั้นคือ `submitRequestError` · ที่นี่ตอบแค่
 * "ใช้เลขไหน" ⇒ ใบที่มีเลขแล้วต้องส่งผ่านได้ตามปกติ ห้ามเปลี่ยนเป็น error
 */
export function assignRequestDocNo(supabase, request, patch, now = new Date()) {
  const { scope, month, prefix, width } = requestDocNoParts(request?.kind, request?.dept, now);
  return supabase.rpc('assign_dept_request_doc_no', {
    p_id: request?.id,
    p_scope: scope,
    p_month: month,
    p_prefix: prefix,
    p_width: width,
    p_patch: patch,
  });
}

// เปิดใบแล้วส่งในจังหวะเดียว (ขออัปเดตกำหนดของเข้าจากหน้าโครงการ) — insert พร้อมเลข
// ⚠️ ห้ามใส่คีย์ docNo ลงใน row เอง ฟังก์ชัน SQL เป็นคนเติมหลังจองเลขสำเร็จ
export function insertRequestWithDocNo(supabase, row, now = new Date()) {
  const { scope, month, prefix, width } = requestDocNoParts(row?.kind, row?.dept, now);
  return supabase.rpc('create_dept_request_with_doc_no', {
    p_scope: scope,
    p_month: month,
    p_prefix: prefix,
    p_width: width,
    p_row: row,
  });
}
