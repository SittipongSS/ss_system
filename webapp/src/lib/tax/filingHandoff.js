// แจ้งเฉพาะ "จุดที่เปลี่ยนมือ" ไม่ใช่ทุกการเปลี่ยนสถานะ — ข้าม 'filing' (LG เริ่มยื่นเอง
// ภายในเลนเดียว) และ 'delivered' (ปลายทาง จบแล้ว) เพื่อไม่ให้การ์ดกลายเป็นเสียงรบกวน
const HANDOFF = Object.freeze({
  pending: {
    space: 'sales',
    title: '💰 ใบยื่นภาษีรอเก็บเงินจากลูกค้า',
    next: 'เก็บเงินค่าภาษีจากลูกค้าแล้วกด "ยืนยันรับเงิน"',
  },
  received: {
    space: 'legal',
    title: '🏛️ ใบยื่นภาษีรอยื่นกรมสรรพสามิต',
    next: 'ระบุเลขที่ใบกำกับภาษีแล้วกด "เริ่มยื่น"',
  },
  complete: {
    space: 'sales',
    title: '✅ ชำระภาษีแล้ว — รอส่งเอกสารให้ลูกค้า',
    next: 'ส่งหลักฐานการชำระให้ลูกค้าแล้วกด "ยืนยันส่งเอกสาร"',
  },
  rejected: {
    space: 'sales',
    title: '↩️ ใบยื่นภาษีถูกตีกลับให้แก้ไข',
    next: 'แก้ตามเหตุผลแล้วส่งกลับเข้าคิวฝ่ายกฎหมาย',
  },
});

export function filingHandoffTarget(before, after) {
  if (!before || !after) return null;
  if (after.status === before.status) return null;
  return HANDOFF[after.status] || null;
}
