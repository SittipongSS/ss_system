// ── ตัวกรองของรายงานภาษี: ที่เดียวที่แปลงตัวกรองเป็น query ──────────────────
// ใช้ร่วมกันระหว่างรายงาน (reports.js) และ ZIP ไฟล์แนบ (registrationFiles.js) —
// ทั้งสองอ่านตัวกรองชุดเดียวกันจาก /api/tax/reports ถ้าเขียนกฎแยกกันมันจะเพี้ยนหากัน
// (ผู้ใช้กดดูรายงานเห็นชุดหนึ่ง กดดาวน์โหลดได้อีกชุด)

// ตัวกรองรับได้ทั้งค่าเดียว/หลายค่า (comma-separated จาก query string หรือ array) —
// ตัวกรองทั้งระบบเป็น multi-select (มติผู้ใช้ 2026-07-18); ว่าง/'all' = ไม่กรอง
export const asList = (v) => {
  if (Array.isArray(v)) return v.filter(Boolean);
  if (!v || v === 'all') return [];
  return String(v).split(',').filter(Boolean);
};

// ตัวกรองทีมของรายงานมี **สองช่องที่ทำงานคนละหน้าที่** แล้ว AND กัน:
//   scopeTeam = ขอบเขตของผู้ใช้ (บังคับตาม role) → ทีมตัวเอง **+ แถวไร้ทีมซึ่งเป็นของกลาง**
//               รับได้ทั้งทีมเดียวและอาร์เรย์ (คนเดียวอยู่ได้หลายทีม)
//               ว่าง = ไม่บังคับ (role ที่เห็นทุกทีม หรือคนที่ scope 'team' แต่ไม่มีทีม)
//   team      = ตัวกรองที่ผู้ใช้เลือก (ไม่บังคับ) → เฉพาะทีมที่เลือก **ไม่พ่วงแถวไร้ทีม**
//
// ⚠️ ห้ามยุบสองช่องนี้กลับเป็น `.eq('team', X)` ตัวเดียว (เดิมเป็นแบบนั้น) เพราะ
// (1) แถว `team = null` จะหายจากรายงานของทุกทีม — แถวพวกนี้เกิดทุกครั้งที่คนไม่มีทีม
//     (แอดมิน/นิติกรรม/ธุรการ) เป็นคนสร้างเอกสาร และ (2) พอแบกสองความหมายในตัวแปรเดียว
//     จะแก้ข้อ 1 ไม่ได้เลย: ขยายให้พ่วงแถวไร้ทีม แอดมินที่ *เลือก* กรอง KA ก็จะได้แถว
//     ไร้ทีมพ่วงมาด้วย ซึ่งไม่ใช่สิ่งที่เขาสั่ง
export function applyTeamScope(query, { scopeTeam, team } = {}) {
  let q = query;
  const scopeTeams = asList(scopeTeam);
  if (scopeTeams.length) q = q.or(`team.in.(${scopeTeams.join(',')}),team.is.null`);
  const teams = asList(team);
  if (teams.length) q = q.in('team', teams);
  return q;
}
