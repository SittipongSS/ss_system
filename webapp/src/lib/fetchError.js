// 🐞 บั๊กจริงที่ทำให้ต้องมีไฟล์นี้: ผู้ใช้แนบเอกสารในหน้าลูกค้าแล้วได้ข้อความว่า
// **"อัปโหลดไฟล์ไม่สำเร็จ"** เฉย ๆ ซึ่งเป็นทางตัน — ตามต่อไม่ได้ทั้งผู้ใช้และคนดูแล
//
// ที่มาของข้อความนั้นคือแพตเทิร์นที่ก๊อปกันอยู่ 7 จุด:
//     const data = await res.json().catch(() => ({}));
//     throw new Error(data.error || "อัปโหลดไฟล์ไม่สำเร็จ");
// มันอ่านได้เฉพาะ error ที่ **handler ของเราเอง** ตอบกลับมาเป็น JSON · แต่คำขอที่
// ตายก่อนถึง handler (ถูกตัดที่ชั้น platform / เกตเวย์ / หมดเวลารอ) ตอบกลับมาเป็น
// HTML หรือ text ⇒ `.json()` พัง ⇒ ตกไปใช้ค่าสำรองตายตัวที่ไม่ได้บอกอะไรเลย
// **แม้แต่ HTTP status ก็ถูกทิ้ง** ทั้งที่มันคือเบาะแสเดียวที่เหลืออยู่ในกรณีนี้
//
// ที่นี่จึงเรียงลำดับความจริงไว้ชัด ๆ: ข้อความจาก handler > ความหมายของ status >
// ค่าสำรอง — และแนบเลข status ต่อท้ายเสมอเพื่อให้แจ้งปัญหาแล้วตามต่อได้ทันที
//
// client-safe: ไม่มี import อะไรเลย (ใช้ได้ทั้งใน component และ lib ฝั่ง client)

// ความหมายของ status ที่ผู้ใช้อ่านแล้วรู้ว่าต้องทำอะไรต่อ — เขียนโดยไม่มีขีดคั่น
// เพราะตัวประกอบข้อความด้านล่างใส่ " — " ให้อยู่แล้ว
const STATUS_REASON = {
  400: 'ข้อมูลที่ส่งไปไม่ถูกต้อง',
  401: 'เซสชันหมดอายุหรือยังไม่ได้เข้าสู่ระบบ ลองเข้าสู่ระบบใหม่',
  403: 'บัญชีนี้ไม่มีสิทธิ์ทำรายการนี้',
  404: 'ไม่พบปลายทางของคำขอ',
  408: 'เซิร์ฟเวอร์ใช้เวลานานเกินไป',
  // ⭐ ตัวสำคัญของสายอัปโหลด: เพดานขนาดคำขออาจถูกบังคับที่ชั้นที่อยู่ **หน้า** แอป
  // (โฮสติ้ง/เกตเวย์) ซึ่งตัดทิ้งก่อนที่ด่านขนาดของเราเองจะได้ทำงาน ⇒ ผู้ใช้ที่เลือก
  // ไฟล์ผ่านด่าน UI มาแล้วยังเจอ 413 ได้ และต้องรู้ว่าให้ไปบีบไฟล์ ไม่ใช่ลองกดซ้ำ
  413: 'ไฟล์ใหญ่เกินกว่าที่เซิร์ฟเวอร์รับได้ ลองบีบไฟล์ให้เล็กลงแล้วแนบใหม่',
  415: 'ชนิดไฟล์นี้ไม่รองรับ',
  429: 'มีคำขอถี่เกินไป รออีกสักครู่แล้วลองใหม่',
  500: 'เซิร์ฟเวอร์ทำงานผิดพลาด',
  502: 'เซิร์ฟเวอร์ปลายทางไม่ตอบสนอง',
  503: 'ระบบไม่พร้อมให้บริการชั่วคราว',
  504: 'หมดเวลารอเซิร์ฟเวอร์ (ไฟล์ใหญ่หรือเครือข่ายช้า)',
};

function parseJsonBody(raw) {
  if (!raw) return null;
  try {
    return JSON.parse(raw);
  } catch {
    // HTML/text จากชั้น platform — ไม่เอาเนื้อหามาโชว์ (เป็นหน้า error ยาว ๆ
    // ที่อ่านไม่รู้เรื่องและอาจยาวเป็นหมื่นตัวอักษร) ใช้แค่ status ก็พอ
    return null;
  }
}

// ข้อความบอกสาเหตุของ response ที่ !ok — เรียกเฉพาะตอนล้มเหลว (มันกินตัว body)
//   fallback = สิ่งที่ผู้ใช้กำลังทำอยู่ เช่น `อัปโหลด ${file.name} ไม่สำเร็จ`
export async function describeResponseError(res, fallback = 'ทำรายการไม่สำเร็จ') {
  const raw = await res?.text?.().catch(() => '') ?? '';
  const payload = parseJsonBody(raw);

  // 1) ข้อความที่ handler ของเราตั้งใจเขียนถึงผู้ใช้ — ตรงที่สุดเสมอ ใช้ทั้งดุ้น
  const fromHandler = typeof payload?.error === 'string' ? payload.error.trim() : '';
  if (fromHandler) return fromHandler;

  // 2) ไปไม่ถึง handler (หรือ handler ไม่ได้ใส่ error มา) — เหลือ status เป็นเบาะแส
  const status = Number(res?.status) || 0;
  const reason = STATUS_REASON[status];
  const code = status ? ` (HTTP ${status})` : '';
  return reason ? `${fallback} — ${reason}${code}` : `${fallback}${code}`;
}
