// ── สวิตช์ "ขั้นเข้าติดตั้ง" (`SERVICE_INSTALL_STEP`) — ฝั่ง server เท่านั้น ───────────────────────
//
// ⭐ **ตัวอ่านสวิตช์ตัวเดียวของทั้งระบบ** — `process.env.SERVICE_INSTALL_STEP` ห้ามโผล่ที่ไฟล์อื่น
//   (แผน docs/service-install-step.md §5 · ท่าเดียวกับ `surveyDrawingFlag.js`)
//
// 🔴 **import ได้เฉพาะไฟล์ใต้ `src/app/api/`** — ตัวแปรที่ไม่ขึ้นต้น `NEXT_PUBLIC_` เป็น `undefined` บนเบราว์เซอร์
//   ⇒ จอจะอ่านว่า "ปิด" เสมอแล้วเถียงกับ server · จอรู้ค่านี้จาก payload ของ GET ใบสั่งขาย (`installStepEnabled`)
//
// ⚠️ **สวิตช์คุมแค่ของที่ผู้ใช้ทำได้ใหม่** (ตั้งธงงวด · ขอคิว · ยืนยันวัน · คอนเฟิร์มลูกค้า) — ตัวตัดสินที่อ่านจาก
//   แถวที่เกิดแล้ว (ด่านมัดจำ · ด่านนัดติดตั้ง · ขั้นของคำขอ) ทำงานเสมอ: ถอยด้วยการปิดสวิตช์ ไม่ใช่ถอยกติกา
//   (งานที่เดินไปแล้วต้องเดินถูกแม้สวิตช์ถูกปิดทีหลัง)

/**
 * เปิดใช้ขั้นเข้าติดตั้งไหม — เปิดด้วยคำว่า `on` **คำเดียว** (ไม่สนตัวพิมพ์/ช่องว่างหัวท้าย)
 * ⚠️ ค่าอื่นทุกค่า (`1` · `true` · ว่าง · ไม่ตั้ง) = ปิด — พิมพ์เพี้ยนต้องไม่กลายเป็นเปิด
 */
export function installStepEnabled() {
  return String(process.env.SERVICE_INSTALL_STEP ?? '').trim().toLowerCase() === 'on';
}
