// 🐞 **ที่มา**: ก่อนไฟล์นี้ ระบบมีนิยาม "นัดที่ยังมีชีวิต" อยู่ **ห้าชุดที่ไม่เท่ากัน**
// และไม่มีชุดไหนอ้างอิงกันเลย —
//   1. `isLive` ใน rounds.js        = scheduled | done   (ภาระรายวัน · เวลาทับ · ข้ามเขต)
//   2. `OPEN_STATUSES` ใน overview  = scheduled          (ตัวเลขหัวจอ · คิวต้องจัดการ)
//   3. ตัวกรองใน groupVisits        = ตัด cancelled/rescheduled แล้วใช้ !== done เป็น "ค้าง"
//   4. `.eq('status','done')`       ใน visitsRepo (วันเติมล่าสุด)
//   5. `.eq('status','scheduled')`  ใน visitsRepo (นัดครั้งหน้า)
// ⇒ เพิ่มสถานะใหม่ทีเดียว 4 ค่าโดยไม่รวมนิยามก่อน จะได้ผลลัพธ์ห้าแบบในหน้าเดียวกัน
// และ "ตัวเลขบนหัวจอ" กับ "แถวในตาราง" จะไม่ตรงกันแบบที่ไม่มีเทสต์ไหนจับได้
//
// สายสถานะ (มติ docs/service-field-operations.md ข้อ 4):
//   draft ─[ผ่านด่าน]─▶ scheduled ─[เริ่มงาน]─▶ in_progress ─[ปิดงาน]─▶ done
