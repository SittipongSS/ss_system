/* สถานะที่ **เลือกจากฟอร์มด้วยมือได้**
   ⚠️ ตัดสามค่าออกโดยเจตนา: `in_progress` · `done` · `partial` เกิดจาก **ปุ่มที่ประทับเวลา**
   เท่านั้น ถ้าปล่อยให้เลือกจากดรอปดาวน์ ทั้งเจตนาของการ stamp ที่ server ก็หมดความหมาย
   (ปุ่ม "เริ่มงาน" ไม่ได้เพิ่มข้อมูลใหม่ มันทำให้ช่องที่มีอยู่แล้วเชื่อถือได้ — มติข้อ 5)
   `unable` เลือกมือได้เพราะเป็นทางออกที่ต้องมีเมื่อไปแล้วทำไม่ได้ แต่ DB บังคับเหตุผล */
export const VISIT_STATUSES_MANUAL = ['draft', 'scheduled', 'unable', 'rescheduled', 'cancelled'];

// ── สามคำถามที่ทั้งโมดูลต้องตอบเหมือนกัน ────────────────────────────────

/* "ร่าง" — ยังไม่ผ่านด่าน ⇒ ไม่ขึ้นตาราง ไม่นับภาระ ไม่โผล่ในงานวันนี้ของเจ้าหน้าที่
   (มติผู้ใช้ 2026-08-28: TS ไม่ใช่ต้นทางของงาน) */
export const isDraftVisit = (visit) => visit?.status === 'draft';

/* "อยู่บนตาราง" — กินคิวของเจ้าหน้าที่จริง ⇒ นับภาระ เตือนเวลาทับ เตือนข้ามเขต
   ⚠️ ต้องรวม `in_progress` ด้วย ไม่งั้นภาระของเจ้าหน้าที่จะ**หายไปตอนที่เขากดเริ่มงาน**
   แล้วป้าย "งานแน่น" บนปฏิทินก็หายกลางวันโดยไม่มีใครเข้าใจ
   ⚠️ ต้องรวมสามสถานะปลายทาง (done/partial/unable) เหมือนที่ของเดิมรวม done —
   งานที่ทำไปแล้วยังกินเวลาของวันนั้นอยู่ ไม่ใช่ว่างขึ้นมาเพราะจบแล้ว */
export const isLiveVisit = (visit) => (
  visit?.status === 'scheduled' || visit?.status === 'in_progress'
  || visit?.status === 'done' || visit?.status === 'partial' || visit?.status === 'unable'
);

/* "ปิดจบแล้ว" — ไปถึงไซต์แล้วและได้ข้อสรุป ⇒ ไม่ใช่ของค้างอีกต่อไป
   ⚠️ `partial`/`unable` ต้องอยู่ในชุดนี้ ไม่งั้นจะค้างในกลุ่ม "ค้างอยู่" ของเจ้าหน้าที่ตลอดกาล */
export const isClosedVisit = (visit) => (
  visit?.status === 'done' || visit?.status === 'partial' || visit?.status === 'unable'
);

/* "ยังรอให้ลงมือ" — ตัวเลขหัวจอและคิวต้องจัดการนับจากชุดนี้
   ร่างไม่นับ (ยังไม่ใช่งาน) · ปิด/ยกเลิก/เลื่อนไม่นับ (จบแล้ว) */
export const isOpenVisit = (visit) => (
  visit?.status === 'scheduled' || visit?.status === 'in_progress'
);

/* เลื่อนวันได้ไหม — ร่างยังไม่มีลูกค้ารู้เรื่อง (เปลี่ยนวันไม่ใช่ "การเลื่อน")
   และของที่จบแล้ว/เจ้าหน้าที่ยืนอยู่หน้างานแล้ว ก็ไม่ใช่การเลื่อนเช่นกัน
   🐞 ของเดิมกันแค่ done/cancelled ⇒ แก้วันย้อนหลังของใบ partial จะถูกบังคับกรอกเหตุผล
   แล้วระบบเขียนเธรดว่า "เลื่อนนัด" ทั้งที่ไม่มีการเลื่อนเกิดขึ้น — เธรดนี้เอาไว้ตอบลูกค้า
   การปลอมเหตุการณ์ลงไปแย่กว่าไม่มีเธรด */
export const canRescheduleVisit = (visit) => (
  visit?.status === 'scheduled'
);

/* ── "นัดของใบคำร้อง" — ชุดที่ยามระดับ DB ใช้ (mig 0316) ────────────────────
   ⭐ กติกา **หนึ่งใบ = หนึ่งนัด** ห้ามเฉพาะนัดที่ *ยังมีชีวิต* ซ้ำกัน · นัดที่จบไปแล้ว
      (เข้าแล้ว · ทำไม่ครบ · เข้าไม่ได้ · ยกเลิก · เลื่อนแล้ว) เป็น **ประวัติ** ⇒ ใบเดียว
      มีได้หลายใบตามรอบที่ไปจริง และต้องลงคิวรอบใหม่ได้เสมอ
   ⚠️ **คนละคำถามกับ `isOpenVisit`** ข้างบน ซึ่งเป็นตัวนับ "คิวที่ต้องจัดการ"
      (scheduled|in_progress) — ร่างไม่ขึ้นตัวเลขนั้น แต่ยังเป็นนัดของใบอยู่จริง
      ⇒ ใช้ผิดตัวเมื่อไร ใบที่มีนัดร่างค้างจะลงคิวซ้ำได้แล้วได้นัดสองใบ
   🔴 **ชุดนี้ต้องตรงกับ predicate ของ index `service_visits_survey_open_request_uk`**
      เป๊ะ ๆ (เทสต์ surveyVisit.test.mjs อ่านไฟล์ .sql มาเทียบ) — เพี้ยนเมื่อไรจะได้เคส
      ที่แอปยอมให้สร้างแต่ DB ตีกลับ หรือแอปห้ามทั้งที่ DB ยอม */
export const REQUEST_SLOT_VISIT_STATES = ['draft', 'scheduled', 'in_progress'];

/** นัดใบนี้ยังกินสิทธิ์ "หนึ่งใบ = หนึ่งนัด" อยู่ไหม (null/undefined = ไม่มีนัด) */
export const holdsRequestSlot = (visit) => REQUEST_SLOT_VISIT_STATES.includes(visit?.status);

/* ลบทิ้งได้ไหม — ประวัติการเข้าไซต์คือของมีค่าที่สุดของโมดูล
   🐞 ของเดิมบล็อกเฉพาะ done ⇒ partial/unable/in_progress ลบได้ = ประวัติหาย */
export const canDeleteVisit = (visit) => !isClosedVisit(visit) && visit?.status !== 'in_progress';
