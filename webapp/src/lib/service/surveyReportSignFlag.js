// ⚠️ **สวิตช์ไม่แตะกระดาษที่ออกไปแล้ว** — ตัวเรนเดอร์ตัดสินจากภาพนิ่งของแถวล้วน ๆ (ภาพนิ่งไม่มีคีย์ `signatures` = คำเดิม)
//   ปิดสวิตช์ทีหลัง = การส่งผลและเอกสารฉบับถัดไปกลับไปพิมพ์คำว่า "ลายเซ็นอิเล็กทรอนิกส์" · ฉบับที่ตรึงแล้วไม่ขยับ
import 'server-only';

/**
 * เปิดกติกาลายเซ็นจริงไหม — เปิดด้วยคำว่า `on` **คำเดียว** (ไม่สนตัวพิมพ์/ช่องว่างหัวท้าย)
 * ⚠️ ค่าอื่นทุกค่า (`1` · `true` · ว่าง · ไม่ตั้ง) = ปิด — พิมพ์เพี้ยนต้องไม่กลายเป็นเปิด
 *    (ตัวแกะเดียวกับ `surveyDrawingMethodEnabled` และ `surveyReportIssueAtSend`)
 */
export function surveyReportSignaturesOn() {
  return String(process.env.SURVEY_REPORT_SIGNATURES ?? '').trim().toLowerCase() === 'on';
}
