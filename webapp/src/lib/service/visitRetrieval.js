// ── นัดถอนเครื่องปิดแล้ว ทะเบียนต้องขยับตาม — logic ล้วน (ไม่แตะ DB) ───────────
//
// 🔴 **ของเดิม: ปิดนัด `remove` แล้วทะเบียนไม่ขยับเลย** — เครื่องที่ช่างถือออกจากร้าน
//   ไปแล้วยังเป็น "ใช้งานอยู่" ที่ไซต์ลูกค้าต่อไป ⇒ ทะเบียนเพี้ยนตั้งแต่การใช้จริงครั้งแรก
//   · ป้ายน้ำหอมใกล้หมดยังยิงให้เครื่องที่ไม่อยู่แล้ว · หาเครื่องว่างไปติดที่ใหม่ไม่เจอ
//   และเงียบที่สุด เพราะไม่มีจอไหนพังให้เห็น
//
// ⭐ **ถอน = คำสั่ง `return` ของระบบคำสั่งย้าย ไม่ใช่การเขียนสถานะตรง ๆ** — ได้แถวประวัติ
//   (วันที่ · เหตุผล · คนสั่ง) เหมือนกดจากหน้าเครื่องทุกประการ แล้วเครื่องกลับเป็น "ว่าง"
//   (`in_stock` · ไม่มีไซต์) ตาม CHECK ของ mig 0344 · ม็อกทะเบียนเครื่องจอ "ถอนกลับคลัง"
//   บอกผลปลายทางเดียวกัน (อยู่คลัง · ไม่มีไซต์ · เหตุผลตั้งต้น "ลูกค้าเลิกสัญญา")
//   ⚠️ **ไม่ใช่ `removed`** — ตั้งแต่ 0332 คำนั้นแปลว่าปลดระวาง (จบชีวิตเครื่อง ปุ่มหายหมด)
//
// ⚠️ **ปรับให้ตรง (reconcile) ทุกครั้งที่บันทึกนัดที่ปิดแล้ว ไม่ใช่เฉพาะตอนปิด** —
//   ถ้าผูกกับจังหวะ "ปิด" อย่างเดียว: คำสั่งที่ล้มกลางทางจะไม่มีใครลองใหม่ · และช่างที่
//   กลับมาแก้ "ถอนไม่ได้" เป็น "ถอนแล้ว" ทีหลัง เครื่องจะไม่ขยับ
//   ⇒ ตัดสินจาก **สภาพปัจจุบัน** แทน: ถอนเฉพาะเครื่องที่ผลบอกว่าถอนแล้ว **ยังติดตั้งอยู่ที่
//     ไซต์นี้** และ **นัดนี้ยังไม่เคยถอนมัน** (ตราบนแถวประวัติ — ดู `retrievalMark`)
//     ⇒ ยิงซ้ำกี่รอบก็ได้ผลเท่าเดิม และไม่ถอนทับเครื่องที่คนติดตั้งคืนเพื่อแก้การถอนผิด
import { assetMoveError } from './assetMoves';
import { VISIT_STATUS_LABELS, isClosedVisit } from './visitStatus';
import { REMOVE_VISIT_KIND } from './visitAssets';

/** นัดนี้ต้องขยับทะเบียนไหม — ใช้ค่า **หลังแก้** ของใบ
 *  ⚠️ `unable` (ชิป "ไปแล้วเข้าไม่ได้") ไม่ถอน — แผ่นปิดงานข้ามการบันทึกผลรายเครื่อง
 *     ในทางนั้น ⇒ แถว "ถอนแล้ว" ที่ค้างจากการกดครั้งก่อน (บันทึกผลสำเร็จแต่ปิดใบล้ม)
 *     จะพาเครื่องออกจากไซต์ทั้งที่ใบบอกว่าเข้าไม่ได้ */
export function retrievalApplies(before, after) {
  return before?.kind === REMOVE_VISIT_KIND && after?.kind === REMOVE_VISIT_KIND
    && isClosedVisit(after) && after.status !== 'unable';
}

/* ── ตราประจำนัดบนแถวประวัติ — "นัดนี้ถอนเครื่องนี้ไปแล้ว" ───────────────────
   🔴 **สภาพปัจจุบันอย่างเดียวไม่พอเป็นตัวกันถอนซ้ำ** — ถ้าถอนผิดเครื่อง ผู้จัดคิวสั่ง
     "ติดตั้งเข้าไซต์" คืน (ซึ่งเป็นทางแก้ที่จอบอกเอง) ⇒ เครื่องกลับมา "ใช้งาน" ที่ไซต์เดิม
     และผลของนัดยังเป็น "ถอนแล้ว" ⇒ ใครบันทึกนัดใบนี้ซ้ำเมื่อไร (แก้สรุป · แนบรูป)
     เครื่องจะถูกถอนออก **อีกรอบเงียบ ๆ** · ด่านวันที่จับไม่ได้ถ้าติดตั้งคืนวันเดียวกัน
   ⇒ นัดหนึ่งใบถอนเครื่องหนึ่งตัวได้ **ครั้งเดียว** — ดูจากแถวประวัติที่นัดนี้เขียนไว้
   ⚠️ เก็บใน `note` (ไม่ได้แสดงบนจอ) ด้วย **id ของนัด** ซึ่งไม่เปลี่ยน ไม่ใช่รหัส SV
      · ไม่มีคอลัมน์ `visitId` บนตารางประวัติ (เพิ่มต้องมี migration) */
export const retrievalMark = (visit = {}) => `(${visit.id})`;

/** เหตุผล/โน้ตที่ติดไปกับแถวประวัติของเครื่อง
 *  ⭐ เหตุผลต้องบอก **ที่มา** — คนเปิดหน้าเครื่องทีหลังต้องรู้ว่าทำไมมันถึงออกจากไซต์
 *    (โน้ตของนัดถอนที่ระบบสร้างให้คือ "ลูกค้าไม่ต่อสัญญาบริการ — …" อยู่แล้ว) */
export function retrievalInput(visit = {}) {
  const code = visit.code || visit.id || '';
  const why = String(visit.note ?? '').trim();
  return {
    movedAt: visit.actualDate || null,
    reason: `ถอนตามนัด ${code}${why ? ` — ${why}` : ''}`.slice(0, 500),
    note: `ถอนตามนัด ${code} ${retrievalMark(visit)}`.slice(0, 1000),
  };
}

/** เครื่องที่นัดนี้ถอนไปแล้ว **และมีคนติดตั้งคืนทีหลัง** — ห้ามถอนทับ
 *  🐞 นับแค่ "มีแถว return ที่มีตรา" ไม่พอ — `commitAssetMove` คงแถวประวัติไว้เมื่อ update
 *    เครื่องล้มแบบไม่รู้ผล ⇒ แถวค้างแถวนั้นจะทำให้ทุกการลองใหม่เชื่อว่า "ถอนแล้ว" แล้วข้าม
 *    ⇒ เครื่องค้างที่ไซต์ถาวร · ทางแก้ของคนคือ **ติดตั้งคืน** เท่านั้น ⇒ ต้องเห็นแถว install/
 *    transfer ที่เกิด **หลัง** แถว return ที่มีตรา ถึงจะนับว่าเป็นการแก้ของคน
 *  @param moves แถวประวัติ kind return/install/transfer ของเครื่องที่ผลบอกว่าถอนแล้ว */
export function retrievedByVisit(moves = [], visit = {}) {
  const mark = retrievalMark(visit);
  const at = (m) => String(m?.createdAt || m?.movedAt || '');
  const out = new Set();
  for (const ret of moves || []) {
    if (ret?.kind !== 'return' || !String(ret.note ?? '').includes(mark)) continue;
    const reinstalled = (moves || []).some((m) => m?.assetId === ret.assetId
      && (m.kind === 'install' || m.kind === 'transfer') && at(m) > at(ret));
    if (reinstalled) out.add(ret.assetId);
  }
  return out;
}

/**
 * แผนถอนของนัดหนึ่งใบ — คืน `{ moves, blocked, skipped }`
 *   moves   = `[{ asset, input }]` ที่ต้องสั่ง `return`
 *   blocked = `[{ asset, error }]` ติดด่าน ⇒ ต้องตีกลับทั้งคำขอ **ก่อนเขียนใบ**
 *   skipped = `[{ asset, error }]` นัดนี้ถอนไปแล้วและมีคนติดตั้งคืน ⇒ ข้ามเงียบ ๆ
 *
 * ⚠️ **ตัดสินรายเครื่อง ไม่ใช่ตามจังหวะ "ปิดครั้งแรก"** — เครื่องที่ผลบอกว่าถอนแล้ว ยัง
 *   ติดตั้งอยู่ที่นี่ และนัดนี้ยังไม่เคยถอน = ทะเบียนกับผลขัดกันจริง ไม่ว่าจะเป็นการปิดครั้งแรก
 *   หรือการแก้ "ถอนไม่ได้" → "ถอนแล้ว" ทีหลัง (หรือใบที่เคยปิดว่าเข้าไม่ได้) ⇒ ติดด่านเมื่อไร
 *   ต้องดังให้แก้ ไม่ใช่ข้ามแล้วปล่อยเครื่องค้างที่ไซต์ทั้งที่ใบบอกว่าถอนแล้ว
 *   🐞 รุ่นแรกแยกด้วย "ปิดครั้งแรกหรือเปล่า" ⇒ ใบที่เคยปิดเป็น `unable` แล้วมาแก้เป็นถอนแล้ว
 *     (ซึ่งยังไม่เคยถอนอะไรเลย) ติดด่านวันที่แบบเงียบ ๆ
 *
 * @param visit       นัด **หลังแก้** (ต้องมี id · siteId · actualDate · code)
 * @param results     แถวผลรายเครื่องของนัดนี้ในฐาน
 * @param siteAssets  `loadAssets(visit.siteId)`
 * @param priorMoves  แถวประวัติ return/install/transfer ของเครื่องที่ผลบอกว่าถอนแล้ว
 */
export function retrievalPlan({ visit, results = [], siteAssets = [], priorMoves = [] } = {}) {
  const out = { moves: [], blocked: [], skipped: [] };
  if (!visit?.siteId) return out;

  const done = new Set((results || []).filter((r) => r?.outcome === 'done').map((r) => r.assetId));
  const already = retrievedByVisit(priorMoves, visit);
  const input = retrievalInput(visit);

  for (const asset of siteAssets || []) {
    if (!done.has(asset.id)) continue;
    // ถอนได้เฉพาะเครื่องที่ยังติดตั้งอยู่ **ที่ไซต์ของนัดนี้** — ที่เหลือคือถอนไปแล้ว/ย้ายไปแล้ว
    if (asset.status !== 'active' || asset.siteId !== visit.siteId) continue;
    // นัดนี้ถอนตัวนี้ไปแล้ว แล้วมีคนติดตั้งคืน = การแก้ของคน ห้ามถอนทับ
    if (already.has(asset.id)) {
      out.skipped.push({ asset, error: 'นัดนี้ถอนเครื่องนี้ไปแล้วครั้งหนึ่ง — ถูกติดตั้งคืนภายหลัง' });
      continue;
    }

    /* 🔑 ด่านตัวเดียวกับปุ่ม "ถอดออกจากไซต์" ที่หน้าเครื่อง
       ⚠️ `canEdit: true` ไม่ใช่การข้ามสิทธิ์ — ผู้เรียก (route ของนัด) ผ่าน `requireVisit`
          มาแล้ว: ช่างที่ถูกมอบหมายนัดนี้ ถอนเครื่องของไซต์นี้ = งานของเขาพอดี
          (เส้นคำสั่งย้ายปิดสำหรับ role `ts` เพราะมันเปิดให้ย้ายเครื่อง **ไหนก็ได้**) */
    const error = assetMoveError(asset, 'return', input, { canEdit: true });
    if (!error) out.moves.push({ asset, input });
    else out.blocked.push({ asset, error });
  }
  return out;
}

/** id ของเครื่องที่ต้องโหลดประวัติมาเช็คตรา — เครื่องที่ผลบอกว่าถอนแล้ว */
export function retrievalCandidateIds(results = []) {
  return [...new Set((results || []).filter((r) => r?.outcome === 'done').map((r) => r.assetId).filter(Boolean))];
}

/** ข้อความของเครื่องที่ติดด่านตอนปิด — บอกว่าเครื่องไหน ติดอะไร และใครแก้ได้ */
export function retrievalBlockedMessage(blocked = []) {
  if (!blocked.length) return null;
  const list = blocked.map(({ asset, error }) => `${asset.label || asset.code || asset.id} (${error})`).join(' · ');
  return `ถอนเครื่องออกจากไซต์ไม่ได้ ${blocked.length} เครื่อง — ${list}`
    + ' · ให้ผู้จัดคิวแก้วันติดตั้งที่หน้าเครื่องก่อน แล้วค่อยปิดงานอีกครั้ง';
}

/* ── เปลี่ยนชนิดของนัดเข้า/ออกจาก "ถอนเครื่อง" ไม่ได้ เมื่อมีผลรายเครื่องแล้ว ──────
   🔴 นัดเติมน้ำหอมที่ปิดแล้วมีผล "ทำแล้ว" ทุกเครื่อง · ถ้าผู้จัดคิวเปลี่ยนชนิดเป็น
     "ถอนเครื่อง" แล้วบันทึก ⇒ ผลชุดเดิมกลายเป็น "ถอนแล้ว" ทันที = ถอนเครื่องทั้งไซต์
     ออกจากทะเบียนทั้งที่ไม่มีใครไปถอดจริง
   ⚠️ ขาออกก็ปิดด้วย — นัดถอนที่ถอนเครื่องไปแล้วถูกเปลี่ยนเป็นงานอื่น ประวัติของเครื่อง
     จะบอกว่า "ถอนตามนัด SV-…" ที่ตอนนี้กลายเป็นงานเติมน้ำหอม
   🐞 รุ่นแรกดูแค่ "ปิดแล้วหรือยัง" ⇒ เปิดใบกลับเป็น "กำลังทำ" ก่อน (สถานะไม่ใช่ช่องของแผน
     ช่างก็ทำได้) แล้วค่อยเปลี่ยนชนิด = ข้ามด่านได้ ⇒ ดู **ผลรายเครื่องที่มีอยู่** ด้วย
   @param hasResults นัดนี้มีแถวผลรายเครื่องในฐานแล้วหรือยัง */
export function retrievalKindSwitchError(before, next, { hasResults = false } = {}) {
  if (!next?.kind || next.kind === before?.kind) return null;
  if (before?.kind !== REMOVE_VISIT_KIND && next.kind !== REMOVE_VISIT_KIND) return null;
  if (!isClosedVisit(before) && !hasResults) return null;
  return next.kind === REMOVE_VISIT_KIND
    ? 'นัดที่มีผลรายเครื่องแล้วเปลี่ยนเป็นงานถอนเครื่องไม่ได้ — ผลเดิมจะกลายเป็น "ถอนแล้ว" ทั้งไซต์ · สร้างนัดถอนเครื่องใบใหม่แทน'
    : 'นัดถอนเครื่องที่มีผลรายเครื่องแล้วเปลี่ยนเป็นงานชนิดอื่นไม่ได้ — ประวัติของเครื่องอ้างนัดนี้ว่าเป็นงานถอน';
}

/* ── นัดถอนที่ถอนเครื่องออกไปแล้ว ต้องปิดเป็น "เข้าแล้ว/ทำไม่ครบ" ตลอดไป ──────────
   ใบจะบอกว่าเข้าไม่ได้ · ยกเลิก · หรือยังไม่ได้ไป ขณะที่ทะเบียนบอกว่าเครื่องออกจากไซต์ด้วย
   นัดนี้ = สองที่พูดขัดกัน
   🐞 รุ่นแรกกันแค่ "ไปแล้วเข้าไม่ได้" ⇒ เปลี่ยนเป็น "ยกเลิก" ได้ แล้วนัดที่ยกเลิกลบทิ้งได้
     (`canDeleteVisit`) — แถวผลรายเครื่องหายตาม CASCADE ทั้งที่แช่แข็งไว้ว่าลบไม่ได้
   ⇒ กันทุกสถานะที่ไม่ใช่ "เข้าแล้ว/ทำไม่ครบ" · ลบก็ไม่ได้ตามไปเอง (ใบปิดแล้วลบไม่ได้อยู่แล้ว)
   @param visit นัด **หลังแก้** · results = แถวผลในฐาน · siteAssets = `loadAssets(visit.siteId)` */
const RETRIEVED_STATUSES = ['done', 'partial'];

export function retrievalStatusLockError(visit, results = [], siteAssets = []) {
  if (visit?.kind !== REMOVE_VISIT_KIND || RETRIEVED_STATUSES.includes(visit.status)) return null;
  const live = new Set((siteAssets || []).filter((a) => a.status === 'active').map((a) => a.id));
  const gone = (results || []).filter((r) => r?.outcome === 'done' && !live.has(r.assetId)).length;
  if (!gone) return null;
  return `นัดนี้ถอนเครื่องออกจากไซต์ไปแล้ว ${gone} เครื่อง — เปลี่ยนเป็น "${VISIT_STATUS_LABELS[visit.status] || visit.status}" ไม่ได้`
    + ' · ถ้าถอนผิด ให้ผู้จัดคิวสั่ง "ติดตั้งเข้าไซต์" ที่หน้าเครื่อง';
}
