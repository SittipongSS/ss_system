//
// ⭐ **ตัวอ่านสวิตช์ตัวเดียวของทั้งระบบ** — `process.env.SURVEY_DRAWING_METHOD` ห้ามโผล่ที่ไฟล์อื่น
//   (แผน survey-desk-assessment §7 · สเปก S1 §4)
//
// 🔴 **import ได้เฉพาะไฟล์ใต้ `src/app/api/`** — โมดูลที่จอ import (การ์ดควบคุม · โมดัลยืนยัน · ตัวตัดสินล้วน)
//   ห้ามดึงไฟล์นี้: ตัวแปรที่ไม่ขึ้นต้น `NEXT_PUBLIC_` เป็น `undefined` บนเบราว์เซอร์ ⇒ จอจะอ่านว่า "ปิด" เสมอ
//   แล้วเถียงกับ server · จอรู้ค่านี้จาก payload ของ GET เท่านั้น (ท่าเดียวกับ `document.issueAtSend`)
//
// ⚠️ **สวิตช์คุมแค่ของที่ผู้ใช้ทำได้ใหม่** (งวด S1 = ด่านส่งผลแถว 17a ตัวเดียว) — กติกาที่อ่านจากแถวพื้นที่
//   (ด่านรายหัวข้อ · คิว · ราง · กระดาษ) ทำงานเสมอไม่ว่าเปิดหรือปิด: แถวที่เป็น `'drawing'` ไปแล้วต้องเดินถูก
//   แม้สวิตช์ถูกปิดทีหลัง (ถอยด้วยการปิดสวิตช์ ไม่ใช่ถอยกติกา — หัว mig 0408)

/**
 * เปิดใช้การประเมินจากแบบไหม — เปิดด้วยคำว่า `on` **คำเดียว** (ไม่สนตัวพิมพ์/ช่องว่างหัวท้าย)
 * ⚠️ ค่าอื่นทุกค่า (`1` · `true` · ว่าง · ไม่ตั้ง) = ปิด — พิมพ์เพี้ยนต้องไม่กลายเป็นเปิด
 *    (ตัวแกะเดียวกับ `surveyReportIssueAtSend` ใน `surveyReportRows.js`)
 */
export function surveyDrawingMethodEnabled() {
  return String(process.env.SURVEY_DRAWING_METHOD ?? '').trim().toLowerCase() === 'on';
}
