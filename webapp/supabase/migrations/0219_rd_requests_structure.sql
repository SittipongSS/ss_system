BEGIN;

-- ────────────────────────────────────────────────────────────────────────────
-- 1) ลบหัวข้อขอราคาทั้งสามและใบที่ใช้หัวข้อนั้น (ม-28)
--
--    ราคากลายเป็น **ขั้นสุดท้ายของพัฒนากลิ่นและพัฒนาสูตร** ไม่ใช่คำร้องคนละใบ
--    ⇒ หัวข้อพวกนี้ไม่มีทางเดินถึงอีกแล้ว
--
--    ⚠️ `guard_dept_request` ห้ามลบใบที่ส่งแล้ว (docNo ที่ออกไปแล้วต้องตามกลับมา
--    อ่านได้) — ที่นี่จงใจข้ามด่านนั้นเพราะเป็นการ **ถอนหัวข้อทั้งหัวข้อ** ไม่ใช่
--    การลบใบทีละใบ · `SET LOCAL` หมดผลเมื่อจบ transaction เอง
--
--    ⚠️ `/sa/costing` (ขอราคาผลิต) เป็นคนละระบบ **ห้ามแตะ** — มันใช้ตาราง
--    costing_requests ของตัวเอง ไม่เกี่ยวกับ dept_requests
-- ────────────────────────────────────────────────────────────────────────────
SET LOCAL app.force_delete = '1';

DELETE FROM public.dept_requests
 WHERE kind IN ('price_f', 'price_fb', 'price_pm');
-- บรรทัดและชั้นจำนวนตามไปเองผ่าน ON DELETE CASCADE (0158:74, 0158:111)

-- ────────────────────────────────────────────────────────────────────────────
-- 2) ชั้นจำนวนไม่มีหัวข้อไหนใช้แล้ว — `price_pm` เป็นตัวเดียวที่ `hasTiers: true`
--
--    โมเดลใหม่ของ RD ใส่ **ราคาเดียวไม่มีชั้นจำนวน** (แบบหน้าจอ §07: "หัวน้ำหอม
--    คิดต่อกิโลตรง ๆ") ⇒ เก็บตารางไว้คือเก็บของที่ไม่มีทางมีแถว
--
--    ⚠️ ต้องเพิ่มชื่อตารางนี้ใน src/lib/droppedTables.test.mjs ในคอมมิตเดียวกัน
--    ไม่งั้นเทสต์ที่คอยจับ "โค้ดยังเรียกตารางที่ถูก DROP ไปแล้ว" จะไม่รู้จักมัน
-- ────────────────────────────────────────────────────────────────────────────
DROP TABLE IF EXISTS public.dept_request_item_tiers;

-- ────────────────────────────────────────────────────────────────────────────
-- 3) `product_dev` → `formula_dev` · scope `MU` → `FD` (ม-26)
--
--    ปลายทางของหัวข้อนี้คือ **ทะเบียนสูตร** ทั้ง key และเลขที่เอกสารควรพูดเรื่อง
--    เดียวกัน · `MU` เป็นซากของคำว่า Mock-up ที่มติ ม-3 เลิกใช้ไปสองรอบแล้ว
--
--    ⭐ ทำได้ฟรี**เฉพาะตอนนี้** — หัวข้อนี้มี 0 แถวและยังไม่เคยออกเลขที่สักใบ
--    มีใบแรกเมื่อไรก็เปลี่ยนไม่ได้อีก เพราะ docNo เป็น immutable (guard)
--
--    ⚠️ ไม่แตะ docNo ของแถวที่มีอยู่ — ถ้า staging มีใบ MU-… อยู่จริง เลขเดิม
--    คงไว้ตามกฎ immutable · เลขใหม่เท่านั้นที่ขึ้นต้น FD
-- ────────────────────────────────────────────────────────────────────────────
UPDATE public.dept_requests SET kind = 'formula_dev' WHERE kind = 'product_dev';

-- ────────────────────────────────────────────────────────────────────────────
-- 4) `1 SO : 1 PDR` — บังคับที่ฐานข้อมูล ไม่ใช่กฎที่คนต้องจำ (ม-37)
--
--    แบบหน้าจอเขียนไว้เอง: "อยากได้เพิ่มต้องออก SO ใหม่ · บังคับถึงระดับ
--    ฐานข้อมูล ⇒ เปิดซ้ำไม่ได้เชิงโครงสร้าง"
--
--    ⭐ **partial** — `WHERE status <> 'cancelled'` ⇒ ใบที่กรอกผิดแล้วยกเลิกทิ้ง
--    เปิดใหม่บน SO เดิมได้ · เคสนี้จะเกิดแน่ในสัปดาห์แรกที่ใช้จริง
--
--    ⭐ ผูก `kind = 'scent_dev'` ไว้ด้วย — PDR มีเฉพาะหัวข้อนี้ · หัวข้ออื่นที่
--    วันหนึ่งอาจอ้าง SO (เช่นขอเอกสารของ SO ใบหนึ่ง) ต้องไม่ถูกกฎนี้กิน
--
--    ⚠️ index เดิม `dept_requests_so_idx` (0195:47) เป็นตัวค้นหา ไม่ใช่ตัวบังคับ —
--    คงไว้ ไม่ทับกัน
-- ────────────────────────────────────────────────────────────────────────────
CREATE UNIQUE INDEX IF NOT EXISTS dept_requests_pdr_so_uk
  ON public.dept_requests ("salesOrderId")
  WHERE "salesOrderId" IS NOT NULL
    AND kind = 'scent_dev'
    AND status <> 'cancelled';

COMMENT ON INDEX public.dept_requests_pdr_so_uk IS
  '1 SO : 1 PDR — ใบสั่งขายออกแบบกลิ่นหนึ่งใบเปิดคำร้องพัฒนากลิ่นได้ใบเดียว '
  '(ยกเลิกแล้วเปิดใหม่ได้) · มติผู้ใช้ 2026-08-07 ม-37';

COMMIT;
