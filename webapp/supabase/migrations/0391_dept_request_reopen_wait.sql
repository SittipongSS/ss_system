alter table public.dept_requests
  add column if not exists "reopenWaitSide" text,
  add column if not exists "reopenedAt"     timestamptz;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'dept_requests_reopen_wait_side_chk'
  ) then
    alter table public.dept_requests
      add constraint dept_requests_reopen_wait_side_chk
      check ("reopenWaitSide" is null or "reopenWaitSide" in ('dept', 'requester'));
  end if;
end $$;

