--
-- ต่อจาก 0219 · มติผู้ใช้ 2026-08-07 (ต่อท้าย ม-28)
--
-- ⭐ สองหัวข้อนี้ติดธง `legacy` มาตั้งแต่รอบก่อน — เปิดใบใหม่ไม่ได้แล้ว แต่ยังอยู่ใน
-- ทะเบียนเพื่อให้ **ใบเก่าบน prod มีป้ายชื่ออ่านได้** · เหตุผลนั้นหมดอายุแล้ว:
--
--   `dept_requests` = **1 แถว** ทั้งตาราง (`scent_dev` · `answered`)
--   ⇒ `scent_brief` = 0 แถว · `mockup` = 0 แถว · **ไม่มีใบไหนต้องอ่านป้ายนั้น**
--
-- ⇒ ลบทั้งไฟล์ `lib/requests/kinds/rd/legacy.js` · ธง `legacy` ในทะเบียนยังอยู่
--   (เป็นกลไกสำหรับหัวข้อที่จะเลิกใช้ในอนาคต ไม่ใช่ของเฉพาะสองตัวนี้)
--
-- ⚠️ ไฟล์นี้เป็น **no-op บน prod** — เขียนไว้เพื่อ staging และเพื่อให้มีร่องรอยว่า
-- หัวข้อถูกถอดเมื่อไรด้วยเหตุผลอะไร · ถ้า staging มีใบของสองหัวข้อนี้อยู่จริง
-- **ให้หยุดแล้วถามก่อน** อย่ารันทับ — ใบที่ออกเลขที่ไปแล้วคือหลักฐาน
--
-- ⚠ รันมือบน Supabase SQL Editor · รันหลัง 0219

BEGIN;

-- ตรวจก่อนลบ: มีใบของหัวข้อที่กำลังจะถอดไหม — มีเมื่อไรให้ migration ล้มทั้งใบ
-- แทนที่จะลบเงียบ ๆ (ต่างจาก 0219 ที่ผู้ใช้สั่งลบใบขอราคาไปด้วยอย่างชัดเจน)
DO $$
DECLARE n integer;
BEGIN
  SELECT count(*) INTO n FROM public.dept_requests
   WHERE kind IN ('scent_brief', 'mockup');
  IF n > 0 THEN
    RAISE EXCEPTION 'ยังมีคำร้องหัวข้อ scent_brief/mockup อยู่ % ใบ — หยุดแล้วถามก่อน '
      'ว่าจะย้ายไป scent_dev/formula_dev หรือเก็บไว้อ่าน (ตอนนับ prod 2026-08-07 = 0)', n;
  END IF;
END $$;

COMMIT;
