-- ⚠️ ใบนี้เคยเป็น 0233 และ **ถูกรันบนฐานจริงไปแล้ว 2026-08-12** ก่อนที่ #1176
-- (`0233_lead_budget_range.sql`) จะเข้า main ด้วยเลขเดียวกัน จึงเลื่อนมาเป็น 0234
-- ทุกคำสั่งในไฟล์นี้รันซ้ำได้ไม่เสียหาย (`IF NOT EXISTS` + UPDATE ที่เล็งเฉพาะแถวที่ยังว่าง)
-- ⇒ รันซ้ำเพื่อความสบายใจได้ ไม่ต้องกลัวข้อมูลเพี้ยน
--
-- ⭐ **`screenedAt` ตัวเดียวรับสองหน้าที่ที่ต้องการค่าคนละตัวหลังตีกลับ** — มันเป็นทั้ง
-- *จุดจบ* ของด่านคัดกรอง (createdAt → screenedAt) และ *จุดเริ่ม* ของด่านกระจาย
-- (screenedAt → assignedAt) พอตีกลับแล้วคัดใหม่ ค่าที่ถูกของสองด่านนี้คนละตัว:
-- ด่านคัดกรองอยากได้ครั้งแรก (มติเดิม: rework ไม่ลบผลงานรอบแรก) ส่วนด่านกระจาย
-- อยากได้ครั้งล่าสุด เพราะ Senior AE คนใหม่เริ่มนับจากตอนที่ใบมาถึงมือเขา
--
-- 🐞 ของเดิมเก็บครั้งแรกอย่างเดียว (`lead.screenedAt || now`) ส่วน `assignedAt` เขียนทับ
-- ทุกครั้ง ⇒ ด่านกระจายวัด "คัดกรองครั้งแรก → มอบครั้งล่าสุด" = กินเวลารอบตีกลับทั้งรอบ
-- (เวลาที่ใบไปนอนอยู่กับ AE คนเก่า + เวลารอคัดกรองใหม่) คนที่มอบภายในวันเดียวจึงถูก
-- นับเป็น "ไม่ทัน" โดยไม่มีทางแก้ตัว · เป็นบั๊กพี่น้องกับที่ล้าง `firstContactAt`
-- ตอนตีกลับไปแล้ว (ดูคอมเมนต์ในไฟล์ transition/route.js) แต่ตกด่านกลางไว้
--
-- แบ่งหน้าที่ใหม่:
--   `firstScreenedAt` = คัดกรองครั้งแรกตลอดกาล — ใช้วัด **SLA คัดกรอง** เท่านั้น
--   `screenedAt` · `assignedAt` = **ของรอบปัจจุบัน** ล้างตอนตีกลับ เขียนใหม่ทุกรอบ
--     (แบบเดียวกับ `firstContactAt`/`meetingAt` ที่ล้างอยู่แล้ว)
ALTER TABLE public.sales_leads
  ADD COLUMN IF NOT EXISTS "firstScreenedAt" timestamptz;

-- ใบเก่า: ที่มีอยู่คือ "ครั้งแรก" ตามนิยามเดิมอยู่แล้ว จึงคัดลอกตรง ๆ ได้
UPDATE public.sales_leads
   SET "firstScreenedAt" = "screenedAt"
 WHERE "firstScreenedAt" IS NULL
   AND "screenedAt" IS NOT NULL;

-- ⚠️ ล้างซากของรอบก่อนที่ค้างอยู่ในใบที่ถูกตีกลับกลับไปคิวคัดกรองแล้ว
-- `status = 'new'` = ยังไม่ถูกคัดกรอง/มอบหมายในรอบปัจจุบัน ตามนิยาม ⇒ สองคอลัมน์นี้
-- ต้องว่าง · ของที่ค้างอยู่ทำให้ผัง Funnel นับ "คัดกรองแล้ว/มอบหมายแล้ว" เกินจริง
-- (ตรวจ 2026-08-12: เดือน ส.ค. ผังขึ้น "มอบหมายแล้ว 56" ขณะที่ตาราง AE รวมได้ 54)
-- ประวัติไม่หาย — ทุก transition อยู่ใน `lead_events` ครบ และครั้งแรกอยู่ที่
-- `firstScreenedAt` ที่เพิ่ง backfill ไป
UPDATE public.sales_leads
   SET "screenedAt" = NULL,
       "assignedAt" = NULL
 WHERE status = 'new'
   AND ("screenedAt" IS NOT NULL OR "assignedAt" IS NOT NULL);
