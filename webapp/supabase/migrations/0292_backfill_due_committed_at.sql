-- ⚠️ `acknowledgedAt` เป็น **ขอบล่าง ไม่ใช่ค่าจริง** — วันกำหนดส่งจะถูกให้ก่อนรับเรื่อง
-- ไม่ได้ · ใช้เป็นขอบล่างแล้วผลที่ได้คือ "แถวรอบแก้ที่เกิดหลังรับเรื่อง = ยังไม่มีใคร
-- แจ้งวันให้" ซึ่งเป็นความจริงเสมอสำหรับรอบแก้ที่ยังไม่ได้ส่ง (รอบแก้เกิดหลังการส่ง
-- ของรอบก่อน ซึ่งเกิดหลังรับเรื่องเสมอ)
-- ⚠️ **ประเมินไม่เกินจริง** — ขอบล่างทำให้ "ค้าง" ง่ายกว่าความจริงได้ แต่ทางกลับกัน
-- (พลาดใบที่ค้างจริง) เกิดไม่ได้ · และตั้งแต่ #1406 ปุ่มแจ้ง/เลื่อนวันเขียนค่านี้เอง
-- ทุกครั้ง ⇒ ใบที่เดินต่อจากนี้ได้เวลาจริง ไม่ต้องพึ่งขอบล่างอีก
--
-- ⚠️ `GREATEST` กับ NULL: Postgres คืนค่าที่ไม่ใช่ NULL ⇒ ใบที่มีอย่างใดอย่างหนึ่ง
-- ได้ตัวนั้น · ใบที่ไม่มีทั้งคู่ตกด่าน `IS NOT NULL` ข้างล่าง ยังเป็น NULL ตามเดิม

UPDATE public.dept_requests r
SET "dueCommittedAt" = GREATEST(e.at, r."acknowledgedAt")
FROM (
  SELECT "entityId" AS rid, max("createdAt") AS at
  FROM public.entity_updates
  WHERE "entityType" = 'dept_request'
    AND kind IN ('commitDue', 'reschedule')
  GROUP BY "entityId"
) e
WHERE r.id = e.rid
  AND r."dueCommittedAt" IS NULL;

-- ใบที่ไม่มีเหตุการณ์ในเธรดเลย แต่รับเรื่องแล้วและมีวันกำหนดส่ง — ใช้ขอบล่างล้วน
-- (SB-26080008 อยู่กลุ่มนี้: วันมาจากทางเก่าตอนที่รับเรื่อง+แจ้งวันยังเป็นก้าวเดียวกัน)
UPDATE public.dept_requests r
SET "dueCommittedAt" = r."acknowledgedAt"
WHERE r."dueCommittedAt" IS NULL
  AND r."acknowledgedAt" IS NOT NULL
  AND r."committedDueDate" IS NOT NULL;
