-- คีย์ที่ใช้เทียบว่า "เลขเดียวกันไหม": ถอดตัวคั่นทิ้ง · 12 หลักล้วน = ศูนย์นำหน้าหาย
-- ⇒ เติมคืน · ค่าที่มีตัวอักษร (เลขต่างชาติ/พาสปอร์ต) เทียบทั้งก้อนแบบตัวพิมพ์ใหญ่
-- immutable + strict = ใช้ในนิพจน์ของ index ได้ และค่า null คืน null (ไม่ถูกนับว่าซ้ำ)
create or replace function public.tax_id_key(value text)
returns text
language sql
immutable
strict
as $$
  select case
    when t.key = '' then null
    when t.key ~ '^[0-9]{12}$' then '0' || t.key
    else t.key
  end
  from (select upper(regexp_replace(value, '[^0-9A-Za-z]', '', 'g')) as key) t
$$;

-- สร้างตัวใหม่ก่อน แล้วค่อยทิ้งตัวเก่า — ถ้าคำสั่งนี้ล้มเพราะยังมีเลขซ้ำ ทะเบียนจะยัง
-- เหลือด่านเดิมคุ้มอยู่ ไม่ใช่ไม่เหลืออะไรเลย
create unique index if not exists customers_taxid_key
  on public.customers (public.tax_id_key("taxId"));

drop index if exists customers_taxid_branch_key;
