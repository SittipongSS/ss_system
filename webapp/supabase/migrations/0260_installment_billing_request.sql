--  0260: ผูกงวดชำระเข้ากับคำร้องขอเอกสารการเงิน (B-5)
--
--  ปิดวงของรอบนี้ — แผนธุรกิจบริการ §4 ตัดสินไว้ตั้งแต่ 2026-08-01:
--      *"งวดจ่าย ↔ คำขอ IV ผูกกันได้แต่ไม่บังคับ (`installment.billingRequestId`
--        nullable) เพราะ **บางทีขอ บางทีไม่ขอ**"*
--
--  ── ทำไม nullable และไม่มีตรรกะไหนบังคับให้มีค่า ────────────────────────
--  สองแกนนี้เดินอิสระกันจริง ๆ:
--    · ปิดคำร้อง ≠ งวดถูกรับรอง — ออกใบวางบิลแล้วไม่ได้แปลว่าเงินเข้า
--    · งวด confirmed ≠ คำร้องปิด — บางงวดไม่มีใครขอเอกสารเลย
--  ⚠️ เขียนตรรกะที่ทำให้แกนหนึ่งขยับตามอีกแกนเมื่อไร = ยุบสองคำถามเป็นคำถามเดียว
--     ซึ่งของจริงตอบคนละอย่าง
--
--  ── ทำไม "ไม่" ผูกอัตโนมัติ ────────────────────────────────────────────
--  ของจริงลูกค้าขอใบวางบิล **50% ก่อนผลิต** ⇒ คำร้องเกิดตั้งแต่ตอนที่มีแค่ใบเสนอราคา
--  ส่วนงวดเกิดจากใบสั่งขายซึ่งอาจยังไม่ถูกสร้างด้วยซ้ำ ⇒ **คำร้องเกิดก่อนงวดเสมอ**
--  ⚠️ เดาจับคู่ด้วย % ที่ใกล้เคียงเมื่อไร จะได้ใบวางบิลไปแขวนผิดงวดโดยไม่มีใครรู้
--  ⇒ หน้าใบโชว์ "คำร้องของใบเสนอราคานี้" แล้วให้ SA **กดแนบเอง**
--
--  ── ทำไมไม่มี FK ──────────────────────────────────────────────────────
--  แพตเทิร์นเดียวกับ `dept_requests.quotationId` (0225): คำร้องถูกบังคับลบได้
--  (`force_delete_dept_request`) แล้วงวดที่อ้างมันต้องยังอ่านได้ ไม่ใช่พังทั้งแถว
--  ⚠️ **บอกตรง ๆ ไม่ใช่เงียบ** — จอขึ้น "คำร้องถูกลบไปแล้ว" และมีปุ่มถอดลิงก์ให้
--     (บทเรียน R-5: ลิงก์ที่หายเงียบคือบันทึกที่โกหก)
--
--  🛑 รันล่วงหน้าได้ทันที — คอลัมน์ใหม่เป็น NULL ได้ โค้ดเก่าไม่รู้จักและไม่แตะ
--  ⚠ รันมือบน Supabase SQL Editor · รันซ้ำได้ · ไม่แตะข้อมูลเดิม
-- ══════════════════════════════════════════════════════════════════════

BEGIN;

ALTER TABLE public.sales_order_installments
  ADD COLUMN IF NOT EXISTS "billingRequestId" text;

COMMENT ON COLUMN public.sales_order_installments."billingRequestId"
  IS 'คำร้องขอเอกสารการเงินที่ครอบงวดนี้ (dept_requests.id · ไม่มี FK โดยเจตนา) · B-5';

-- ตอบคำถาม "คำร้องใบนี้ถูกแนบกับงวดไหนไปแล้วบ้าง" — ใช้ตอนกันแนบซ้ำ
DROP INDEX IF EXISTS sales_order_installments_billing_request_idx;
CREATE INDEX sales_order_installments_billing_request_idx
  ON public.sales_order_installments ("billingRequestId")
  WHERE "billingRequestId" IS NOT NULL;

COMMIT;

