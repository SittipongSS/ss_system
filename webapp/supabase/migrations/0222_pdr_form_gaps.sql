-- ────────────────────────────────────────────────────────────────────────────
-- 1) เหตุผลที่เป็นงานด่วน
--
--    ⚠️ **ไม่ใส่ CHECK ผูกกับ `urgent`ที่ DB** — ด่าน "ด่วนแล้วต้องมีเหตุผล" อยู่ที่
--    API (`requestShapeError`) เพราะข้อความไทยที่บอกว่าต้องกรอกอะไรเขียนที่นั่นได้
--    · CHECK ระดับตารางจะได้ error ดิบที่ผู้ใช้อ่านไม่รู้เรื่อง (แพตเทิร์นเดียวกับ
--    `title` ของ 0173)
-- ────────────────────────────────────────────────────────────────────────────
ALTER TABLE public.dept_requests
  ADD COLUMN IF NOT EXISTS "urgentReason" text
    CHECK ("urgentReason" IS NULL OR length("urgentReason") <= 500);

COMMENT ON COLUMN public.dept_requests."urgentReason" IS
  'เหตุผลที่เป็นงานด่วน — ฟอร์มกระดาษ FM-RD-01 บังคับให้แจ้งเหตุผล ไม่ใช่แค่ติ๊กว่าด่วน';

-- ────────────────────────────────────────────────────────────────────────────
-- 2) ข้อความต่อท้าย Scentotype รายตัว
--
--    ⭐ เก็บเป็น **jsonb map** `{"cheerer": "…", "admirer": "…"}` ไม่ใช่ 5 คอลัมน์ —
--    ชุด Scentotype อยู่ในโค้ด (`scentBriefTypes.js`) และยังเพิ่มได้ · แตกเป็น
--    คอลัมน์เมื่อไร การเพิ่มตัวที่หกก็ต้องออก migration ซึ่งขัดกับที่ 0213 ตั้งใจไว้
--
--    ⚠️ `scentotypes` (text[]) ยังเป็นตัวบอกว่า **ติ๊กอันไหน** เหมือนเดิม — ตัวใหม่นี้
--    เก็บแค่ข้อความต่อท้าย · ติ๊กโดยไม่เขียนต่อได้ (กระดาษก็เว้นได้)
-- ────────────────────────────────────────────────────────────────────────────
ALTER TABLE public.dept_request_scents
  ADD COLUMN IF NOT EXISTS "scentotypeNotes" jsonb NOT NULL DEFAULT '{}'::jsonb;

COMMENT ON COLUMN public.dept_request_scents."scentotypeNotes" IS
  'ข้อความต่อท้าย Scentotype รายตัว {"cheerer":"…"} — เส้นเขียนต่อบนกระดาษข้อ 2.1.4';
