alter table public.scents
  add column if not exists "proposedStatus" text;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'scents_proposed_status_chk'
  ) then
    alter table public.scents
      add constraint scents_proposed_status_chk
      check ("proposedStatus" is null or "proposedStatus" in ('developing', 'active'));
  end if;
end $$;

comment on column public.scents."proposedStatus" is
  'สถานะที่ผู้เสนอร่างระบุว่าเป็นจริง (developing/active) — ค่าตั้งต้นตอน RD กดรับเข้าทะเบียน · มีความหมายเฉพาะตอน status = draft';
