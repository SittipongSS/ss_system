--  อาการ (ตรวจระบบเธรด 2026-08-04): แถวที่ระบบเขียนตอนอนุมัติลูกค้า/สินค้า
--  ทั้งที่เอกสารบังคับไม่ครบ ("อนุมัติโดยยกเว้นเอกสารบังคับ — เหตุผล: …")
--  ขึ้นบนจอด้วยป้าย **"ข้อความ" สี accent = หน้าตาเหมือนข้อความที่คนพิมพ์เอง**
--  และในกล่องแจ้งเตือนขึ้นว่า "ข้อความ · ลูกค้า X" เหมือนมีคนมาทัก
--
--  ต้นเหตุ: route เขียน kind = 'note' แต่ UPDATE_KINDS.customer/.product
--  **ไม่เคยประกาศ 'note'** (มีแค่ comment/approve/reject/reset) ⇒
--  `updateKindMeta` ถอยไปใช้ meta ของชนิดตั้งต้นที่คนพิมพ์ได้ ซึ่งคือ 'comment'
--
--  ผลข้างเคียงอีกทาง: `isAuthorableKind` = false ⇒ ระบบจัดเป็น "เหตุการณ์ระบบ"
--  ⇒ หายไปเมื่อผู้ใช้กดสวิตช์ "ซ่อนเหตุการณ์ระบบ" ทั้งที่หน้าตาเป็นข้อความคน
--  (หน้าตาบอกอย่าง พฤติกรรมเป็นอีกอย่าง)
--
--  ทำไมเปลี่ยนชื่อแทนที่จะประกาศ 'note' เพิ่ม: 'note' บนดีล/ลีดคือ **ชนิดที่คน
--  พิมพ์เอง** ("บันทึก") — ชื่อเดียวกันคนละฝั่งของเส้นแบ่ง "ข้อความคน vs
--  เหตุการณ์ระบบ" ซึ่งเป็นเส้นที่ทั้งระบบใช้ตัดสินการซ่อนและสิทธิ์แก้/ลบ
--  ตั้งชื่อตามความหมาย (override = ข้ามด่านเอกสาร) ตามกฎเดิมของทะเบียนชนิด
--
--  ไม่ลบ ไม่แก้เนื้อความ — เปลี่ยนเฉพาะค่า kind ของแถวเดิม (25 แถว ณ วันตรวจ:
--  ลูกค้า 10 · สินค้า 15) ย้อนกลับได้ด้วยการสลับ 'override' ↔ 'note' ใน WHERE
--
--  ⚠ ปลอดภัยเพราะ 'note' ไม่เคยเป็นชนิดที่ถูกต้องของสอง entity นี้ — ไม่มีทาง
--  ไปโดนข้อความที่คนพิมพ์เอง (ของคนคือ 'comment')
--
--  ⚠ รันมือบน Supabase SQL Editor · รันซ้ำได้
-- ============================================================

BEGIN;

UPDATE public.entity_updates
   SET kind = 'override'
 WHERE "entityType" IN ('customer', 'product')
   AND kind = 'note';

COMMIT;

