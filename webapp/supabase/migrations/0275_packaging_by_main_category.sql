BEGIN;

-- ล้างช่องบรรจุภัณฑ์ของกลุ่มที่ไม่มีของ — ยึด categoryCode เป็นหลัก และถอยไปอ่าน
-- จาก fgCode ให้แถวที่ categoryCode ว่าง (รูปแบบรหัส FG-xxx-MM-TTT-nnnn)
UPDATE public.products
   SET volume = NULL, "volumeUnit" = NULL, "piecesPerCase" = NULL
 WHERE COALESCE(
         left("categoryCode", 2),
         (regexp_match("fgCode", '(\d{2})-(\d{3})'))[1]
       ) IN ('03', '04')
   AND (volume IS NOT NULL OR "volumeUnit" IS NOT NULL OR "piecesPerCase" IS NOT NULL);

COMMIT;

