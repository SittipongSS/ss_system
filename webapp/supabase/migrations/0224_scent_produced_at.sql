BEGIN;

-- ── 1) ช่องวันที่ผลิต + คนบันทึก ─────────────────────────────────────────
-- เก็บ "ใครบันทึก" คู่กับวันที่ตามแพตเทิร์นเดียวกับ sentAt/acceptedAt ของ 0171/0205
-- — วันที่ลอย ๆ ที่ไม่รู้ว่าใครกรอกคือข้อมูลที่ตามกลับไม่ได้เวลามันขัดกับความจริง
ALTER TABLE public.scents
  ADD COLUMN IF NOT EXISTS "producedAt"     date,
  ADD COLUMN IF NOT EXISTS "producedById"   text,
  ADD COLUMN IF NOT EXISTS "producedByName" text;

COMMENT ON COLUMN public.scents."producedAt" IS
  'วันที่ RD ผลิตกลิ่นตัวนี้เสร็จ — คนละวันกับวันพร้อมส่ง (dept_request_items.readyAt) '
  'และวันส่งลูกค้า (scents.sentAt) · มติผู้ใช้ 2026-08-08 ม-66';

-- ── 2) ยกวันเดิมไปเป็นวันผลิต ────────────────────────────────────────────
-- รันซ้ำได้: เงื่อนไข `producedAt IS NULL` กันไม่ให้ทับค่าที่ RD แก้ไปแล้วรอบก่อน
UPDATE public.scents
   SET "producedAt" = "sentAt"
 WHERE "producedAt" IS NULL
   AND "sentAt" IS NOT NULL;

