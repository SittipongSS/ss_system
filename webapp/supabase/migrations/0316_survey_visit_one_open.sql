-- ⚠️ ครอบ BEGIN/COMMIT — ใบนี้ตรวจของค้างก่อนแล้วค่อยสร้าง index ⇒ ล้มต้องไม่เหลือครึ่งใบ
BEGIN;

-- ── 1) ของค้างต้องถูกจัดการก่อน ไม่ใช่ปล่อยให้ CREATE INDEX ตีกลับด้วย error ดิบ ──
--
-- 🔴 `CREATE UNIQUE INDEX` บนข้อมูลที่ซ้ำอยู่แล้วจะล้มด้วยข้อความที่บอกแค่ค่าที่ชน
--    (`Key ("requestId")=(DR-…) is duplicated`) ซึ่งไม่บอกว่าเป็นนัดใบไหนบ้าง และ
--    ต้องเก็บใบไหนไว้ ⇒ ตรวจเองก่อนแล้วบอกให้ครบทั้งรหัสนัดและสถานะ
DO $$
DECLARE
  v_dup text;
BEGIN
  SELECT string_agg(line, E'\n' ORDER BY line) INTO v_dup FROM (
    SELECT v."requestId" || ' → ' || string_agg(
             COALESCE(v.code, v.id) || ' (' || v.status || ' · ' || COALESCE(v."scheduledDate"::text, '—') || ')',
             ' · ' ORDER BY v."createdAt")
           AS line
      FROM public.service_visits v
     WHERE v."requestId" IS NOT NULL
       AND v.kind = 'survey'
       AND v.status IN ('draft', 'scheduled', 'in_progress')
     GROUP BY v."requestId"
    HAVING count(*) > 1
  ) dups;

  IF v_dup IS NOT NULL THEN
    /* ข้อความต้องบอกสิ่งที่ทำตามได้จริง: เหลือนัดเปิดใบเดียวต่อใบคำร้อง โดย
       **ปิด/ยกเลิก** ใบที่ไม่ได้ไปจริง (ห้ามลบ — ประวัติการนัดคือของที่ต้องตอบลูกค้า) */
    RAISE EXCEPTION E'มีใบประเมินที่ถือนัดเปิดค้างมากกว่าหนึ่งใบ — แก้ให้เหลือใบเดียวก่อน (ตั้งสถานะใบที่ไม่ได้ไปจริงเป็น cancelled อย่าลบทิ้ง) แล้วรันซ้ำ:\n%', v_dup;
  END IF;
END $$;

-- ── 2) ยามจริง ────────────────────────────────────────────────────────────────
CREATE UNIQUE INDEX IF NOT EXISTS service_visits_survey_open_request_uk
  ON public.service_visits ("requestId")
  WHERE "requestId" IS NOT NULL
    AND kind = 'survey'
    AND status IN ('draft', 'scheduled', 'in_progress');

COMMENT ON INDEX public.service_visits_survey_open_request_uk IS
  'หนึ่งใบประเมิน = หนึ่งนัดที่ยังมีชีวิต (draft/scheduled/in_progress) · นัดที่จบไปแล้วซ้ำได้ เพราะนัดรอบใหม่คือแถวใหม่';

COMMIT;

