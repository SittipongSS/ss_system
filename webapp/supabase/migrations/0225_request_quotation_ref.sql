--    "SA ยื่นคำร้อง เลือกขอเอกสาร ใส่ข้อมูล ลูกค้า/โครงการ ดีล/
--     ใส่รายละเอียดที่เกี่ยวข้อง QT SO FG (ถ้ามี)/ใส่รายการเอกสาร …"
--
--  ── ของที่มีอยู่แล้ว ─────────────────────────────────────────────────
--  dept_requests มี "salesOrderId" (0195 · ใช้กับบรีฟกลิ่น) และ "productId"/
--  "productName" (0195) อยู่แล้ว — สามอ้างอิงของมตินี้จึงขาดแค่ QT ตัวเดียว
--
--  ── ทำไมไม่มี FK ──────────────────────────────────────────────────────
--  แพตเทิร์นเดียวกับ "salesOrderId" ที่อยู่มาก่อน: ใบเสนอราคาลบได้ (ร่างที่ถูก
--  ทิ้ง) แล้วคำร้องที่อ้างมันต้องยังเปิดอ่านได้ ไม่ใช่พังทั้งใบเพราะ FK ค้าง —
--  จอเป็นคนบอกว่า "ใบเสนอราคาที่อ้างถูกลบไปแล้ว" (บทเรียนเดียวกับ briefId
--  ของทะเบียนกลิ่นที่ตามกลับไม่เจอ = บอกตรง ๆ ไม่ใช่เงียบ)
-- ══════════════════════════════════════════════════════════════════════

ALTER TABLE public.dept_requests
  ADD COLUMN IF NOT EXISTS "quotationId" text;

COMMENT ON COLUMN public.dept_requests."quotationId"
  IS 'ใบเสนอราคาที่คำร้องนี้อ้างถึง (ม-88 · ไม่มี FK โดยเจตนา — QT ลบได้)';

-- index เฉพาะแถวที่อ้างจริง — ใบส่วนใหญ่ไม่อ้าง QT ไม่ต้องจ่ายราคา index เต็มตาราง
DROP INDEX IF EXISTS dept_requests_quotation_idx;
CREATE INDEX dept_requests_quotation_idx
  ON public.dept_requests ("quotationId") WHERE "quotationId" IS NOT NULL;
