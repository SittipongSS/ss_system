-- ══════════════════════════════════════════════════════════════════════
--  0258: ผลลัพธ์ของบรรทัดเอกสารการเงิน — เลขที่เอกสาร + วันครบกำหนด (B-3)
--
--  ⭐ ปิดข้อ R-6 ของ `docs/request-hub-rebuild-plan.md` สำหรับหัวข้อนี้:
--      *"ขาเข้าอ้างอะไร · ขาออกได้อะไร"* — ต้นทางทำครบแล้ว (`needs`) แต่ปลายทาง
--      ยังไม่มี ⇒ ปิดคำร้องแล้วไม่มีอะไรตกผลึกไปไหน
--  ของหัวข้อนี้ ขาออกคือ **เลขที่ใบวางบิล/ใบกำกับ + วันครบกำหนด**
--
--  ── ทำไมอยู่ที่ "บรรทัด" ไม่ใช่ "ใบ" (กลับทางกับยอดใน 0257) ─────────────
--  1 บรรทัด = 1 เอกสาร ⇒ **เลขที่เป็นของเอกสารแต่ละใบจริง ๆ**
--  ของจริงขอใบวางบิลกับใบกำกับภาษีในคำร้องเดียว แล้วได้เลขที่คนละเลข คนละวันครบกำหนด
--  ⚠️ ตรงข้ามกับ **ยอด** ซึ่งเป็นของก้อนเดียวทั้งใบ (0257) — สองอย่างนี้อยู่คนละที่
--     โดยตั้งใจ ไม่ใช่ความไม่สม่ำเสมอ
--
--  ── ทำไมไม่มี FK และไม่ unique ────────────────────────────────────────
--  เลขที่มาจาก **ระบบบัญชีข้างนอก** (Express) — ไม่มีตารางในระบบนี้ให้ชี้
--  ⚠️ ไม่ unique เพราะใบกำกับภาษีที่ยกเลิกแล้วออกเลขซ้ำได้ในบางกรณี และเราไม่ใช่
--     เจ้าของเลข · บังคับ unique = ระบบนี้ปฏิเสธความจริงของระบบบัญชี
--
--  ── วันครบกำหนดไม่บังคับ ──────────────────────────────────────────────
--  ใบวางบิล/ใบแจ้งหนี้มีกำหนดชำระ · **ใบเสร็จไม่มี** (ออกหลังรับเงินแล้ว)
--  ⇒ บังคับที่ระดับ DB ไม่ได้ · ด่านตามชนิดเอกสารอยู่ที่ API เหมือน `title`/`dealId`
--
--  🛑 รันล่วงหน้าได้ทันที — คอลัมน์ใหม่เป็น NULL ได้ทั้งคู่ โค้ดเก่าไม่รู้จักและไม่แตะ
--  ⚠ รันมือบน Supabase SQL Editor · รันซ้ำได้ · ไม่แตะข้อมูลเดิม
-- ══════════════════════════════════════════════════════════════════════

BEGIN;

ALTER TABLE public.dept_request_items
  ADD COLUMN IF NOT EXISTS "docNumber"  text
    CHECK ("docNumber" IS NULL OR length(btrim("docNumber")) BETWEEN 1 AND 60),
  ADD COLUMN IF NOT EXISTS "docDueDate" date;

COMMENT ON COLUMN public.dept_request_items."docNumber"
  IS 'เลขที่เอกสารที่บัญชีออกให้ (จากระบบบัญชีภายนอก) · B-3 · R-6';
COMMENT ON COLUMN public.dept_request_items."docDueDate"
  IS 'วันครบกำหนดชำระของเอกสารใบนี้ — ว่างได้ (ใบเสร็จไม่มีกำหนด) · B-3 · R-6';

-- ค้นด้วยเลขที่เอกสารได้ — บัญชีถามกลับด้วยเลขที่เสมอ ("IV เลขนี้มาจากคำร้องไหน")
DROP INDEX IF EXISTS dept_request_items_doc_number_idx;
CREATE INDEX dept_request_items_doc_number_idx
  ON public.dept_request_items ("docNumber") WHERE "docNumber" IS NOT NULL;

COMMIT;
