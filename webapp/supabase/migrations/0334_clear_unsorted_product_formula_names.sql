BEGIN;

/* แถวเป้าหมาย: ตรงกับเงื่อนไขของ `loadUnsortedProducts` เป๊ะ ๆ
   ⚠️ ไม่กรองด้วย btrim — แถวที่มีแต่ช่องว่าง/แท็บไม่ขึ้นการ์ด (โค้ด `.trim()` ทิ้ง)
   แต่ก็เป็นค่าลอยแบบเดียวกัน และ btrim ตั้งต้นไม่ตัดแท็บ ⇒ กวาดทุกแถวที่ไม่ใช่ NULL */
CREATE TEMP TABLE _unsorted_formula_targets ON COMMIT DROP AS
SELECT p.*
FROM public.products p
WHERE p."formulaId" IS NULL
  AND p."scentId" IS NULL
  AND p."formulaName" IS NOT NULL;

-- ร่องรอยก่อนแก้
INSERT INTO public.audit_logs
  ("actorId", "actorName", "actorRole", action, "entityType", "entityId", summary, "changedKeys", before, "createdAt")
SELECT
  'migration-0334', 'ระบบ (mig 0334)', 'system', 'update', 'product', t.id,
  'ล้างชื่อสูตรที่ค้างบนสินค้า — เคลียร์กอง "รอจัดระเบียบ" (มติ 2026-09-02)',
  '["formulaName","formulaCode","formulaDate"]'::jsonb,
  to_jsonb(t), now()
FROM _unsorted_formula_targets t;

UPDATE public.products p SET
  "formulaName" = NULL,
  "formulaCode" = NULL,
  "formulaDate" = NULL
FROM _unsorted_formula_targets t
WHERE p.id = t.id;

COMMIT;
