-- 🐞 **อาการ (ผู้ใช้ทัก 2026-08-25)**: ลูกค้าขอให้แก้ ⇒ ระบบเปิดแถวรอบใหม่ให้เอง
-- (`outcome: 'revise'`) แต่ **ไม่มีอะไรถามวันส่งของรอบนั้นเลย** · ใบยังถือ
-- `committedDueDate` ของรอบก่อน ซึ่งโดยนิยามคือวันที่ผ่านไปแล้ว
--
-- วัดของจริง 2026-08-25: ใบที่เดินอยู่ 53 ใบ — **22 ใบเลยวันที่แจ้งไว้แล้ว**
-- และ `requestAwaitingDue()` (`lib/requests/statuses.js`) เป็นจริงได้ครั้งเดียว
--   `status === 'acknowledged' && !committedDueDate`
-- ⇒ แจ้งวันไปแล้วครั้งหนึ่ง ขั้น "แจ้งวันส่ง" ไม่มีวันกลับมาอีก · RD ไม่มีปุ่มไหน
--   แจ้งวันของรอบใหม่ได้ นอกจากจะนึกเองว่าต้องกด "เลื่อนวันกำหนดส่ง"
--
-- ⭐ **เก็บ "แจ้งเมื่อไร" ไม่ใช่ "แจ้งของรอบไหน"** — เลขรอบต้องมีคนคอยนับให้ตรงกับ
-- สายพันธุ์ของแถว (`derivedFromItemId`) ซึ่งเป็นตัวนับที่สองที่ drift ได้
-- ⇒ เก็บ **เวลาที่ลงวัน** แล้วเทียบกับ `createdAt` ของแถวรอบแก้ที่ยังเดินอยู่:
--   แถวรอบแก้เกิดหลังการแจ้งวันครั้งล่าสุด = วันที่ถืออยู่เป็นของรอบก่อน
-- (ตรรกะอยู่ที่ `lib/requests/dueRound.js` พร้อมเทสต์ — ที่นี่มีแค่คอลัมน์)
--
-- ⚠️ **timestamptz ไม่ใช่ date** — `outcomeAt`/`dueAt` เป็น date ⇒ เทียบกับวันที่
-- ลูกค้าขอแก้ในวันเดียวกันแยกไม่ออกว่าอะไรเกิดก่อน · `createdAt` ของแถวเป็น
-- timestamptz อยู่แล้ว จึงเทียบกันได้ตรง ๆ ไม่ต้องเดา
--
-- ⚠️ **ค่าเก่าเป็น NULL โดยตั้งใจ ไม่ backfill** — NULL แปลว่า "ไม่รู้ว่าแจ้งเมื่อไร"
-- และ `dueRound.js` ตีความว่า **ไม่ค้าง** ⇒ ใบเก่าทั้งหมดพฤติกรรมเดิมเป๊ะ ไม่มีใบไหน
-- เด้งกลับไปขั้น "แจ้งวันส่ง" เพราะ migration นี้ · ใบจะเข้าสู่กติกาใหม่เมื่อ RD
-- แจ้ง/เลื่อนวันครั้งถัดไป ซึ่งเป็นจังหวะที่ค่านี้ถูกเขียนครั้งแรก
--   (backfill ด้วย `acknowledgedAt` จะทำให้ใบที่มีรอบแก้ค้างอยู่แล้ว 2 ใบ เด้งขึ้นมา
--    พร้อมกันโดยที่ไม่มีใครสั่ง — ปล่อยให้ค่อย ๆ เข้าเองปลอดภัยกว่า)

