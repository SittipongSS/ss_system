-- ── 0230 · เลขรันของรหัสลูกค้า (AR) และรหัสสินค้า (FG) ──────────────────────
--
-- ⭐ ที่มา (มติผู้ใช้ 2026-08-12): โมดัลเพิ่มลูกค้า/เพิ่มสินค้ามีสวิตช์ "ระบบใหม่"
--   เปิด  = ระบบออกรหัสให้ · AR-AAAA 4 หลักเริ่ม 1001 · FG-AAAA-BB-CCC-DDDDD
--           โดย AAAA = รหัสลูกค้า · BB-CCC = หมวดสินค้า · DDDDD = เลขรันเริ่ม 10001
--   ปิด   = กรอกรหัสเอง (รูปแบบเดิม AR-AAA / FG-AAA-BB-CCC-DDDD) ไม่กินเลขรัน
--
-- ⚠️ **ไม่สร้างตารางเคาน์เตอร์ใหม่** — ใช้ `entity_number_counters` +
--   `next_entity_number(p_scope, p_month)` ของ mig 0096 ที่ atomic อยู่แล้ว
--   (INSERT … ON CONFLICT DO UPDATE … RETURNING = จองเลขในคำสั่งเดียว)
--   ตารางนั้นมี PK (scope, month) เพราะรหัสดีล/โครงการรันใหม่ทุกเดือน — **แต่ AR/FG
--   รันยาวตัวเดียวตลอดกาล** จึงลง month = '-' หนึ่งแถวต่อ scope แล้วไม่ยุ่งอีกเลย
--   (เลือกทางนี้แทนการเพิ่มตารางที่สอง เพราะสองตารางที่ทำงานเดียวกันคือจุดที่วันหนึ่ง
--   จะมีคนไปเพิ่มเลขผิดตาราง แล้วรหัสซ้ำโดยไม่มีอะไรฟ้อง)
--
-- ⚠️ **เลขรัน FG นับรวมทั้งระบบ ไม่ใช่ต่อลูกค้า** (มติผู้ใช้ 2026-08-12) — สินค้าตัวถัด
--   ไปได้ 10002 ไม่ว่าเป็นของลูกค้ารายไหน · ถ้าวันหนึ่งเปลี่ยนใจเป็นต่อลูกค้า ต้องเพิ่ม
--   scope ต่อรายแทน (เช่น 'FG:0109') ห้ามแตกเลขจากตัวเดิม เพราะเลขที่ออกไปแล้วอยู่บน
--   เอกสารของลูกค้า
--
-- ⚠️ **ค่าเริ่มต้นคือ "เลขล่าสุด" ไม่ใช่ "เลขถัดไป"** — RPC คืนค่าหลัง +1 เสมอ
--   ⇒ AR ตั้ง 1000 เพื่อให้ใบแรกได้ 1001 · FG ตั้ง 10000 เพื่อให้ใบแรกได้ 10001
--
-- ⚠️ **ซิงก์กับของที่มีอยู่จริงก่อนเสมอ** — ถ้าเคยมีแถวรูปแบบใหม่หลุดเข้าไปแล้ว
--   (ทดลอง/นำเข้า) ต้องเริ่มนับต่อจากตัวสูงสุด ไม่งั้นใบถัดไปชนกับของเดิมทันที
--   (customers."arCode" unique ที่ 0031 · products."fgCode" unique ที่ 0035 จะโยน 23505
--    ซึ่งแอปแปลเป็น "รหัสนี้มีในระบบแล้ว" — ผู้ใช้เห็นเป็นระบบพังทั้งที่เป็นเลขซ้ำ)
--
-- 🔒 รหัสเก่าทั้งหมดไม่ถูกแตะ: AR-109 ยังเป็น AR-109 (ระบบสหมิตรอ้างค่านี้ตรง ๆ ที่
--   lib/sahamit/server.js) · ลูกค้าเก่าจะถูกเติมศูนย์เป็น 4 หลัก **เฉพาะตอนประกอบรหัส
--   FG** (109 → 0109) ซึ่งเป็นการอ่านค่า ไม่ใช่การเขียนทับ
--
-- ⚠ รันมือบน Supabase (เหมือน migration อื่น) · ไม่มี DDL ในใบนี้ = ปลอดภัยที่จะรันซ้ำ

-- ── AR: เลขล่าสุดของรหัสลูกค้ารูปแบบใหม่ (AR-AAAA) ────────────────────────
INSERT INTO public.entity_number_counters (scope, month, "lastNo")
SELECT 'AR', '-', GREATEST(1000, COALESCE(max(split_part("arCode", '-', 2)::int), 0))
FROM public.customers
WHERE "arCode" ~ '^AR-\d{4}$'
ON CONFLICT (scope, month) DO UPDATE
  SET "lastNo" = GREATEST(public.entity_number_counters."lastNo", EXCLUDED."lastNo");

-- ── FG: เลขล่าสุดของรหัสสินค้ารูปแบบใหม่ (FG-AAAA-BB-CCC-DDDDD) ───────────
INSERT INTO public.entity_number_counters (scope, month, "lastNo")
SELECT 'FG', '-', GREATEST(10000, COALESCE(max(split_part("fgCode", '-', 5)::int), 0))
FROM public.products
WHERE "fgCode" ~ '^FG-\d{4}-\d{2}-\d{3}-\d{5}$'
ON CONFLICT (scope, month) DO UPDATE
  SET "lastNo" = GREATEST(public.entity_number_counters."lastNo", EXCLUDED."lastNo");
