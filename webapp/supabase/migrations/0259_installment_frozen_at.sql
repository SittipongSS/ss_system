--
--  มติผู้ใช้ 2026-08-15: *"งวดชำระ gen ตั้งแต่ร่าง SO เลยได้มั้ย"* → ได้
--
--  ── ปัญหาที่แก้ ───────────────────────────────────────────────────────
--  `0245` สร้างงวดตอน **อนุมัติ** พร้อมเหตุผลที่เขียนกำกับไว้ว่า *"ยอดยังเปลี่ยนได้
--  จนกว่าจะอนุมัติ สร้างงวดก่อนหน้านั้นยอดต่องวดจะผิดเงียบ ๆ"*
--
--  ⭐ เหตุผลนั้นถูก แต่โทษผิดตัว — ปัญหาไม่ใช่ "สร้างเร็วไป" แต่คือ **snapshot ครั้งเดียว
--  แล้วไม่มีใครมาทับ** ⇒ ย้ายจุดที่ *หยุดยอด* ไม่ใช่จุดที่ *สร้างแถว*
--
--  ผลที่ได้จริง: `dueDate` เป็นช่องที่ **ใบเสนอราคาไม่มีมาให้** และ SA ต้องกรอกเองทีละงวด
--  (คอมเมนต์ของ 0245 เขียนไว้เอง: "ของจริงมีงวดที่ผูกกับเหตุการณ์ ไม่ใช่ผูกกับวัน")
--  ⇒ ก่อนใบนี้ ไม่มีแถวให้กรอกจนกว่าใบจะอนุมัติ ⇒ **ใบผ่านด่านอนุมัติไปโดยไม่มี
--  กำหนดชำระสักงวด** แล้วต้องหวังว่ามีคนย้อนกลับมาใส่
--
--  ── ความหมายของ frozenAt ──────────────────────────────────────────────
--    NULL     = งวดร่าง · ยอด/สัดส่วนยังเดินตามแผนของ QT และยอดของใบ
--               **ไม่เข้าทะเบียนการชำระของบัญชี · แจ้งชำระไม่ได้**
--    มีค่า    = ยอดถูกเขียนทับครั้งสุดท้ายตอนอนุมัติแล้ว ห้ามแก้อีก (กติกาเดิมของ 0245)
--
--  🛑 **BACKFILL จำเป็น ไม่ใช่ทางเลือก** — แถวที่มีอยู่ทุกแถวเกิดตอนอนุมัติอยู่แล้ว
--  (นั่นคือทางเดียวที่สร้างได้ก่อนใบนี้) ⇒ ปล่อยเป็น NULL เมื่อไร เงินที่บัญชีรับรอง
--  ไปแล้วจะ **หายจากทะเบียนการชำระทั้งหมด** และแจ้งชำระต่อไม่ได้
--  ⇒ ใช้ `createdAt` เป็นเวลาที่ freeze ซึ่งตรงกับความจริง (แถวเกิด = ตอนอนุมัติ)
--
--  ⚠ รันมือบน Supabase SQL Editor · รันซ้ำได้ · **ต้องรันก่อน deploy โค้ด**
--    (โค้ดใหม่กรองทะเบียนด้วย frozenAt — คอลัมน์ไม่มี = ทะเบียนพัง)
-- ══════════════════════════════════════════════════════════════════════

BEGIN;

ALTER TABLE public.sales_order_installments
  ADD COLUMN IF NOT EXISTS "frozenAt" timestamptz;

COMMENT ON COLUMN public.sales_order_installments."frozenAt"
  IS 'เวลาที่ยอด/สัดส่วนถูกหยุด (ตอนใบอนุมัติ) · NULL = งวดร่าง ยอดยังเดินตามใบ · B-4';

-- ── backfill: ทุกแถวที่มีอยู่เกิดตอนอนุมัติ จึง freeze ไปแล้วโดยนิยาม ──────
UPDATE public.sales_order_installments
   SET "frozenAt" = "createdAt"
 WHERE "frozenAt" IS NULL;

-- ทะเบียนของบัญชีอ่านเฉพาะแถวที่ freeze แล้ว — index ให้ตรงกับคำถามนั้น
DROP INDEX IF EXISTS sales_order_installments_frozen_idx;
CREATE INDEX sales_order_installments_frozen_idx
  ON public.sales_order_installments ("frozenAt") WHERE "frozenAt" IS NOT NULL;

-- ⭐ **แจ้งชำระบนงวดร่างไม่ได้ที่ระดับ DB ด้วย** ไม่ใช่พึ่งว่า API จะกันให้
-- ยอดของงวดร่างยังขยับได้ ⇒ หลักฐานที่แนบไว้จะผูกกับตัวเลขที่กำลังจะถูกเขียนทับ
ALTER TABLE public.sales_order_installments
  DROP CONSTRAINT IF EXISTS sales_order_installments_draft_pending;
ALTER TABLE public.sales_order_installments
  ADD CONSTRAINT sales_order_installments_draft_pending CHECK (
    "frozenAt" IS NOT NULL OR status = 'pending'
  );

COMMIT;

