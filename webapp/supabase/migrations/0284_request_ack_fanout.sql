-- ── รับเรื่องเป็นเรื่องของ "ใบ" — แถวต้องไม่ค้างรอรับเรื่องอีกชั้น ────────────
--
-- 🐞 **อาการที่ผู้ใช้ทักมา (2026-08-24)**: *"การรับเรื่อง หัวข้อขอเอกสาร เป็นการรับ
-- ระดับใบใช่มั้ย ซึ่งจริงๆคือทุกหัวข้อ"* — ใช่ครึ่งเดียว
--
-- มติ 2026-08-20 ย้ายการรับเรื่องมาเป็น **ระดับใบ** แล้วจริง (ปุ่มอยู่ที่แผงจัดการ ·
-- ก้าว `ack` รายแถวถูกปิดไม่ให้ดันสถานะใบอีกต่อไป) แต่ **ไม่ได้ล้างขั้นรับเรื่องออก
-- จากสายของแถว** ⇒ ใบที่ฝ่ายกดรับแล้ว แถวข้างในยังอยู่ขั้น `awaiting_ack` ทุกแถว
-- และหน้าจอยังขึ้นปุ่ม "รับเรื่อง" ให้กดซ้ำรายแถวก่อนถึงจะกด "ส่งงาน" ได้
--
-- วัดของจริงบน prod (2026-08-24):
--   · DC-26080003  รับเรื่องใบ 21/08 — **25 แถวยังค้าง `awaiting_ack` ทั้งหมด**
--     ⇒ RD ต้องกดรับเรื่องอีก 25 ครั้งก่อนเริ่มส่งงานได้
--   · RQ-26080059  รับเรื่องใบ 20/08 · แถว MSDS ถูกกดรับรายแถว **26/08**
--     ⇒ `ackAt` ของแถวบันทึกวันที่ไม่ใช่วันที่ฝ่ายรับเรื่องจริง เส้นวัด lead time
--       ของแถวนั้นสั้นกว่าความจริง 6 วัน
--   · FD-26080007  (พัฒนาสูตร) อาการเดียวกัน — ไม่ใช่เรื่องของหัวข้อขอเอกสารอย่างเดียว
--
-- ⭐ คอมเมนต์ใน `lib/requests/delivery.js` เขียนแผนนี้ไว้เองแล้วว่า
--    "(แผน: การรับเรื่องระดับใบ fan-out ลงแถวที่ยังไม่มี ackAt)" — ไฟล์นี้คือแผนนั้น
--
-- ⚠️ **ไม่แตะแถวที่มี `ackAt` อยู่แล้ว** — ของที่กดไปแล้วคือหลักฐาน ต่อให้วันเพี้ยน
--    ก็ไม่ใช่ของที่ migration ควรไปเขียนทับ (ผู้ใช้แก้วันเองได้ทางก้าวของแถว)
-- ⚠️ **ไม่แตะใบที่ยังไม่ถูกรับเรื่อง** (`draft` / `pending`) — แถวของมันค้างที่
--    `awaiting_ack` อย่างถูกต้อง เพราะยังไม่มีใครรับใบเลย
-- ⚠️ `ackById`/`ackByName` ยกจาก **คนที่กดรับเรื่องที่ใบ** ไม่ใช่เดาเป็น null —
--    ป้าย "ใครรับเรื่อง" บนแถวต้องตรงกับหัวใบ ไม่งั้นสองที่พูดคนละคน
-- ⚠️ วันที่ใช้ `acknowledgedAt` แปลงเป็น **วันไทย** ก่อนตัดเวลา — ใบที่ถูกกดรับ
--    ระหว่างเที่ยงคืนถึง 07:00 น. ของไทย มี UTC เป็นเมื่อวาน (กติกาเดียวกับ
--    `businessDate()` ฝั่ง JS · ดู 0279 ที่ใช้เหตุผลเดียวกันกับเดือน Actual)

UPDATE dept_request_items i
SET "ackAt"     = (r."acknowledgedAt" AT TIME ZONE 'Asia/Bangkok')::date,
    "ackById"   = COALESCE(i."ackById",   r."acknowledgedById"),
    "ackByName" = COALESCE(i."ackByName", r."acknowledgedByName")
FROM dept_requests r
WHERE i."requestId" = r.id
  AND i."ackAt" IS NULL
  AND r."acknowledgedAt" IS NOT NULL
  AND r.status IN ('acknowledged', 'answered', 'closed');

-- ⚠️ ใบที่ **ยกเลิก** ไม่อยู่ในลิสต์โดยตั้งใจ — งานของมันไม่ได้เดินต่อ การเติมวัน
--    รับเรื่องให้แถวจะทำให้รายงาน lead time นับใบที่ไม่มีใครทำเป็นงานที่เริ่มแล้ว
