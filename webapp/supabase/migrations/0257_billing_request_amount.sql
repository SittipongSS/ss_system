-- ══════════════════════════════════════════════════════════════════════
--  0257: ยอดที่ขอวางบิลบนคำร้องขอเอกสารการเงิน (B-2 · ม-ค)
--
--  มติผู้ใช้ 2026-08-15: *"การขอเอกสาร ขอจาก QT"* — คำร้อง `billing_doc` ยึด
--  ใบเสนอราคาเป็นต้นทาง และยอดที่ขอคิดจากยอดของใบนั้น
--
--  ที่มาของรูปนี้คือข้อความจริงที่ทีมส่งกันในแชท (docs/service-business-system-plan.md §5):
--      ใบเสนอราคา :  Q#260731-0006
--      ยอดเต็ม =  181,016.25 บาท
--      ยอด 50 % ก่อนผลิต = 90,508.125 บาท
--
--  ── ทำไมอยู่ที่ "ใบ" ไม่ใช่ "บรรทัด" ───────────────────────────────────
--  บรรทัดของคำร้องนี้คือ **เอกสารที่ขอ** (ใบวางบิล · ใบกำกับภาษี · ใบเสร็จ) ซึ่งของจริง
--  ขอหลายใบต่อ **ยอดก้อนเดียว** — ข้อความข้างบนขอทั้งใบวางบิลและใบกำกับภาษีบนยอด
--  50% ก้อนเดียวกัน ⇒ ยอดเป็นคุณสมบัติของ *การวางบิลรอบนั้น* ไม่ใช่ของเอกสารแต่ละใบ
--  ⚠️ เก็บรายบรรทัดเมื่อไร จะมีสองแหล่งที่ตอบ "ขอเท่าไร" แล้วเพี้ยนกันทันทีที่มีคน
--     แก้บรรทัดใดบรรทัดหนึ่ง
--
--  ── ทำไมเก็บสามค่า ไม่ใช่ค่าเดียว ─────────────────────────────────────
--  `billAmount` อย่างเดียวแปลว่าวันหลังไม่มีใครตอบได้ว่า 90,508.125 มาจาก 50% ของอะไร
--  และใบเสนอราคาแก้ทีหลังได้ (revision) ⇒ **ฐานต้องเป็น snapshot** ไม่ใช่อ่านสดจากใบ
--  (โรคเดียวกับที่ 0245 เขียนไว้เรื่อง snapshot ยอดตอนอนุมัติ)
--
--  ⚠️ **ไม่มี CHECK ผูกสามค่าเข้าหากัน** — ความสัมพันธ์ `amount = base × percent / 100`
--  เป็นจริงตอนกรอก แต่เศษทศนิยมทำให้ CHECK แบบเท่ากันเป๊ะล้มโดยไม่มีเหตุผลทางธุรกิจ
--  · ตัวคำนวณอยู่ที่ `lib/requests/billingQuotations.js` ที่เดียว มีเทสต์คุม
--
--  ⚠️ **ไม่ปัดเศษ** — 181,016.25 × 50% = 90,508.125 คือเลขที่คุยกับลูกค้าจริง
--  numeric เก็บได้ครบ · การปัดเป็นเรื่องของบัญชีตอนออกเอกสาร ไม่ใช่ของที่เก็บ
--
--  🛑 รันล่วงหน้าได้ทันที — คอลัมน์ใหม่เป็น NULL ได้ทั้งหมด โค้ดเก่าไม่รู้จักและไม่แตะ
--  ⚠ รันมือบน Supabase SQL Editor · รันซ้ำได้ · ไม่แตะข้อมูลเดิม
-- ══════════════════════════════════════════════════════════════════════

BEGIN;

ALTER TABLE public.dept_requests
  -- สัดส่วนที่ขอ (0 < percent <= 100) — ว่างได้เมื่อผู้ใช้กรอกเป็นจำนวนเงินตรง ๆ
  -- แล้วยอดใบเป็นศูนย์จนคิด % กลับไม่ได้ (ด่านกันไว้แล้ว แต่คอลัมน์ไม่ควรบังคับ)
  ADD COLUMN IF NOT EXISTS "billPercent"    numeric
    CHECK ("billPercent" IS NULL OR ("billPercent" > 0 AND "billPercent" <= 100)),
  -- ยอดที่ขอจริง — ค่าที่บัญชีเอาไปออกเอกสาร
  ADD COLUMN IF NOT EXISTS "billAmount"     numeric
    CHECK ("billAmount" IS NULL OR "billAmount" > 0),
  -- ยอดของใบเสนอราคา ณ ตอนเปิดคำร้อง — snapshot ห้ามอ่านสดจากใบ
  ADD COLUMN IF NOT EXISTS "billBaseAmount" numeric
    CHECK ("billBaseAmount" IS NULL OR "billBaseAmount" >= 0);

COMMENT ON COLUMN public.dept_requests."billPercent"
  IS 'สัดส่วนที่ขอวางบิล เทียบกับยอดใบเสนอราคา (%) · B-2 · ม-ค';
COMMENT ON COLUMN public.dept_requests."billAmount"
  IS 'ยอดที่ขอวางบิล (บาท) — ไม่ปัดเศษ · B-2 · ม-ค';
COMMENT ON COLUMN public.dept_requests."billBaseAmount"
  IS 'ยอดใบเสนอราคา ณ ตอนเปิดคำร้อง — snapshot ของฐานที่ใช้คิด % · B-2 · ม-ค';

COMMIT;
